#Requires -Version 5.1
<#
.SYNOPSIS
    Restarts the PC with a visible countdown: now, at a set time, or only when a restart is pending.

.DESCRIPTION
    THIS SCRIPT CHANGES THINGS. It schedules a Windows restart with
    shutdown.exe /r /t <seconds> /c "<message>". Windows shows the message and
    a countdown to anyone signed in, so nobody is restarted without warning.
    It never signs anybody out by itself before the countdown ends, and it
    changes nothing else: no settings, no files, no services.

    When decides whether to restart:
      * IfPending (default) restarts only when Windows says a restart is
        pending: component servicing (CBS), Windows Update, the Configuration
        Manager client (only when installed) or a pending computer rename.
        Queued file renames alone do not count (antivirus and drivers leave
        them set on healthy PCs).
      * Now restarts after DelaySeconds.
      * At restarts at the next HH:mm (24-hour, local time): today if that
        time is still ahead, otherwise tomorrow. DelaySeconds is ignored.

    SkipIfUserActive (default true): when somebody is signed in and the
    session is Active (not locked, not disconnected), nothing is scheduled and
    the run ends SKIPPED with "user active". When=At ignores it, because the
    restart happens later, when the countdown warns whoever is there then.
    Windows closes apps without asking when the countdown ends, so unsaved
    work can be lost: keep SkipIfUserActive on unless you mean it.

    Servers: the script does not restart a server or domain controller unless
    AllowServers is true.

    CancelPending=true cancels a scheduled restart (shutdown.exe /a) and does
    nothing else. If a restart is already scheduled, running it again says OK
    and leaves that restart alone.

    The script cannot see a restart that somebody else scheduled, except that
    Windows refuses a second one: that case ends OK "already scheduled".

    This is a High-risk Action: it is a dry run until DryRun=false and
    Approve=restart-computer are both set. Reboot: the PC restarts when the
    countdown ends, unless cancelled.

.PARAMETER When
    IfPending (default), Now or At. Environment variable: When

.PARAMETER At
    Time of day for When=At, HH:mm, 24-hour, local (for example 02:30).
    Environment variable: At

.PARAMETER DelaySeconds
    Countdown before a restart for When=Now or IfPending. Whole number, 0 to
    86400. Default 300. Environment variable: DelaySeconds

.PARAMETER Message
    Text Windows shows to signed-in users, up to 512 characters, no double
    quotes. Environment variable: Message

.PARAMETER SkipIfUserActive
    true (default) to skip when a user is signed in and active. When=At
    ignores it. Environment variable: SkipIfUserActive

.PARAMETER AllowServers
    true to allow a restart on a server or domain controller. Default false.
    Environment variable: AllowServers

.PARAMETER CancelPending
    true to cancel a scheduled restart and do nothing else. Default false.
    Environment variable: CancelPending

.PARAMETER DryRun
    true to list what would be scheduled and schedule nothing. High-risk
    scripts default to a dry run. -WhatIf does the same. Environment variable: DryRun

.PARAMETER OutputFormat
    Text (default), Answer, Json or Csv. Environment variable: OutputFormat

.PARAMETER ExportPath
    Also write the rows to this .csv or .json file. Environment variable: ExportPath

.PARAMETER ResultField
    Also write the answer to this RMM custom field. Environment variable: ResultField

.EXAMPLE
    .\restart-computer.ps1 -When IfPending -DelaySeconds 600 -DryRun false -Approve restart-computer

    Restarts in 10 minutes if Windows is waiting for a restart and nobody is using the PC.

.EXAMPLE
    .\restart-computer.ps1 -When At -At 02:30 -DryRun false -Approve restart-computer

    Schedules a restart for 02:30 (tonight, or tomorrow if 02:30 has passed).

.EXAMPLE
    .\restart-computer.ps1 -CancelPending true -DryRun false -Approve restart-computer

    Cancels a restart scheduled earlier.

