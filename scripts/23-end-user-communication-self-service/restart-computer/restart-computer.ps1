# ---- Constants ------------------------------------------------------------
$CbsKey = 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Component Based Servicing\RebootPending'
$WindowsUpdateKey = 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\WindowsUpdate\Auto Update\RebootRequired'
$ActiveNameKey = 'HKLM:\SYSTEM\CurrentControlSet\Control\ComputerName\ActiveComputerName'
$PendingNameKey = 'HKLM:\SYSTEM\CurrentControlSet\Control\ComputerName\ComputerName'
$ConfigMgrService = 'CcmExec'
$LockScreenProcess = 'LogonUI'
$ShutdownNoneInProgress = 1116
$ShutdownAlreadyScheduled = 1190
$MaxMessageLength = 512
$SentinelNone = 'OUTPOST-NONE-SCHEDULED'
$SentinelScheduled = 'OUTPOST-ALREADY-SCHEDULED'

# ---- Functions ------------------------------------------------------------
function Get-RegistryValueOrNull {
    param([string] $Key, [string] $Name)
    $item = Get-ItemProperty -LiteralPath $Key -ErrorAction SilentlyContinue
    if ($null -eq $item) { return $null }
    $property = $item.PSObject.Properties[$Name]
    if ($null -eq $property) { return $null }
    return $property.Value
}

function Get-SystemFile {
    param([string] $Name)
    $folder = [Environment]::GetFolderPath('System')
    if (-not $folder) { $folder = 'C:\Windows\System32' }
    return (Join-Path -Path $folder -ChildPath $Name)
}

function Get-PendingRestartReason {
    # The same sources as test-pending-reboot, except queued file renames.
    $reasons = New-Object -TypeName System.Collections.ArrayList
    if (Test-Path -LiteralPath $CbsKey) { [void]$reasons.Add('Windows servicing') }
    if (Test-Path -LiteralPath $WindowsUpdateKey) { [void]$reasons.Add('Windows Update') }
    if (Get-Service -Name $ConfigMgrService -ErrorAction SilentlyContinue) {
        try {
            $ccm = Invoke-CimMethod -Namespace 'root/ccm/ClientSDK' -ClassName 'CCM_ClientUtilities' -MethodName 'DetermineIfRebootPending'
            if ($ccm.RebootPending -or $ccm.IsHardRebootPending) { [void]$reasons.Add('Configuration Manager') }
        }
        catch {
            Write-OutpostWarning -Text "Configuration Manager client is installed but did not answer: $($_.Exception.Message)"
        }
    }
    $activeName = Get-RegistryValueOrNull -Key $ActiveNameKey -Name 'ComputerName'
    $newName = Get-RegistryValueOrNull -Key $PendingNameKey -Name 'ComputerName'
    if (($null -ne $activeName) -and ($null -ne $newName) -and ($activeName -ne $newName)) { [void]$reasons.Add('computer rename') }
    return @($reasons)
}

function Get-ActiveSessionUser {
    # User names of sessions that are Active (WTS state 0) and not locked (no LogonUI
    # in that session). Disconnected and idle sessions do not count. Throws when the
    # session list cannot be read.
    if (-not ('OutpostWts' -as [type])) {
        $source = @'
using System;
using System.Runtime.InteropServices;
using System.Text;
public static class OutpostWts {
    [StructLayout(LayoutKind.Sequential)]
    private struct SessionInfo { public int SessionId; public IntPtr WinStationName; public int State; }
    [DllImport("wtsapi32.dll", SetLastError = true)]
    private static extern bool WTSEnumerateSessions(IntPtr server, int reserved, int version, out IntPtr info, out int count);
    [DllImport("wtsapi32.dll")]
    private static extern void WTSFreeMemory(IntPtr memory);
    [DllImport("wtsapi32.dll", EntryPoint = "WTSQuerySessionInformationW", CharSet = CharSet.Unicode, SetLastError = true)]
    private static extern bool WTSQuerySessionInformation(IntPtr server, int sessionId, int infoClass, out IntPtr buffer, out int bytes);
    public static string Sessions() {
        IntPtr info; int count;
        if (!WTSEnumerateSessions(IntPtr.Zero, 0, 1, out info, out count)) {
            throw new System.ComponentModel.Win32Exception(Marshal.GetLastWin32Error());
        }
        StringBuilder text = new StringBuilder();
        try {
            int size = Marshal.SizeOf(typeof(SessionInfo));
            for (int i = 0; i < count; i++) {
                SessionInfo item = (SessionInfo)Marshal.PtrToStructure(new IntPtr(info.ToInt64() + (long)i * size), typeof(SessionInfo));
                text.Append(item.SessionId).Append(':').Append(item.State).Append(':').Append(UserName(item.SessionId)).Append(';');
            }
        }
        finally { WTSFreeMemory(info); }
        return text.ToString();
    }
    private static string UserName(int sessionId) {
        IntPtr buffer; int bytes;
        if (!WTSQuerySessionInformation(IntPtr.Zero, sessionId, 5, out buffer, out bytes)) { return ""; }
        try { return Marshal.PtrToStringUni(buffer); }
        finally { WTSFreeMemory(buffer); }
    }
}
'@
        Add-Type -TypeDefinition $source
    }
    $lockedSessions = @(Get-Process -Name $LockScreenProcess -ErrorAction SilentlyContinue | ForEach-Object { [int]$_.SessionId })
    $users = New-Object -TypeName System.Collections.ArrayList
    foreach ($entry in ([OutpostWts]::Sessions() -split ';')) {
        $parts = $entry -split ':'
        if ($parts.Count -lt 3) { continue }
        $sessionId = [int]$parts[0]
        $state = [int]$parts[1]
        if ($state -eq 0 -and $parts[2] -ne '' -and $lockedSessions -notcontains $sessionId) { [void]$users.Add(($parts[2] -replace '[^\x20-\x7E]', '?')) }
    }
    return @($users)
}

function Invoke-Shutdown {
    # Runs shutdown.exe and returns its exit code. Its messages go to the void: only
    # the code (documented, not localised) is trusted.
    param([string[]] $ShutdownArgument)
    $previous = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        $null = & (Get-SystemFile -Name 'shutdown.exe') @ShutdownArgument 2>&1
        return [int]$LASTEXITCODE
    }
    finally { $ErrorActionPreference = $previous }
}

function Format-WaitText {
    param([double] $Seconds)
    if ($Seconds -lt 120) { return ('{0} seconds' -f [math]::Round($Seconds)) }
    if ($Seconds -lt 7200) { return ('{0} minutes' -f [math]::Round($Seconds / 60)) }
    return ('{0} hours' -f [math]::Round($Seconds / 3600))
}

# ---- Main -----------------------------------------------------------------
Start-OutpostRun
try {
    # Validate
    $Config = [pscustomobject]@{
        When             = Read-OutpostChoice -Name 'When' -Allowed @('Now', 'IfPending', 'At')
        At               = Read-OutpostText -Name 'At'
        DelaySeconds     = Read-OutpostInt -Name 'DelaySeconds' -Min 0 -Max 86400
        Message          = Read-OutpostText -Name 'Message'
        SkipIfUserActive = Read-OutpostBool -Name 'SkipIfUserActive'
        AllowServers     = Read-OutpostBool -Name 'AllowServers'
        CancelPending    = Read-OutpostBool -Name 'CancelPending'
    }
    $clock = [datetime]::MinValue
    if ($Config.When -eq 'At') {
        if ($Config.At -eq '') { Stop-OutpostRun -Message 'When is At but At is not set. Set At to a time like 02:30 (24-hour, local), or choose When Now or IfPending.' }
        if (-not [datetime]::TryParseExact($Config.At, 'HH:mm', [Globalization.CultureInfo]::InvariantCulture, [Globalization.DateTimeStyles]::None, [ref]$clock)) {
            Stop-OutpostInput -Name 'At' -Value $Config.At -Expected 'a time like 02:30 (HH:mm, 24-hour, local)'
        }
    }
    if ($Config.Message.Length -gt $MaxMessageLength -or $Config.Message.Contains('"')) {
        Stop-OutpostInput -Name 'Message' -Value $Config.Message -Expected "text up to $MaxMessageLength characters with no double quotes"
    }
    if (-not (Test-OutpostAdmin)) {
        Stop-OutpostRun -Message 'This script needs administrator rights. Run it as SYSTEM from your RMM or from an elevated PowerShell.'
    }
    $computerName = [Environment]::MachineName

    # CancelPending does nothing but cancel.
    if ($Config.CancelPending) {
        $noneScheduled = $false
        try {
            $null = Invoke-OutpostChange -Item $computerName -Change 'Cancel the scheduled restart (shutdown /a)' -Action {
                $exitCode = Invoke-Shutdown -ShutdownArgument @('/a')
                if ($exitCode -eq $ShutdownNoneInProgress) { throw $SentinelNone }
                if ($exitCode -ne 0) { throw "shutdown.exe /a failed with exit code $exitCode." }
            }
        }
        catch {
            if ($_.Exception.Message -ne $SentinelNone) { throw }
            $noneScheduled = $true
        }
        if ($noneScheduled) { Complete-OutpostRun -Status 'OK' -Answer 'No restart was scheduled; nothing to cancel' }
        Complete-OutpostRun -Status 'CHANGED' -Answer 'Cancelled the scheduled restart'
    }

    # Detect
    $operatingSystem = Get-CimInstance -ClassName Win32_OperatingSystem
    $computerSystem = Get-CimInstance -ClassName Win32_ComputerSystem
    $isDomainController = [int]$computerSystem.DomainRole -ge 4
    $isServer = [int]$operatingSystem.ProductType -ne 1
    if ($isServer -and -not $Config.AllowServers) {
        $kind = if ($isDomainController) { 'a domain controller' } else { 'a server' }
        Complete-OutpostRun -Status 'SKIPPED' -Answer "Skipped: this is $kind; set AllowServers=true to allow a restart here."
    }

    $reasonText = ''
    if ($Config.When -eq 'IfPending') {
        $reasons = @(Get-PendingRestartReason)
        if ($reasons.Count -eq 0) { Complete-OutpostRun -Status 'OK' -Answer 'No restart is pending; not restarting' }
        $reasonText = '; pending: ' + ($reasons -join ', ')
    }

    $waitSeconds = $Config.DelaySeconds
    if ($Config.When -eq 'At') {
        $target = [datetime]::Today.Add($clock.TimeOfDay)
        if ($target -le (Get-Date).AddSeconds(30)) { $target = $target.AddDays(1) }
        $waitSeconds = [int][math]::Ceiling(($target - (Get-Date)).TotalSeconds)
    }

    if ($Config.SkipIfUserActive -and $Config.When -ne 'At') {
        try {
            $activeUsers = @(Get-ActiveSessionUser)
        }
        catch {
            # Cannot tell: be safe, treat a signed-in user as active.
            Write-OutpostWarning -Text "Could not read the session list ($($_.Exception.Message)); treating a signed-in user as active."
            $signedIn = Get-OutpostSignedInUser
            $activeUsers = if ($signedIn) { @($signedIn) } else { @() }
        }
        if ($activeUsers.Count -gt 0) {
            Complete-OutpostRun -Status 'SKIPPED' -Answer ('Skipped: user active ({0}); no restart scheduled. Run again later or set SkipIfUserActive=false.' -f ($activeUsers -join ', '))
        }
    }
    elseif (-not $Config.SkipIfUserActive) {
        $signedInNow = Get-OutpostSignedInUser
        if ($signedInNow) { Write-OutpostWarning -Text "$signedInNow is signed in; they will get the Windows warning and the restart will close their apps." }
    }

    # Act
    Assert-OutpostChangeLimit -Planned 1
    $restartTime = [DateTimeOffset]::Now.AddSeconds($waitSeconds).ToString('yyyy-MM-dd HH:mm zzz', [Globalization.CultureInfo]::InvariantCulture)
    $waitText = Format-WaitText -Seconds $waitSeconds
    $alreadyScheduled = $false
    try {
        $null = Invoke-OutpostChange -Item $computerName -Change "Schedule a restart for $restartTime (in $waitText)" -Action {
            $exitCode = Invoke-Shutdown -ShutdownArgument @('/r', '/t', [string]$waitSeconds, '/c', $Config.Message)
            if ($exitCode -eq $ShutdownAlreadyScheduled) { throw $SentinelScheduled }
            if ($exitCode -ne 0) { throw "shutdown.exe could not schedule the restart (exit code $exitCode)." }
        }
    }
    catch {
        if ($_.Exception.Message -ne $SentinelScheduled) { throw }
        $alreadyScheduled = $true
    }

    # Finish
    if ($alreadyScheduled) {
        Complete-OutpostRun -Status 'OK' -Answer 'A restart is already scheduled; left as it is. Use CancelPending=true to cancel it first.'
    }
    Complete-OutpostRun -Status 'CHANGED' -Answer "Restart scheduled for $restartTime (in $waitText)$reasonText; signed-in users see the Windows warning"
}
catch {
    Stop-OutpostRun -ErrorRecord $_
}
