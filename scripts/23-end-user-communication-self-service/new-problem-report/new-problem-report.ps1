# ---- Constants ------------------------------------------------------------
$MaxDescriptionLength = 500
$MaxEvents = 50
$MaxEventTextLength = 300
$NoDescriptionText = '(no description given)'
$ReportFolderName = 'ProblemReports'
$ReportFilePattern = 'problem-report-*.zip'
$BytesPerGB = 1073741824

# ---- Functions ------------------------------------------------------------
function Format-UtcText {
    param([DateTime] $Time)
    return $Time.ToUniversalTime().ToString("yyyy-MM-dd'T'HH:mm:ss'Z'", [Globalization.CultureInfo]::InvariantCulture)
}

function New-PrivateFolder {
    # A folder only SYSTEM and administrators can use: a report holds diagnostics.
    param([Parameter(Mandatory = $true)][string] $Path)
    $null = New-Item -Path $Path -ItemType Directory -Force
    $system = New-Object -TypeName Security.Principal.SecurityIdentifier -ArgumentList 'S-1-5-18'
    $admins = New-Object -TypeName Security.Principal.SecurityIdentifier -ArgumentList 'S-1-5-32-544'
    $inherit = [Security.AccessControl.InheritanceFlags]'ContainerInherit, ObjectInherit'
    $none = [Security.AccessControl.PropagationFlags]::None
    $security = New-Object -TypeName Security.AccessControl.DirectorySecurity
    $security.SetOwner($admins)
    $security.SetAccessRuleProtection($true, $false)
    $security.AddAccessRule((New-Object -TypeName Security.AccessControl.FileSystemAccessRule -ArgumentList $system, 'FullControl', $inherit, $none, 'Allow'))
    $security.AddAccessRule((New-Object -TypeName Security.AccessControl.FileSystemAccessRule -ArgumentList $admins, 'FullControl', $inherit, $none, 'Allow'))
    Set-Acl -LiteralPath $Path -AclObject $security
}

function Get-RecentAppError {
    # Error and Critical events of the Application log since $Since. No events is not an error.
    param([DateTime] $Since)
    try {
        return @(Get-WinEvent -FilterHashtable @{ LogName = 'Application'; Level = @(1, 2); StartTime = $Since } -MaxEvents $MaxEvents -ErrorAction Stop)
    }
    catch {
        if ($_.FullyQualifiedErrorId -like 'NoMatchingEventsFound*') { return @() }
        Write-OutpostWarning -Text "Could not read the Application event log: $($_.Exception.Message)"
        return @()
    }
}

function Get-ReportLine {
    # The text of report.txt.
    param([string] $DescriptionText, [string] $Account, [int] $Minutes, $Events)
    $os = Get-CimInstance -ClassName Win32_OperatingSystem
    $addresses = @()
    foreach ($adapter in @(Get-CimInstance -ClassName Win32_NetworkAdapterConfiguration -Filter 'IPEnabled = TRUE')) {
        foreach ($address in @($adapter.IPAddress)) { if ([string]$address -match '^\d{1,3}(\.\d{1,3}){3}$') { $addresses += [string]$address } }
    }
    $systemDrive = (Split-Path -Path ([Environment]::GetFolderPath('Windows')) -Qualifier).ToUpperInvariant()
    $diskText = 'unknown'
    $disk = Get-CimInstance -ClassName Win32_LogicalDisk -Filter "DeviceID = '$systemDrive'" -ErrorAction SilentlyContinue
    if ($null -ne $disk -and [double]$disk.Size -gt 0) {
        $diskText = ('{0} free of {1} GB ({2}%)' -f [math]::Round([double]$disk.FreeSpace / $BytesPerGB, 1), [math]::Round([double]$disk.Size / $BytesPerGB, 0), [math]::Round(([double]$disk.FreeSpace / [double]$disk.Size) * 100, 0))
    }
    $uptimeDays = [math]::Round(((Get-Date) - $os.LastBootUpTime).TotalDays, 1)
    $lines = New-Object -TypeName System.Collections.ArrayList
    [void]$lines.Add('Problem report')
    [void]$lines.Add('Created (UTC):  ' + (Format-UtcText -Time ([DateTime]::UtcNow)))
    [void]$lines.Add('Description:    ' + $DescriptionText)
    [void]$lines.Add('Computer:       ' + [Environment]::MachineName)
    [void]$lines.Add('User:           ' + $Account)
    [void]$lines.Add('Windows:        ' + ([string]$os.Caption).Trim() + ' (build ' + [string]$os.BuildNumber + ')')
    [void]$lines.Add('IPv4 addresses: ' + $(if ($addresses.Count -gt 0) { $addresses -join ', ' } else { 'none' }))
    [void]$lines.Add('Uptime (days):  ' + $uptimeDays)
    [void]$lines.Add("Disk $($systemDrive):         " + $diskText)
    [void]$lines.Add('')
    [void]$lines.Add("Application log errors in the last $Minutes minute(s): $(@($Events).Count)")
    foreach ($entry in @($Events)) {
        $text = [string]$entry.Message
        $text = ($text -replace '\s+', ' ').Trim()
        if ($text.Length -gt $MaxEventTextLength) { $text = $text.Substring(0, $MaxEventTextLength) + '...' }
        [void]$lines.Add(('{0}  id {1}  {2}  {3}' -f (Format-UtcText -Time $entry.TimeCreated), $entry.Id, $entry.ProviderName, $text))
    }
    return $lines
}

function Send-ReportZip {
    # One POST of the zip; the address is a secret and is never put in a message.
    param([string] $Url, [string] $ZipPath)
    try {
        $response = Invoke-WebRequest -Uri $Url -Method Post -InFile $ZipPath -ContentType 'application/zip' -UseBasicParsing
        $code = [int]$response.StatusCode
    }
    catch {
        $text = ([string]$_.Exception.Message).Replace($Url, '[webhook address]')
        throw "Sending the report to the webhook failed: $text"
    }
    if ($code -lt 200 -or $code -gt 299) { throw "The webhook answered HTTP $code instead of 2xx." }
}

# ---- Main -----------------------------------------------------------------
Start-OutpostRun
try {
    # Validate
    $Config = [pscustomobject]@{
        Description       = Read-OutpostText -Name 'Description'
        EventMinutes      = Read-OutpostInt -Name 'EventMinutes' -Min 1 -Max 1440
        KeepDays          = Read-OutpostInt -Name 'KeepDays' -Min 1 -Max 3650
    }
    if ($Config.Description.Length -gt $MaxDescriptionLength) {
        Stop-OutpostInput -Name 'Description' -Value ($Config.Description.Substring(0, 40) + '...') -Expected "at most $MaxDescriptionLength characters (it has $($Config.Description.Length))"
    }
    $descriptionText = ($Config.Description -replace '[\x00-\x1F]+', ' ').Trim()
    if ($descriptionText -eq '') { $descriptionText = $NoDescriptionText }
    $webhookAddress = [string](Read-OutpostSecret -Name 'ProblemReportWebhook')
    if ($webhookAddress -ne '' -and $webhookAddress -notmatch '^https://\S+$') {
        Stop-OutpostRun -Message 'The secure environment variable ProblemReportWebhook must be an https:// address with no spaces. Correct it (its value is not shown here) or clear it.'
    }
    if (-not (Test-OutpostAdmin)) {
        Stop-OutpostRun -Message 'This script needs administrator rights. Run it as SYSTEM from your RMM or from an elevated PowerShell.'
    }
    $account = Get-OutpostSignedInUser
    if (-not $account) {
        Complete-OutpostRun -Status 'SKIPPED' -Answer 'Skipped: nobody is signed in, so there is no user to report a problem for.'
    }

    # Detect
    Write-OutpostLine -Text "Problem report for $account on $([Environment]::MachineName): reading errors from the last $($Config.EventMinutes) minute(s)."
    $events = @(Get-RecentAppError -Since ((Get-Date).AddMinutes(-$Config.EventMinutes)))
    $reportsRoot = Join-Path -Path (Get-OutpostDataFolder) -ChildPath $ReportFolderName
    $stamp = [DateTime]::UtcNow.ToString('yyyyMMdd-HHmmss', [Globalization.CultureInfo]::InvariantCulture)
    $safeComputer = ([Environment]::MachineName -replace '[^A-Za-z0-9-]', '')
    $zipPath = Join-Path -Path $reportsRoot -ChildPath ("problem-report-$safeComputer-$stamp.zip")
    $workFolder = Join-Path -Path $reportsRoot -ChildPath ('work-' + [Guid]::NewGuid().ToString('N'))
    $sent = $false

    # Act
    $null = Invoke-OutpostChange -Item $zipPath -Change 'Create the problem report zip (diagnostics and description)' -Action {
        New-PrivateFolder -Path $reportsRoot
        New-PrivateFolder -Path $workFolder
        try {
            $reportFile = Join-Path -Path $workFolder -ChildPath 'report.txt'
            Set-Content -LiteralPath $reportFile -Value (Get-ReportLine -DescriptionText $descriptionText -Account $account -Minutes $Config.EventMinutes -Events $events) -Encoding UTF8
            Compress-Archive -Path (Join-Path -Path $workFolder -ChildPath '*') -DestinationPath $zipPath -Force
        }
        finally {
            Remove-Item -LiteralPath $workFolder -Recurse -Force -ErrorAction SilentlyContinue
        }
    }
    if ($webhookAddress -ne '') {
        $sent = Invoke-OutpostChange -Item 'ProblemReportWebhook' -Change 'Send the zip to the webhook (one POST)' -Action {
            Send-ReportZip -Url $webhookAddress -ZipPath $zipPath
        }
    }
    if (Test-Path -LiteralPath $reportsRoot) {
        $cutoff = (Get-Date).AddDays(-$Config.KeepDays)
        foreach ($old in @(Get-ChildItem -LiteralPath $reportsRoot -Filter $ReportFilePattern -File -ErrorAction SilentlyContinue | Where-Object { $_.LastWriteTime -lt $cutoff })) {
            $oldFile = $old.FullName
            $null = Invoke-OutpostChange -Item $old.Name -Change "Delete a report older than $($Config.KeepDays) days" -Action {
                Remove-Item -LiteralPath $oldFile -Force
            }
        }
    }

    # Verify (a dry run made nothing)
    if (-not $script:OutpostRun.DryRun) {
        if (-not (Test-Path -LiteralPath $zipPath) -or (Get-Item -LiteralPath $zipPath).Length -le 0) {
            Stop-OutpostRun -Message "The report zip was not created at $zipPath. Check free disk space and that Compress-Archive works."
        }
    }

    # Finish
    $sentText = $(if ($sent) { '; sent to the webhook' } elseif ($webhookAddress -ne '') { '' } else { '; no webhook set' })
    Complete-OutpostRun -Status 'CHANGED' -Answer ("Problem report " + (Split-Path -Path $zipPath -Leaf) + " saved ($($events.Count) app error(s))" + $sentText)
}
catch {
    Stop-OutpostRun -ErrorRecord $_
}
