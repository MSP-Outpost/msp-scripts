#Requires -Version 5.1
<#
.SYNOPSIS
    Collects a "something is wrong" report from the signed-in user's PC: basic diagnostics and a description, zipped and optionally sent to your webhook.
.DESCRIPTION
    THIS SCRIPT CHANGES THINGS (it writes a report file and may send it). In order it:
      * reads diagnostics as SYSTEM: computer name, signed-in user, Windows
        version, IPv4 addresses, uptime, free space on the system drive, and the
        Error and Critical events of the Application log from the last
        EventMinutes minutes (at most 50, each cut to 300 characters);
      * writes report.txt (the description and the diagnostics) into one zip under %ProgramData%\MSPOutpost\ProblemReports,
        a folder only SYSTEM and administrators can read, and deletes zips there
        older than KeepDays;
      * when the secure environment variable ProblemReportWebhook holds an
        https:// address, sends the zip to it as one HTTP POST with the content
        type application/zip and checks for a 2xx answer.

    No dialog is shown. The library standard forbids prompts and message boxes in
    a script, and Microsoft's documentation does not establish that a window
    opened from a one-shot task in the user's session is safe to wait on, so the
    one-line description comes from the Description input: let your RMM, your
    shortcut or your help desk fill it in.

    It takes NO screenshot. Screen-capture code in a PowerShell script is
    detected by Microsoft Defender as a hack tool (on 2026-11-18 Defender
    named this script's first version HackTool:PowerShell/EmpireGetScreenshot.C
    and blocked the whole script), so ask the user to attach a picture to the
    ticket instead (Windows key + Shift + S).

    With a webhook the zip leaves the PC; the
    webhook address is a secret and is never printed. The description is placed
    in report.txt only, not in the web address. The webhook must accept a raw
    application/zip body (a plain HTTPS endpoint you control or a custom
    automation trigger). Not confirmed against any ticketing product: Slack,
    Teams and most PSA "email in" or "webhook" doors do not take a file this
    way, so put a small receiver in front of them.

    Where each fact comes from: Get-WinEvent -FilterHashtable with the keys
    LogName, Level (1 Critical, 2 Error) and StartTime, and -MaxEvents; Win32_OperatingSystem,
    Win32_NetworkAdapterConfiguration and Win32_LogicalDisk (CIM).
    Not confirmed in the documentation read here, so treated defensively: Compress-Archive behaviour; the error id
    NoMatchingEventsFound that Get-WinEvent raises when no event matches (read as "no events").
.PARAMETER Description
    One line from the user about what is wrong, up to 500 characters. Default empty,
    which is recorded as "(no description given)". Environment variable: Description
.PARAMETER EventMinutes
    How far back to read Application-log errors, in minutes. Whole number, 1 to 1440.
    Default 10. Environment variable: EventMinutes
.PARAMETER KeepDays
    Reports older than this many days are deleted from the ProblemReports folder.
    Whole number, 1 to 3650. Default 30. Environment variable: KeepDays
.PARAMETER DryRun
    true or -WhatIf lists what it would do and does nothing. Default false.
.PARAMETER OutputFormat
    Text (default), Answer, Json or Csv. Environment variable: OutputFormat
.PARAMETER ExportPath
    Also write the rows to this .csv or .json file. Environment variable: ExportPath
.PARAMETER ResultField
    Also write the answer to this RMM custom field. Environment variable: ResultField
.EXAMPLE
    .\new-problem-report.ps1 -Description "Outlook closes when I open a PDF"
    Saves a report zip for the signed-in user's PC.
.EXAMPLE
    .\new-problem-report.ps1 -EventMinutes 60 -OutputFormat Json
    A report with an hour of errors, as JSON.
