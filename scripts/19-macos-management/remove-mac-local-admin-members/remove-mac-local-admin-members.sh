#!/bin/bash
# ---------------------------------------------------------------------------
# SYNOPSIS:    Demotes every administrator on a Mac who is not on your approved list to a standard user.
# DESCRIPTION:
#   THIS SCRIPT CHANGES THINGS. Risk is High, so it is a dry run unless you set
#   BOTH DRY_RUN=false AND APPROVE=remove-mac-local-admin-members (typing the
#   script name is the deliberate step), and it refuses to demote more
#   accounts than MAX_CHANGES (default 25) in one run. Look at the dry-run
#   list first, then run it for real.
#   It reads the members of the local admin group and removes each one that is
#   not in ALLOWED_ADMINS (dseditgroup). The account itself is not deleted, not
#   disabled, not signed out and keeps its files, SecureToken and FileVault
#   unlock rights; it just stops being an administrator. Before changing
#   anything it copies the admin group's directory record
#   (/var/db/dslocal/nodes/Default/groups/admin.plist) to
#   /Library/Application Support/MSPOutpost/Backups/remove-mac-local-admin-members/.
#   Always kept, whatever ALLOWED_ADMINS says: root; accounts with a user ID
#   below 500 (system accounts); and the signed-in console user, unless
#   DEMOTE_CONSOLE_USER is true (signing a person out of their admin rights
#   mid-session is surprising, so it is off by default).
#   The last administrator is never removed: a real run refuses, changing
#   nothing, when no kept administrator with a user ID of 500 or more would
#   remain, so the Mac is never left without one. The dry run only warns.
#   ALLOWED_ADMINS entries are plain account short names, matched ignoring
#   case (no wildcards). An entry that is not an admin on this Mac is only a
#   warning, so one list can serve many Macs.
#   Admin rights that come only from a nested group are not seen.
#   Demoting an account does not touch its SecureToken. A standard user with a
#   SecureToken can still unlock FileVault.
# INPUTS:
#   --allowed-admins LIST       (env ALLOWED_ADMINS)       Account short names that stay admin, comma-separated, e.g. "msp-admin, jsmith". Default empty: only root and the console user stay.
#   --demote-console-user B     (env DEMOTE_CONSOLE_USER)  Also demote the signed-in console user when not approved. Default false.
#   --dry-run B                 (env DRY_RUN)              Default TRUE for this script: lists who would be demoted. Set false AND --approve remove-mac-local-admin-members to act.
#   --output-format F           (env OUTPUT_FORMAT)        Text (default), Answer, Json or Csv.
#   --export-path FILE          (env EXPORT_PATH)          Also write rows to this .csv or .json file.
#   --result-field NAME         (env RESULT_FIELD)         Also write the answer to this RMM custom field.
# EXAMPLE:
#   sudo ./remove-mac-local-admin-members.sh --allowed-admins "msp-admin"
#   sudo ./remove-mac-local-admin-members.sh --allowed-admins "msp-admin" --dry-run=false --approve=remove-mac-local-admin-members
# NOTES:
#   Name:        Unapproved administrators on this Mac - demote them
#   Slug:        remove-mac-local-admin-members
#   Version:     1.0.0
#   Updated:     2026-11-17
#   Type:        Action
#   Category:    19 macOS management
#   Platforms:   macOS 13+
#   RunAs:       System
#   Requires:    bash 3.2, root, dscl, dseditgroup
#   Changes:     Removes accounts from the local admin group (the accounts stay as standard users)
#   Risk:        High
#   Reboot:      Never
#   Runtime:     Under 10 seconds
#   Answer:      "Removed 2 account(s) from the admin group: jsmith, temp1; kept: root, msp-admin"
