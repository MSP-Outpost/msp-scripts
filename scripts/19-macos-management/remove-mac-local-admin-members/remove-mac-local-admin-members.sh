# ---- Inputs: THIS SCRIPT'S defaults. Edit here if your RMM cannot pass variables.
DEFAULT_ALLOWED_ADMINS=""
DEFAULT_DEMOTE_CONSOLE_USER="false"

# ---- Constants ------------------------------------------------------------
readonly ADMIN_GROUP="admin"
readonly ADMIN_GROUP_RECORD="/var/db/dslocal/nodes/Default/groups/admin.plist"
readonly CHANGE_TEXT="Remove from admin group"

# ---- Functions ------------------------------------------------------------
lower() { printf '%s' "$1" | tr 'A-Z' 'a-z'; }

# Prints the short names in the admin group other than root, one per line.
list_admins() {
    dscl . -read "/Groups/$ADMIN_GROUP" GroupMembership 2>/dev/null |
        sed 's/^GroupMembership://' | tr ' ' '\n' | sed '/^$/d' | grep -vx 'root' || true
}

# in_list NAME LIST (newline-separated), ignoring case.
in_list() {
    printf '%s\n' "$2" | tr 'A-Z' 'a-z' | grep -Fxq "$(lower "$1")"
}

demote_user() { dseditgroup -o edit -d "$1" -t user "$ADMIN_GROUP" > /dev/null 2>&1; }

# Prints the numeric user ID of an account, or nothing.
user_id() { dscl . -read "/Users/$1" UniqueID 2>/dev/null | awk '{ print $2 }'; }

# ---- Main -----------------------------------------------------------------
op_start "$@"

# Validate
op_read_list allowed_admins ALLOWED_ADMINS "$DEFAULT_ALLOWED_ADMINS"
op_read_bool demote_console_user DEMOTE_CONSOLE_USER "$DEFAULT_DEMOTE_CONSOLE_USER"
if [ "$OP_OS" != "macOS" ]; then op_finish SKIPPED "Skipped: this script is for macOS."; fi
while IFS= read -r entry; do
    [ -z "$entry" ] && continue
    case "$entry" in
        *[!A-Za-z0-9._-]*) op_fail "Input ALLOWED_ADMINS has '$entry'; expected account short names (letters, digits, . _ -) separated by commas. Fix it and run again." ;;
    esac
done <<EOF
$allowed_admins
EOF
op_is_root || op_fail "This script must run as root to change group membership. Run it with sudo or from your RMM."
command -v dseditgroup >/dev/null 2>&1 || op_fail "dseditgroup is missing, so group membership cannot be changed. This Mac's macOS install looks damaged."

# Detect
op_line "Reading the members of the '$ADMIN_GROUP' group."
members=$(list_admins)
console_user=$(op_signed_in_user)
to_remove=""
kept="root"
kept_real=0
remove_count=0
while IFS= read -r name; do
    [ -z "$name" ] && continue
    uid=$(user_id "$name")
    if in_list "$name" "$allowed_admins"; then
        kept="${kept}, ${name}"
        if [ -n "$uid" ] && [ "$uid" -ge 500 ] 2>/dev/null; then kept_real=$((kept_real + 1)); fi
    elif [ -n "$uid" ] && [ "$uid" -lt 500 ] 2>/dev/null; then
        op_line "Keeping $name: system account (user ID $uid)."
        kept="${kept}, ${name}"
    elif [ -n "$console_user" ] && [ "$(lower "$name")" = "$(lower "$console_user")" ] && [ "$demote_console_user" -eq 0 ]; then
        op_line "Keeping $name: signed in at the console (set DEMOTE_CONSOLE_USER=true to demote)."
        kept="${kept}, ${name}"
        if [ -n "$uid" ] && [ "$uid" -ge 500 ] 2>/dev/null; then kept_real=$((kept_real + 1)); fi
    else
        to_remove="${to_remove}${name}"$'\n'
        remove_count=$((remove_count + 1))
    fi
done <<EOF
$members
EOF
while IFS= read -r entry; do
    [ -z "$entry" ] && continue
    if ! printf '%s\n' "$members" | tr 'A-Z' 'a-z' | grep -Fxq "$(lower "$entry")"; then
        op_warn "Approved account '$entry' is not an administrator on this Mac."
    fi
done <<EOF
$allowed_admins
EOF
op_line "$remove_count unapproved administrator(s) found."
if [ "$remove_count" -eq 0 ]; then op_finish OK "Already compliant: every administrator is approved or protected (${kept})."; fi

# Never leave the Mac without an administrator.
if [ "$kept_real" -eq 0 ]; then
    if [ "$OP_DRY_RUN" -eq 1 ]; then
        op_warn "A real run would stop: no approved or console administrator would remain. Add your management admin to ALLOWED_ADMINS."
    else
        op_fail "Refusing to demote $remove_count account(s): no approved administrator with a user ID of 500 or more would remain on this Mac. Nothing was changed. Add your management admin to ALLOWED_ADMINS, then run again."
    fi
fi

# Act
op_assert_change_limit "$remove_count"
if [ "$OP_DRY_RUN" -eq 0 ]; then
    op_backup "$ADMIN_GROUP_RECORD" > /dev/null
    op_line "Saved the admin group record to $OP_BACKUP_DIR."
fi
while IFS= read -r name; do
    [ -z "$name" ] && continue
    op_change "$name" "$CHANGE_TEXT" demote_user "$name" || true
done <<EOF
$to_remove
EOF

# Verify
if [ "$OP_DRY_RUN" -eq 0 ]; then
    after=$(list_admins)
    while IFS= read -r name; do
        [ -z "$name" ] && continue
        if printf '%s\n' "$after" | grep -Fxq "$name"; then op_fail "$name is still in the admin group after the change. A configuration profile or another tool may be managing it."; fi
    done <<EOF
$to_remove
EOF
fi

# Finish
names=$(printf '%s' "$to_remove" | sed '/^$/d' | tr '\n' ',' | sed 's/,$//;s/,/, /g')
op_finish CHANGED "Removed ${remove_count} account(s) from the admin group: ${names}; kept: ${kept}"
