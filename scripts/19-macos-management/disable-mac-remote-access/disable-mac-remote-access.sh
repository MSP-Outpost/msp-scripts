# ---- Inputs: THIS SCRIPT'S defaults. Edit here if your RMM cannot pass variables.
DEFAULT_DISABLE_REMOTE_LOGIN="true"
DEFAULT_DISABLE_SCREEN_SHARING="true"
DEFAULT_DISABLE_REMOTE_MANAGEMENT="true"

# ---- Constants ------------------------------------------------------------
readonly SSH_JOB="system/com.openssh.sshd"
readonly SCREEN_SHARING_JOB="system/com.apple.screensharing"
readonly KICKSTART="/System/Library/CoreServices/RemoteManagement/ARDAgent.app/Contents/Resources/kickstart"
readonly LAUNCHD_OVERRIDES="/var/db/com.apple.xpc.launchd/disabled.plist"
readonly CHANGE_TEXT="Turn off"

# ---- Functions ------------------------------------------------------------
remote_login_state() {
    local out
    out=$(systemsetup -getremotelogin 2>&1 < /dev/null) || true
    case "$out" in
        *"Remote Login: On"*) printf 'On' ;;
        *"Remote Login: Off"*) printf 'Off' ;;
        *) # systemsetup refused (Full Disk Access) or is missing: ask launchd.
            if launchctl print "$SSH_JOB" > /dev/null 2>&1; then printf 'On'; else printf 'Off'; fi ;;
    esac
}
screen_sharing_state() {
    if launchctl print "$SCREEN_SHARING_JOB" > /dev/null 2>&1; then printf 'On'; else printf 'Off'; fi
}
remote_management_state() {
    local listeners
    if pgrep -x ARDAgent > /dev/null 2>&1; then printf 'On'; return; fi
    listeners=$(netstat -an -p tcp 2>/dev/null) || true
    if grep -Eq '[.]3283[[:space:]].*LISTEN' <<< "$listeners"; then printf 'On'; else printf 'Off'; fi
}

# True when this script is running inside an SSH session (sshd or sshd-session
# anywhere above it): turning Remote Login off would end the run itself.
started_over_ssh() {
    local pid=$$ steps=0 name
    while [ -n "$pid" ] && [ "$pid" -gt 1 ] && [ "$steps" -lt 20 ]; do
        name=$(ps -o comm= -p "$pid" 2>/dev/null)
        case "${name##*/}" in sshd|sshd-*) return 0 ;; esac
        pid=$(ps -o ppid= -p "$pid" 2>/dev/null | tr -d ' ')
        steps=$((steps + 1))
    done
    return 1
}

disable_remote_login() {
    local out rc
    out=$(systemsetup -f -setremotelogin off 2>&1 < /dev/null); rc=$?
    case "$out" in
        *"Full Disk Access"*)
            op_fail "macOS refused to turn Remote Login off: the program running this script needs Full Disk Access (System Settings > Privacy & Security, or a PPPC profile from your MDM for your RMM agent). Or turn it off in System Settings > General > Sharing. No other change was made." ;;
    esac
    [ "$rc" -eq 0 ]
}
disable_screen_sharing() {
    launchctl disable "$SCREEN_SHARING_JOB" > /dev/null 2>&1 || return 1
    launchctl bootout "$SCREEN_SHARING_JOB" > /dev/null 2>&1 || true
    return 0
}
disable_remote_management() {
    [ -x "$KICKSTART" ] || return 1
    "$KICKSTART" -deactivate -configure -access -off > /dev/null 2>&1 || return 1
    "$KICKSTART" -stop > /dev/null 2>&1 || true
    return 0
}

# wait_off STATE_FUNCTION -> waits up to 10 seconds for it to print Off.
wait_off() {
    local tries=0
    while [ "$tries" -lt 10 ]; do
        [ "$("$1")" = "Off" ] && return 0
        sleep 1
        tries=$((tries + 1))
    done
    return 1
}

# ---- Main -----------------------------------------------------------------
op_start "$@"

# Validate
op_read_bool disable_remote_login DISABLE_REMOTE_LOGIN "$DEFAULT_DISABLE_REMOTE_LOGIN"
op_read_bool disable_screen_sharing DISABLE_SCREEN_SHARING "$DEFAULT_DISABLE_SCREEN_SHARING"
op_read_bool disable_remote_management DISABLE_REMOTE_MANAGEMENT "$DEFAULT_DISABLE_REMOTE_MANAGEMENT"
if [ "$OP_OS" != "macOS" ]; then op_finish SKIPPED "Skipped: this script is for macOS."; fi
op_is_root || op_fail "This script must run as root to turn services off. Run it with sudo or from your RMM."

# Detect
op_line "Reading Remote Login, Screen Sharing and Remote Management."
todo_login=0; todo_sharing=0; todo_management=0; left_on_ssh=0
if [ "$disable_remote_login" -eq 1 ] && [ "$(remote_login_state)" = "On" ]; then
    if started_over_ssh; then
        left_on_ssh=1
        op_warn "Remote Login is on but this run came in over SSH; turning it off would end the run. Leaving it on. Run this script from your RMM agent."
    else
        todo_login=1
    fi
fi
if [ "$disable_screen_sharing" -eq 1 ] && [ "$(screen_sharing_state)" = "On" ]; then todo_sharing=1; fi
if [ "$disable_remote_management" -eq 1 ] && [ "$(remote_management_state)" = "On" ]; then todo_management=1; fi
planned=$((todo_login + todo_sharing + todo_management))
if [ "$planned" -eq 0 ]; then
    if [ "$left_on_ssh" -eq 1 ]; then op_finish SKIPPED "Skipped: Remote Login is on but this run came in over SSH. Run it from your RMM agent."; fi
    op_finish OK "Already off: nothing to turn off (Remote Login, Screen Sharing, Remote Management as selected)."
fi

# Act: Remote Login first, so a Full Disk Access refusal stops the run before anything else changes.
op_assert_change_limit "$planned"
if [ "$OP_DRY_RUN" -eq 0 ] && [ -f "$LAUNCHD_OVERRIDES" ]; then
    op_backup "$LAUNCHD_OVERRIDES" > /dev/null
    op_line "Saved the launchd override list to $OP_BACKUP_DIR."
fi
turned_off=""
if [ "$todo_login" -eq 1 ]; then
    op_change "Remote Login" "$CHANGE_TEXT" disable_remote_login || true
    turned_off="${turned_off}Remote Login, "
fi
if [ "$todo_sharing" -eq 1 ]; then
    op_change "Screen Sharing" "$CHANGE_TEXT" disable_screen_sharing || true
    turned_off="${turned_off}Screen Sharing, "
fi
if [ "$todo_management" -eq 1 ]; then
    op_change "Remote Management" "$CHANGE_TEXT" disable_remote_management || true
    turned_off="${turned_off}Remote Management, "
fi

# Verify
if [ "$OP_DRY_RUN" -eq 0 ]; then
    if [ "$todo_login" -eq 1 ] && ! wait_off remote_login_state; then op_fail "Remote Login is still on after turning it off. A configuration profile may be managing it."; fi
    if [ "$todo_sharing" -eq 1 ] && ! wait_off screen_sharing_state; then op_fail "Screen Sharing is still on after turning it off. A configuration profile may be managing it."; fi
    if [ "$todo_management" -eq 1 ] && ! wait_off remote_management_state; then op_fail "Remote Management is still on after turning it off. Run '$KICKSTART -deactivate -stop' by hand to see the error."; fi
fi

# Finish
op_finish CHANGED "Turned off ${turned_off%, }"
