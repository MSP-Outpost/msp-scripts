#!/bin/bash
# ---------------------------------------------------------------------------
# SYNOPSIS:    Turns off Remote Login (SSH), Screen Sharing and Remote Management (ARD) on a Mac.
# DESCRIPTION:
#   THIS SCRIPT CHANGES THINGS. Risk is High, because switching these off can
#   lock out whoever supports the Mac remotely, so it is a dry run unless you
#   set BOTH DRY_RUN=false AND APPROVE=disable-mac-remote-access, and it
#   refuses more than MAX_CHANGES (default 25) changes in one run.
#   For each service that is on and whose DISABLE_* input is true it:
#     Remote Login        runs systemsetup -f -setremotelogin off.
#     Screen Sharing      launchctl disable and bootout of
#                         system/com.apple.screensharing (stays off after a restart).
#     Remote Management   kickstart -deactivate -configure -access -off, then
#                         kickstart -stop (the Apple Remote Desktop agent).
#   It then reads each service again and ends in ERROR if one is still on.
#   Nothing else is touched: no account, no firewall rule, no key. Before
#   changing anything it copies launchd's override database
#   (/var/db/com.apple.xpc.launchd/disabled.plist) to
#   /Library/Application Support/MSPOutpost/Backups/disable-mac-remote-access/.
#   REMOTE LOGIN NEEDS FULL DISK ACCESS. On macOS 13 and later, systemsetup
#   -setremotelogin is refused unless the program that runs this script (your
#   RMM agent or MDM agent) has Full Disk Access. When macOS refuses, this
#   script ends in ERROR before changing anything else and says so. Grant Full
#   Disk Access to the agent (a PPPC profile from your MDM), or turn Remote
#   Login off in System Settings > General > Sharing. Screen Sharing and
#   Remote Management do not need it.
#   PROTECTED: a run that was started over SSH never turns Remote Login off
#   (that would cut off the run itself): it warns and leaves it on, and ends
#   SKIPPED if that was all there was to do. Run it from your RMM agent.
# INPUTS:
#   --disable-remote-login B       (env DISABLE_REMOTE_LOGIN)       Turn Remote Login (SSH) off when it is on. Default true.
#   --disable-screen-sharing B     (env DISABLE_SCREEN_SHARING)     Turn Screen Sharing off when it is on. Default true.
#   --disable-remote-management B  (env DISABLE_REMOTE_MANAGEMENT)  Turn Remote Management (ARD) off when it is on. Default true.
#   --dry-run B                    (env DRY_RUN)                    Default TRUE for this script: lists what it would turn off. Set false AND --approve disable-mac-remote-access to act.
#   --output-format F              (env OUTPUT_FORMAT)              Text (default), Answer, Json or Csv.
#   --export-path FILE             (env EXPORT_PATH)                Also write rows to this .csv or .json file.
#   --result-field NAME            (env RESULT_FIELD)               Also write the answer to this RMM custom field.
# EXAMPLE:
#   sudo ./disable-mac-remote-access.sh
#   sudo ./disable-mac-remote-access.sh --disable-remote-login false --dry-run=false --approve=disable-mac-remote-access
# NOTES:
#   Name:        Turn off Remote Login and Screen Sharing on a Mac
#   Slug:        disable-mac-remote-access
#   Version:     1.0.0
#   Updated:     2026-11-17
#   Type:        Action
#   Category:    19 macOS management
#   Platforms:   macOS 13+
#   RunAs:       System
#   Requires:    bash 3.2, root, Full Disk Access for the agent to turn Remote Login off
#   Changes:     Turns off Remote Login (SSH), Screen Sharing and Remote Management (ARD)
#   Risk:        High
#   Reboot:      Never
#   Runtime:     Under 15 seconds
#   Answer:      "Turned off Screen Sharing, Remote Management"
