<#
.SYNOPSIS
    Audits a new Microsoft 365 client tenant in one pass: licences, global admins, security defaults, Conditional Access, MFA registration, guests, external sharing, audit log and mailbox forwarding.
.DESCRIPTION
    THIS SCRIPT IS READ-ONLY. It signs in to ONE client tenant as an app registration (TenantId, ClientId and a certificate, or a ClientSecret in the environment) and writes one row per finding, each with a Severity (High, Medium, Low or Info) and the evidence in Detail:
      * Licences: every subscribed SKU with units used and bought; a suspended or locked-out SKU, or more units used than bought, is flagged.
      * Global administrators: how many active Global Administrator assignments there are and who they are. Fewer than 2 (no emergency account) or more than 5 is flagged.
      * Security defaults on or off, and the Conditional Access policy count (enabled, report-only, disabled). Security defaults off with no enabled Conditional Access policy is High.
      * MFA registration: the percentage of member accounts registered for MFA, and administrators that are not registered.
      * Guest users: how many guests the tenant holds.
      * External sharing: the SharePoint and OneDrive tenant sharing level (Anyone links are flagged), guest resharing and domain restriction.
      * Only when CheckExchange=true: whether the unified audit log is on (Get-AdminAuditLogConfig) and how many mailboxes forward mail, with the targets (Get-Mailbox). Exchange checks need the ExchangeOnlineManagement module 3.1 or later; when it is missing the two rows say "Not checked" and the rest of the report still runs.
    A check the app is not allowed to run (a missing permission or licence) becomes a "Not checked" row with the service's own error, so one missing permission does not lose the whole report. The run is ERROR only when every check failed. Active role assignments only: Privileged Identity Management eligible assignments are not listed.

    Microsoft Graph application permissions (admin consent): LicenseAssignment.Read.All, RoleManagement.Read.Directory, Policy.Read.All, AuditLog.Read.All (MFA registration report), User.Read.All, SharePointTenantSettings.Read.All. For CheckExchange: Exchange.ManageAsApp plus an Exchange or Entra role that can read mailboxes and the audit configuration (Global Reader or Exchange Administrator). The MFA registration report is reported to need Entra ID P1 or P2.

    Where each fact comes from (read in Microsoft's reference): GET v1.0/subscribedSkus (skuPartNumber, consumedUnits, capabilityStatus, prepaidUnits.enabled); GET v1.0/roleManagement/directory/roleAssignments with a roleDefinitionId filter and $expand=principal (Global Administrator is role template 62e90394-69f5-4237-9190-012177145e10, the id Microsoft's own example uses); GET v1.0/policies/identitySecurityDefaultsEnforcementPolicy (isEnabled); GET v1.0/identity/conditionalAccess/policies (state); GET v1.0/reports/authenticationMethods/userRegistrationDetails (isMfaRegistered, isAdmin, userType); GET v1.0/users filtered on userType eq 'Guest' with ConsistencyLevel eventual and $count; GET v1.0/admin/sharepoint/settings (sharingCapability, isResharingByExternalUsersEnabled, sharingDomainRestrictionMode); Get-AdminAuditLogConfig (UnifiedAuditLogIngestionEnabled, read in Exchange Online PowerShell); Get-Mailbox.
    Not confirmed in the documentation, so read defensively: the Get-Mailbox page does not list ForwardingAddress and ForwardingSmtpAddress as output properties (the Set-Mailbox page does); the least-privileged Exchange role for the two Exchange reads; whether the principal of a role assignment always returns userPrincipalName (display name or id is used when it does not); the shape of the sharepoint settings reply (Microsoft's example wraps it in a value object, so both shapes are read); the Entra licence the MFA registration report needs (the page states none).
.PARAMETER TenantId
    The client tenant: its ID (a GUID) or a domain such as contoso.onmicrosoft.com. Required.
    Environment variable: TenantId
.PARAMETER ClientId
    The app registration's Application (client) ID, a GUID. Required.
    Environment variable: ClientId
.PARAMETER CertificateThumbprint
