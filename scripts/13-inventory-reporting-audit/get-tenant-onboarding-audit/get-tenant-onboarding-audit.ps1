Start-OutpostRun
try {
    # Validate
    Read-OutpostM365Inputs
    $Config = [pscustomobject]@{
        CheckExchange = Read-OutpostBool -Name 'CheckExchange'
    }
    $script:SeverityCount = @{}
    $script:CheckFailures = 0
    $totalChecks = 6
    if ($Config.CheckExchange) { $totalChecks = 8 }

    # Detect
    Write-OutpostLine -Text "Auditing tenant $($script:OutpostM365.Tenant) as app $($script:OutpostM365.Client) (read-only)."
    Invoke-AuditCheck -Area 'Licences' -Finding 'Subscribed SKUs' -Check { Test-Licence }
    Invoke-AuditCheck -Area 'Admins' -Finding 'Global Administrators' -Check { Test-GlobalAdmin }
    Test-IdentityPolicy
    Invoke-AuditCheck -Area 'Identity' -Finding 'MFA registration' -Check { Test-MfaRegistration }
    Invoke-AuditCheck -Area 'Sharing' -Finding 'Guest users' -Check { Test-GuestUser }
    Invoke-AuditCheck -Area 'Sharing' -Finding 'SharePoint and OneDrive sharing level' -Check { Test-ExternalSharing }
    if ($Config.CheckExchange) { Test-ExchangeSetting }

    # Finish
    $rowCount = @($script:OutpostRun.Rows).Count
    if ($script:CheckFailures -ge $totalChecks) {
        Stop-OutpostRun -Message 'Every check failed, so nothing was audited. Check the app permissions and admin consent (see the Not checked rows above).'
    }
    $high = [int]$script:SeverityCount['High']
    $medium = [int]$script:SeverityCount['Medium']
    $low = [int]$script:SeverityCount['Low']
    Complete-OutpostRun -Status 'OK' -Answer "Tenant audit: $rowCount findings; $high High, $medium Medium, $low Low; $($script:CheckFailures) not checked"
}
catch {
    Stop-OutpostRun -ErrorRecord $_
}
