function Get-PropertyValue {
    # A property an object may not have: null instead of a strict-mode error.
    param($Object, [string] $Name)
    if ($null -eq $Object) { return $null }
    $found = $Object.PSObject.Properties[$Name]
    if ($null -eq $found) { return $null }
    return $found.Value
}
function Get-ShortText {
    param([string] $Text)
    $line = ($Text -replace '\s+', ' ').Trim()
    if ($line.Length -gt 160) { return $line.Substring(0, 157) + '...' }
    return $line
}
function Format-Percent {
    param([double] $Part, [double] $Whole)
    if ($Whole -le 0) { return '0' }
    return ([math]::Round(100.0 * $Part / $Whole, 1)).ToString('0.#', [Globalization.CultureInfo]::InvariantCulture)
}
function Add-Finding {
    param([string] $Area, [string] $Finding, [string] $Value, [string] $Severity, [string] $Evidence = '')
    Add-OutpostRow -Values @{ Area = $Area; Finding = $Finding; Value = $Value; Severity = $Severity; Detail = $Evidence }
    $script:SeverityCount[$Severity] = 1 + [int]$script:SeverityCount[$Severity]
}
function Add-NotChecked {
    param([string] $Area, [string] $Finding, $ErrorRecord)
    $script:CheckFailures++
    Add-Finding -Area $Area -Finding $Finding -Value 'Not checked' -Severity 'Info' -Evidence (Get-ShortText -Text $ErrorRecord.Exception.Message)
}
function Join-Names {
    param($Names)
    $list = @($Names)
    if ($list.Count -eq 0) { return '' }
    $shown = @($list | Select-Object -First $MaxNamesListed) -join '; '
    if ($list.Count -gt $MaxNamesListed) { return "$shown; and $($list.Count - $MaxNamesListed) more" }
    return $shown
}
function Test-Licence {
    $skus = @(Invoke-OutpostGraph -Path 'v1.0/subscribedSkus' -All)
    if ($skus.Count -eq 0) { Add-Finding -Area 'Licences' -Finding 'Subscribed SKUs' -Value '0' -Severity 'Medium' -Evidence 'The tenant reports no subscriptions.'; return }
    foreach ($sku in $skus) {
        $name = [string](Get-PropertyValue -Object $sku -Name 'skuPartNumber')
        $status = [string](Get-PropertyValue -Object $sku -Name 'capabilityStatus')
        $used = [int](Get-PropertyValue -Object $sku -Name 'consumedUnits')
        $prepaid = Get-PropertyValue -Object $sku -Name 'prepaidUnits'
        $bought = [int](Get-PropertyValue -Object $prepaid -Name 'enabled')
        $severity = 'Info'
        $detail = "Status $status"
        if ($status -and $status -ne 'Enabled') { $severity = 'Medium'; $detail = "Status $status (suspended, locked out or in warning)" }
        elseif ($used -gt $bought) { $severity = 'Low'; $detail = "$used units assigned but $bought bought" }
        Add-Finding -Area 'Licences' -Finding $name -Value "$used of $bought used" -Severity $severity -Evidence $detail
    }
}
function Test-GlobalAdmin {
    $path = 'v1.0/roleManagement/directory/roleAssignments?$filter=roleDefinitionId%20eq%20''' + $GlobalAdministratorRoleId + '''&$expand=principal'
    $assignments = @(Invoke-OutpostGraph -Path $path -All)
    $names = New-Object -TypeName System.Collections.ArrayList
    $users = 0
    foreach ($assignment in $assignments) {
        $principal = Get-PropertyValue -Object $assignment -Name 'principal'
        $kind = [string](Get-PropertyValue -Object $principal -Name '@odata.type')
        $label = [string](Get-PropertyValue -Object $principal -Name 'userPrincipalName')
        if (-not $label) { $label = [string](Get-PropertyValue -Object $principal -Name 'displayName') }
        if (-not $label) { $label = [string](Get-PropertyValue -Object $assignment -Name 'principalId') }
        if ($kind -eq '#microsoft.graph.group') { $label = "$label (group)" }
        elseif ($kind -eq '#microsoft.graph.servicePrincipal') { $label = "$label (app)" }
        else { $users++ }
        [void]$names.Add($label)
    }
    $severity = 'Info'
    $note = 'Active assignments only; eligible (PIM) assignments are not listed.'
    if ($users -eq 0) { $severity = 'High'; $note = 'No user holds Global Administrator directly. ' + $note }
    elseif ($users -lt 2) { $severity = 'Medium'; $note = 'Only one Global Administrator user: no emergency (break-glass) account. ' + $note }
    elseif ($users -gt 5) { $severity = 'Medium'; $note = 'More than 5 Global Administrator users: reduce it. ' + $note }
    Add-Finding -Area 'Admins' -Finding 'Global Administrators' -Value "$users user(s)" -Severity $severity -Evidence ($note + ' ' + (Join-Names -Names $names))
}
function Get-SecurityDefault {
    try {
        $policy = Invoke-OutpostGraph -Path 'v1.0/policies/identitySecurityDefaultsEnforcementPolicy'
        return [bool](Get-PropertyValue -Object $policy -Name 'isEnabled')
    }
    catch { Add-NotChecked -Area 'Identity' -Finding 'Security defaults' -ErrorRecord $_; return $null }
}
function Get-ConditionalAccessCount {
    try {
        $policies = @(Invoke-OutpostGraph -Path 'v1.0/identity/conditionalAccess/policies' -All)
        $counts = @{ enabled = 0; report = 0; disabled = 0 }
        foreach ($policy in $policies) {
            $state = [string](Get-PropertyValue -Object $policy -Name 'state')
            if ($state -eq 'enabled') { $counts.enabled++ }
            elseif ($state -eq 'enabledForReportingButNotEnforced') { $counts.report++ }
            else { $counts.disabled++ }
        }
        return [pscustomobject]@{ Total = $policies.Count; Enabled = $counts.enabled; ReportOnly = $counts.report; Disabled = $counts.disabled }
    }
    catch { Add-NotChecked -Area 'Identity' -Finding 'Conditional Access policies' -ErrorRecord $_; return $null }
}
function Test-IdentityPolicy {
    $defaults = Get-SecurityDefault
    $access = Get-ConditionalAccessCount
    if ($null -ne $defaults) {
        $severity = 'Info'
        $detail = ''
        if (-not $defaults -and $null -ne $access -and $access.Enabled -eq 0) { $severity = 'High'; $detail = 'Security defaults are off and no Conditional Access policy is enabled: nothing enforces MFA.' }
        elseif (-not $defaults -and $null -eq $access) { $detail = 'Off. Conditional Access could not be read, so enforcement is unknown.' }
        elseif (-not $defaults) { $detail = 'Off; Conditional Access policies are in use.' }
        Add-Finding -Area 'Identity' -Finding 'Security defaults' -Value $(if ($defaults) { 'On' } else { 'Off' }) -Severity $severity -Evidence $detail
    }
    if ($null -ne $access) {
        $detail = "$($access.Enabled) enabled, $($access.ReportOnly) report-only, $($access.Disabled) disabled"
        Add-Finding -Area 'Identity' -Finding 'Conditional Access policies' -Value ([string]$access.Total) -Severity 'Info' -Evidence $detail
    }
}
function Test-MfaRegistration {
    $details = @(Invoke-OutpostGraph -Path 'v1.0/reports/authenticationMethods/userRegistrationDetails' -All)
    $members = @($details | Where-Object { ([string](Get-PropertyValue -Object $_ -Name 'userType')) -ne 'guest' })
    $registered = @($members | Where-Object { [bool](Get-PropertyValue -Object $_ -Name 'isMfaRegistered') })
    $percent = Format-Percent -Part $registered.Count -Whole $members.Count
    $severity = 'Info'
    if ($members.Count -gt 0) {
        $number = [double]$registered.Count / [double]$members.Count
        if ($number -lt 0.5) { $severity = 'High' } elseif ($number -lt 0.9) { $severity = 'Medium' } elseif ($number -lt 1) { $severity = 'Low' }
    }
    Add-Finding -Area 'Identity' -Finding 'MFA registration (members)' -Value "$percent%" -Severity $severity -Evidence "$($registered.Count) of $($members.Count) member accounts registered; disabled accounts are not in the report"
    $adminsWithout = @($members | Where-Object { [bool](Get-PropertyValue -Object $_ -Name 'isAdmin') -and -not [bool](Get-PropertyValue -Object $_ -Name 'isMfaRegistered') })
    $label = 'None'
    $adminSeverity = 'Info'
    if ($adminsWithout.Count -gt 0) { $label = [string]$adminsWithout.Count; $adminSeverity = 'High' }
    Add-Finding -Area 'Identity' -Finding 'Administrators without MFA' -Value $label -Severity $adminSeverity -Evidence (Join-Names -Names @($adminsWithout | ForEach-Object { [string](Get-PropertyValue -Object $_ -Name 'userPrincipalName') }))
}
function Test-GuestUser {
    $guests = @(Invoke-OutpostGraph -Path 'v1.0/users?$filter=userType%20eq%20''Guest''&$count=true&$select=id,userPrincipalName' -All -Eventual)
    $severity = 'Info'
    if ($guests.Count -gt 10) { $severity = 'Low' }
    Add-Finding -Area 'Sharing' -Finding 'Guest users' -Value ([string]$guests.Count) -Severity $severity -Evidence 'Review that each guest still needs access.'
}
function Test-ExternalSharing {
    $reply = Invoke-OutpostGraph -Path 'v1.0/admin/sharepoint/settings'
    $settings = $reply
    if ($null -eq (Get-PropertyValue -Object $reply -Name 'sharingCapability')) { $settings = Get-PropertyValue -Object $reply -Name 'value' }
    $capability = [string](Get-PropertyValue -Object $settings -Name 'sharingCapability')
    if (-not $capability) { throw 'The SharePoint settings reply has no sharingCapability.' }
    $severity = 'Info'
    $detail = ''
    if ($capability -eq 'externalUserAndGuestSharing') { $severity = 'Medium'; $detail = 'Users can share with anyone through links that need no sign-in.' }
    elseif ($capability -eq 'externalUserSharingOnly') { $detail = 'New and existing guests, who must sign in or use a code.' }
    elseif ($capability -eq 'existingExternalUserSharingOnly') { $detail = 'Existing guests only.' }
    elseif ($capability -eq 'disabled') { $detail = 'Internal sharing only.' }
    Add-Finding -Area 'Sharing' -Finding 'SharePoint and OneDrive sharing level' -Value $capability -Severity $severity -Evidence $detail
    $resharing = Get-PropertyValue -Object $settings -Name 'isResharingByExternalUsersEnabled'
    if ($null -ne $resharing) {
        $reshareSeverity = 'Info'
        if ([bool]$resharing -and $capability -ne 'disabled') { $reshareSeverity = 'Low' }
        Add-Finding -Area 'Sharing' -Finding 'Guests can reshare' -Value $(if ([bool]$resharing) { 'Yes' } else { 'No' }) -Severity $reshareSeverity -Evidence 'Whether guests may share files and sites they do not own.'
    }
    $mode = [string](Get-PropertyValue -Object $settings -Name 'sharingDomainRestrictionMode')
    if ($mode) { Add-Finding -Area 'Sharing' -Finding 'External sharing domain restriction' -Value $mode -Severity 'Info' -Evidence 'none, allowList or blockList.' }
}
function Test-ExchangeSetting {
    if (-not (Get-Module -ListAvailable -Name ExchangeOnlineManagement)) {
        $script:CheckFailures += 2
        $detail = 'The ExchangeOnlineManagement module is not installed on this computer (Install-Module ExchangeOnlineManagement).'
        Add-Finding -Area 'Exchange' -Finding 'Unified audit log' -Value 'Not checked' -Severity 'Info' -Evidence $detail
        Add-Finding -Area 'Exchange' -Finding 'Mailbox forwarding' -Value 'Not checked' -Severity 'Info' -Evidence $detail
        return
    }
    try { Connect-OutpostExchange }
    catch {
        Add-NotChecked -Area 'Exchange' -Finding 'Unified audit log' -ErrorRecord $_
        Add-NotChecked -Area 'Exchange' -Finding 'Mailbox forwarding' -ErrorRecord $_
        return
    }
    try {
        try {
            $audit = Get-AdminAuditLogConfig
            $enabled = [bool](Get-PropertyValue -Object $audit -Name 'UnifiedAuditLogIngestionEnabled')
            $severity = 'Info'
            $detail = 'Audit records are being collected.'
            if (-not $enabled) { $severity = 'High'; $detail = 'Off: sign-ins and admin actions are not being recorded for investigation.' }
            Add-Finding -Area 'Exchange' -Finding 'Unified audit log' -Value $(if ($enabled) { 'On' } else { 'Off' }) -Severity $severity -Evidence $detail
        }
        catch { Add-NotChecked -Area 'Exchange' -Finding 'Unified audit log' -ErrorRecord $_ }
        try {
            $forwarding = New-Object -TypeName System.Collections.ArrayList
            $external = 0
            foreach ($mailbox in @(Get-Mailbox -ResultSize Unlimited)) {
                $internal = [string](Get-PropertyValue -Object $mailbox -Name 'ForwardingAddress')
                $smtp = [string](Get-PropertyValue -Object $mailbox -Name 'ForwardingSmtpAddress')
                if (-not $internal -and -not $smtp) { continue }
                $target = $internal
                if ($smtp) { $target = $smtp; $external++ }
                [void]$forwarding.Add(([string](Get-PropertyValue -Object $mailbox -Name 'UserPrincipalName')) + ' -> ' + $target)
            }
            $severity = 'Info'
            $value = 'None'
            if ($forwarding.Count -gt 0) { $value = [string]$forwarding.Count; $severity = 'Medium'; if ($external -gt 0) { $severity = 'High' } }
            Add-Finding -Area 'Exchange' -Finding 'Mailbox forwarding' -Value $value -Severity $severity -Evidence (Join-Names -Names $forwarding)
        }
        catch { Add-NotChecked -Area 'Exchange' -Finding 'Mailbox forwarding' -ErrorRecord $_ }
    }
    finally { Disconnect-OutpostExchange }
}
function Invoke-AuditCheck {
    param([string] $Area, [string] $Finding, [scriptblock] $Check)
    try { & $Check }
    catch { Add-NotChecked -Area $Area -Finding $Finding -ErrorRecord $_ }
}
