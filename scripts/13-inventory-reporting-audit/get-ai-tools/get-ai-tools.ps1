.SYNOPSIS
    Lists the AI tools installed on the PC and for each user: ChatGPT, Claude, Copilot, Ollama, Cursor and more.

.DESCRIPTION
    THIS SCRIPT IS READ-ONLY. It answers "which AI tools do staff use?" by
    looking for the install traces of well-known AI tools, one row per tool
    and place it was found:

      * installed programs (Programs and Features entries for this PC and for
        signed-in users),
      * Microsoft Store apps for all users (the Copilot app, ChatGPT; the Copilot provider package built into Windows 11 is ignored),
      * per-user installs under each user's AppData folder, which need no
        admin rights and so never show in Programs and Features: Claude,
        Ollama, LM Studio, GPT4All, Jan, Cursor, Windsurf, Perplexity Comet,
      * VS Code extensions in each user's .vscode folder: GitHub Copilot,
        GitHub Copilot Chat and Claude Code,
      * browser extensions identified by their Chrome Web Store ID in every
        Chrome, Edge and Brave profile: Grammarly.

    The tools covered are those whose install names, folders or IDs are known
    with confidence; it is a list of the common ones, not every AI product.
    Browser extensions are matched by ID only (a name can be copied by an
    imitation): other AI extensions (Monica, Sider, Merlin, Harpa and the
    like) are not recognised here, so use get-browser-extensions with
    NameMatch to look for them by name. Web-only tools used in a browser tab
    (chatgpt.com, claude.ai, gemini.google.com) leave no install and are not
    seen. Finding a tool means it is installed, not that it was used. Needs
    administrator rights.

.PARAMETER DryRun
    Reserved; ignored by Reports.

.PARAMETER OutputFormat
    Text (default), Answer, Json or Csv. Environment variable: OutputFormat

.PARAMETER ExportPath
    Also write the rows to this .csv or .json file. Environment variable: ExportPath

.PARAMETER ResultField
    Also write the answer to this RMM custom field. Environment variable: ResultField

