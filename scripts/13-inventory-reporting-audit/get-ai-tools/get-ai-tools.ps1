function Get-VsCodeExtensionList {
    # Extension folder pattern (publisher.name-version) and the tool it means.
    return @(
        [pscustomobject]@{ Tool = 'GitHub Copilot (VS Code)'; Pattern = '^github\.copilot-(\d+(\.\d+)*)' },
        [pscustomobject]@{ Tool = 'GitHub Copilot Chat (VS Code)'; Pattern = '^github\.copilot-chat-(\d+(\.\d+)*)' },
        [pscustomobject]@{ Tool = 'Claude Code (VS Code)'; Pattern = '^anthropic\.claude-code-(\d+(\.\d+)*)' }
