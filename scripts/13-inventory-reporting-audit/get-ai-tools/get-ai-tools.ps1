function Get-BrowserFolderList {
    return @(
        [pscustomobject]@{ Name = 'Chrome'; Tail = 'AppData\Local\Google\Chrome\User Data' },
        [pscustomobject]@{ Name = 'Edge'; Tail = 'AppData\Local\Microsoft\Edge\User Data' },
        [pscustomobject]@{ Name = 'Brave'; Tail = 'AppData\Local\BraveSoftware\Brave-Browser\User Data' }
    )
}

function Get-FileVersionText {
    param([string] $Path)
    try {
        $text = [string](Get-Item -LiteralPath $Path).VersionInfo.ProductVersion
        if ($text -ne '') { return $text }
    }
    catch { $null = $_ }
    return 'unknown'
}

function Get-UninstallEntryList {
    # Programs and Features entries for the PC and for each signed-in user: name, version, owner.
    param($Owners)
    $entries = @()
    $sources = @(
        [pscustomobject]@{ Path = ('HKLM:\' + $UninstallPath); Owner = $AllUsersLabel },
        [pscustomobject]@{ Path = ('HKLM:\' + $UninstallPathWow64); Owner = $AllUsersLabel }
    )
    foreach ($hive in @(Get-ChildItem -LiteralPath $UserHiveRoot -ErrorAction SilentlyContinue | Where-Object { $_.PSChildName -match '^S-1-(5-21|12-1)-[\d-]+$' })) {
        $owner = if ($Owners.ContainsKey($hive.PSChildName)) { [string]$Owners[$hive.PSChildName] } else { $hive.PSChildName }
        $sources += [pscustomobject]@{ Path = ($UserHiveRoot + '\' + $hive.PSChildName + '\' + $UninstallPath); Owner = $owner }
    }
    foreach ($source in $sources) {
        if (-not (Test-Path -LiteralPath $source.Path)) { continue }
        foreach ($key in @(Get-ChildItem -LiteralPath $source.Path -ErrorAction SilentlyContinue)) {
            $properties = Get-ItemProperty -LiteralPath $key.PSPath -ErrorAction SilentlyContinue
            $displayName = [string](Get-PropertyOrNull -Source $properties -Name 'DisplayName')
            if ($displayName -eq '') { continue }
            $entries += [pscustomobject]@{ Name = $displayName; Version = [string](Get-PropertyOrNull -Source $properties -Name 'DisplayVersion'); Owner = $source.Owner }
        }
    }
    return $entries
}

function Add-ToolFinding {
    # One finding per tool, place and user.
    param([string] $Tool, [string] $Place, [string] $Version, [string] $User)
    $key = "$Tool|$Place|$User"
    if (-not $script:Seen.ContainsKey($key)) {
        $script:Seen[$key] = $true
        [void]$script:Found.Add([pscustomobject]@{ Tool = $Tool; Place = $Place; Version = $Version; User = $User })
    }
}

# ---- Main -----------------------------------------------------------------
Start-OutpostRun
try {
    # Validate
    if (-not (Test-OutpostAdmin)) {
        Stop-OutpostRun -Message 'This script needs administrator rights to read other users'' profiles. Run it as SYSTEM from your RMM or from an elevated PowerShell.'
    }

    # Detect
    Write-OutpostLine -Text 'Looking for AI tool installs on this PC and in every local user profile.'
    $profiles = @(Get-CimInstance -ClassName Win32_UserProfile | Where-Object { -not $_.Special -and ([string]$_.SID) -match '^S-1-(5-21|12-1)-' -and $_.LocalPath } | Sort-Object -Property LocalPath)
    $owners = @{}
    foreach ($userProfile in $profiles) { $owners[[string]$userProfile.SID] = (Split-Path -Path ([string]$userProfile.LocalPath) -Leaf) }
    $tools = @(Get-ToolList)
    $script:Found = New-Object -TypeName System.Collections.ArrayList
    $script:Seen = @{}

    # Programs and Features
    foreach ($entry in @(Get-UninstallEntryList -Owners $owners)) {
        foreach ($tool in $tools) {
            if ($tool.Installed -ne '' -and $entry.Name -match $tool.Installed) {
                $entryVersion = if ($entry.Version -ne '') { $entry.Version } else { 'unknown' }
                Add-ToolFinding -Tool $tool.Tool -Place 'Installed program' -Version $entryVersion -User $entry.Owner
            }
        }
    }

    # Per-user AppData installs and machine-wide files
    $programFiles = [Environment]::GetFolderPath('ProgramFiles')
    foreach ($tool in $tools) {
        foreach ($relative in $tool.MachinePaths) {
            $file = Join-Path -Path $programFiles -ChildPath $relative
            if (Test-Path -LiteralPath $file) { Add-ToolFinding -Tool $tool.Tool -Place "Program Files: $relative" -Version (Get-FileVersionText -Path $file) -User $AllUsersLabel }
        }
        foreach ($userProfile in $profiles) {
            $userName = Split-Path -Path ([string]$userProfile.LocalPath) -Leaf
            foreach ($relative in $tool.UserPaths) {
                $file = Join-Path -Path ([string]$userProfile.LocalPath) -ChildPath $relative
                if (Test-Path -LiteralPath $file) { Add-ToolFinding -Tool $tool.Tool -Place "User folder: $relative" -Version (Get-FileVersionText -Path $file) -User $userName }
            }
        }
    }

    # Microsoft Store apps
    try {
        foreach ($package in @(Get-AppxPackage -AllUsers)) {
            foreach ($tool in $tools) {
                if ($tool.Store -eq '' -or ([string]$package.Name) -notmatch $tool.Store) { continue }
                $users = @()
                foreach ($info in @(Get-PropertyOrNull -Source $package -Name 'PackageUserInformation')) {
                    $sid = [string](Get-PropertyOrNull -Source (Get-PropertyOrNull -Source $info -Name 'UserSecurityId') -Name 'Sid')
                    if ($sid -ne '' -and $owners.ContainsKey($sid)) { $users += [string]$owners[$sid] }
                }
                if ($users.Count -eq 0) { $users = @($AllUsersLabel) }
                foreach ($storeUser in $users) { Add-ToolFinding -Tool $tool.Tool -Place 'Microsoft Store app' -Version ([string]$package.Version) -User $storeUser }
            }
        }
    }
    catch { Write-OutpostWarning -Text "Could not list Microsoft Store apps: $($_.Exception.Message)" }

    # VS Code extensions and browser extensions, per user
    foreach ($userProfile in $profiles) {
        $userName = Split-Path -Path ([string]$userProfile.LocalPath) -Leaf
        foreach ($editorFolder in @('.vscode', '.vscode-insiders')) {
            $extensionRoot = Join-Path -Path ([string]$userProfile.LocalPath) -ChildPath ($editorFolder + '\extensions')
            if (-not (Test-Path -LiteralPath $extensionRoot)) { continue }
            foreach ($folder in @(Get-ChildItem -LiteralPath $extensionRoot -Directory -ErrorAction SilentlyContinue)) {
                foreach ($extension in @(Get-VsCodeExtensionList)) {
                    if ($folder.Name -match $extension.Pattern) {
                        $extensionVersion = $Matches[1]
                        Add-ToolFinding -Tool $extension.Tool -Place "$editorFolder\extensions" -Version $extensionVersion -User $userName
                    }
                }
            }
        }
        foreach ($browser in @(Get-BrowserFolderList)) {
            $userData = Join-Path -Path ([string]$userProfile.LocalPath) -ChildPath $browser.Tail
            if (-not (Test-Path -LiteralPath $userData)) { continue }
            foreach ($browserProfile in @(Get-ChildItem -LiteralPath $userData -Directory -ErrorAction SilentlyContinue)) {
                $idFolder = Join-Path -Path (Join-Path -Path $browserProfile.FullName -ChildPath 'Extensions') -ChildPath $GrammarlyExtensionId
                if (-not (Test-Path -LiteralPath $idFolder)) { continue }
                $newest = @(Get-ChildItem -LiteralPath $idFolder -Directory -ErrorAction SilentlyContinue | Sort-Object -Property LastWriteTime -Descending | Select-Object -First 1)
                $extensionVersion = if ($newest.Count -gt 0) { ($newest[0].Name -replace '_\d+$', '') } else { 'unknown' }
                Add-ToolFinding -Tool 'Grammarly (AI writing assistant)' -Place "$($browser.Name) extension ($($browserProfile.Name))" -Version $extensionVersion -User $userName
            }
        }
    }

    $rows = @($script:Found | Sort-Object -Property Tool, User, Place)
    foreach ($row in $rows) {
        Add-OutpostRow -Values @{ Tool = $row.Tool; Where = $row.Place; Version = $row.Version; User = $row.User }
    }

    # Finish
    $names = @($rows | ForEach-Object { $_.Tool } | Sort-Object -Unique)
    if ($names.Count -eq 0) {
        Complete-OutpostRun -Status 'OK' -Answer 'No known AI tools found (install traces of the common desktop tools and VS Code extensions)'
    }
    $noun = if ($names.Count -eq 1) { 'AI tool' } else { 'AI tools' }
    Complete-OutpostRun -Status 'OK' -Answer "$($names.Count) $noun found: $($names -join ', ')"
}
catch {
    Stop-OutpostRun -ErrorRecord $_
}
