function Get-PropertyOrNull {
    param($Source, [string] $Name)
    if ($null -eq $Source) { return $null }
    $property = $Source.PSObject.Properties[$Name]
    if ($null -eq $property) { return $null }
    return $property.Value
}

function New-Tool {
    param([string] $Tool, [string] $Installed = '', [string] $Store = '', [string[]] $UserPaths = @(), [string[]] $MachinePaths = @())
    return [pscustomobject]@{ Tool = $Tool; Installed = $Installed; Store = $Store; UserPaths = $UserPaths; MachinePaths = $MachinePaths }
}

