#Requires -Version 5.1
<#
.SYNOPSIS
    Collects one PC's quarterly-review facts (OS, patching, security, disk, hardware) from the PC itself.
.DESCRIPTION
    THIS SCRIPT IS READ-ONLY. It reads local facts only (no PSA, no internet) and
    writes one Fact/Value row per item: computer name; Windows edition, version and
    build (with the update revision); Windows install date; uptime in days; date
    of the newest installed update (the newer of Windows Update history and
    Get-HotFix) and which one; whether a restart is pending (Windows servicing or
    Windows Update flags); Microsoft Defender state and signature age in days;
    BitLocker protection of the system drive; free space of the system drive in
    percent and GB; installed RAM in GB; processor; manufacturer and model; BIOS
    serial number. Run it on each PC and collect the rows (OutputFormat Json or
    Csv, or ExportPath) into the review. A fact that cannot be read says
    "Unknown" or "Not available" with the reason; one unreadable fact never
    stops the run.
    Warranty is NOT included: it needs the manufacturer's service, which the
    script get-warranty-status does. The install date is the date of the last
    Windows feature update (an upgrade resets it), not the date the PC was bought.

    Where each fact comes from: Win32_OperatingSystem (Caption, Version, BuildNumber,
    InstallDate, LastBootUpTime), Win32_ComputerSystem (Manufacturer, Model,
    TotalPhysicalMemory), Win32_Processor (Name, NumberOfCores), Win32_BIOS (SerialNumber),
    Win32_LogicalDisk (Size, FreeSpace), Win32_EncryptableVolume in
    root\CIMV2\Security\MicrosoftVolumeEncryption (GetProtectionStatus: 0 off, 1 on, 2 unknown),
    Get-MpComputerStatus (AMServiceEnabled, AntivirusEnabled, RealTimeProtectionEnabled,
    AMRunningMode, AntivirusSignatureLastUpdated), the Windows Update Agent history
    (Microsoft.Update.Session), Get-HotFix, and the registry keys CBS RebootPending and
    WindowsUpdate RebootRequired.
    Not confirmed in the documentation read for this script, so read defensively: the
    Defender property AMRunningMode and the registry values DisplayVersion and UBR of
    HKLM\SOFTWARE\Microsoft\Windows NT\CurrentVersion (both proven on Windows 11 by other
    library scripts, not stated on the pages above). Pending file renames are not
    counted as a pending restart (they are common and noisy); use test-pending-reboot for that.
.PARAMETER DryRun
    Reserved; ignored by Reports.
.PARAMETER OutputFormat
    Text (default), Answer, Json or Csv. Environment variable: OutputFormat
.PARAMETER ExportPath
    Also write the rows to this .csv or .json file. Environment variable: ExportPath
.PARAMETER ResultField
    Also write the answer to this RMM custom field. Environment variable: ResultField
.EXAMPLE
    .\get-qbr-data-pack.ps1
    Prints the facts for this PC, one per line.
.EXAMPLE
    .\get-qbr-data-pack.ps1 -OutputFormat Json
    Prints one JSON object with the facts as rows, for the review tool to read.
