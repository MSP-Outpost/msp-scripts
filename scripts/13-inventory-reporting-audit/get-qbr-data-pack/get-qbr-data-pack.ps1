# ---- Constants ------------------------------------------------------------
$VersionKey = 'HKLM:\SOFTWARE\Microsoft\Windows NT\CurrentVersion'
$CbsKey = 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Component Based Servicing\RebootPending'
$WindowsUpdateKey = 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\WindowsUpdate\Auto Update\RebootRequired'
$EncryptionNamespace = 'root\CIMV2\Security\MicrosoftVolumeEncryption'
$HistoryEntriesToRead = 300
$OperationInstallation = 1
$ResultSucceeded = 2
$IgnoredTitlePattern = 'Security Intelligence|Definition Update|Defender Antivirus|Malicious Software Removal'
$EarliestRealYear = 2000
$BytesPerGB = 1073741824

# ---- Functions ------------------------------------------------------------
function Get-PropertyOrNull {
    param($Source, [string] $Name)
    if ($null -eq $Source) { return $null }
    $property = $Source.PSObject.Properties[$Name]
    if ($null -eq $property) { return $null }
    return $property.Value
}

function Format-DateText {
    param($Time)
    if ($null -eq $Time) { return 'Unknown' }
    return ([DateTime]$Time).ToUniversalTime().ToString('yyyy-MM-dd', [Globalization.CultureInfo]::InvariantCulture)
}

function Get-LastPatch {
    # Newest installed update: the newer of Windows Update history and Get-HotFix. Null when neither knows.
    $best = $null
    $label = ''
    try {
        $session = New-Object -ComObject 'Microsoft.Update.Session'
        $searcher = $session.CreateUpdateSearcher()
        $total = $searcher.GetTotalHistoryCount()
        if ($total -gt 0) {
            foreach ($entry in $searcher.QueryHistory(0, [math]::Min($total, $HistoryEntriesToRead))) {
                if ([int]$entry.Operation -ne $OperationInstallation -or [int]$entry.ResultCode -ne $ResultSucceeded) { continue }
                if ([string]$entry.Title -match $IgnoredTitlePattern) { continue }
                $when = [DateTime]::SpecifyKind([DateTime]$entry.Date, [DateTimeKind]::Utc)
                if ($when.Year -lt $EarliestRealYear) { continue }
                if ($null -eq $best -or $when -gt $best) {
                    $best = $when
                    $kb = [regex]::Match([string]$entry.Title, 'KB\d+').Value
                    $label = $(if ($kb) { $kb } else { 'Windows Update' })
                }
            }
        }
    }
    catch { Write-OutpostWarning -Text "Could not read Windows Update history: $($_.Exception.Message)" }
    try {
        foreach ($hotfix in @(Get-HotFix | Where-Object { $null -ne $_.InstalledOn })) {
            $when = [DateTime]::SpecifyKind(([DateTime]$hotfix.InstalledOn).Date, [DateTimeKind]::Utc)
            if ($null -eq $best -or $when -gt $best) { $best = $when; $label = [string]$hotfix.HotFixID }
        }
    }
    catch { Write-OutpostWarning -Text "Could not read installed hotfixes: $($_.Exception.Message)" }
    if ($null -eq $best) { return $null }
    return [pscustomobject]@{ Date = $best; Label = $label }
}

function Get-DefenderFact {
    # Returns @{ State; SignatureAgeDays } as text; never throws.
    $state = 'Not available (no Microsoft Defender, or another antivirus manages this PC)'
    $age = 'Unknown'
    if (-not (Get-Command -Name 'Get-MpComputerStatus' -ErrorAction SilentlyContinue)) { return @{ State = $state; SignatureAgeDays = $age } }
    try {
        $status = Get-MpComputerStatus
        $mode = [string](Get-PropertyOrNull -Source $status -Name 'AMRunningMode')
        $avOn = [bool](Get-PropertyOrNull -Source $status -Name 'AntivirusEnabled') -and [bool](Get-PropertyOrNull -Source $status -Name 'AMServiceEnabled')
        $realTime = [bool](Get-PropertyOrNull -Source $status -Name 'RealTimeProtectionEnabled')
        if ($mode -like '*Passive*' -or $mode -like '*EDR Block*') { $state = "Passive ($mode): another antivirus is primary" }
        elseif ($avOn -and $realTime) { $state = 'On (real-time protection on)' }
        elseif ($avOn) { $state = 'On, real-time protection OFF' }
        else { $state = 'OFF' }
        $updated = Get-PropertyOrNull -Source $status -Name 'AntivirusSignatureLastUpdated'
        if (($updated -is [DateTime]) -and $updated.Year -ge $EarliestRealYear) {
            $age = [string][math]::Floor(((Get-Date) - $updated).TotalDays)
        }
    }
    catch { $state = "Unreadable: $($_.Exception.Message)" }
    return @{ State = $state; SignatureAgeDays = $age }
}

function Get-BitLockerFact {
    # BitLocker protection of the system drive from the encryption WMI class (language independent).
    param([string] $Drive)
    try {
        $volume = Get-CimInstance -Namespace $EncryptionNamespace -ClassName Win32_EncryptableVolume -ErrorAction Stop |
            Where-Object { ([string]$_.DriveLetter).ToUpperInvariant() -eq $Drive } | Select-Object -First 1
        if ($null -eq $volume) { return 'Not available (volume not listed by BitLocker)' }
        $result = Invoke-CimMethod -InputObject $volume -MethodName 'GetProtectionStatus'
        switch ([int]$result.ProtectionStatus) {
            1 { return 'On' }
            0 { return 'Off' }
            default { return 'Unknown (volume locked or unreadable)' }
        }
    }
    catch { return 'Not available (BitLocker WMI class missing, e.g. Windows Home)' }
}

function Add-Fact {
    param([string] $Fact, [string] $Value)
    Add-OutpostRow -Values @{ Fact = $Fact; Value = $Value }
}

# ---- Main -----------------------------------------------------------------
Start-OutpostRun
try {
    # Validate
    if (-not (Test-OutpostAdmin)) {
        Stop-OutpostRun -Message 'Administrator rights are required to read Defender and BitLocker. Run the script as SYSTEM from your RMM or from an elevated PowerShell.'
    }

    # Detect
    Write-OutpostLine -Text 'Reading this PC''s local facts for the quarterly review.'
    $os = Get-CimInstance -ClassName Win32_OperatingSystem
    $system = Get-CimInstance -ClassName Win32_ComputerSystem
    $bios = Get-CimInstance -ClassName Win32_BIOS | Select-Object -First 1
    $cpus = @(Get-CimInstance -ClassName Win32_Processor)
    $computer = [Environment]::MachineName

    $versionInfo = Get-ItemProperty -LiteralPath $VersionKey -ErrorAction SilentlyContinue
    $displayVersion = [string](Get-PropertyOrNull -Source $versionInfo -Name 'DisplayVersion')
    $revision = Get-PropertyOrNull -Source $versionInfo -Name 'UBR'
    $buildText = [string]$os.BuildNumber
    if ($null -ne $revision) { $buildText = "$buildText.$revision" }
    $osName = ([string]$os.Caption).Trim() -replace '^Microsoft\s+', ''
    $osText = $(if ($displayVersion) { "$osName $displayVersion" } else { $osName })

    $uptimeDays = [math]::Round(((Get-Date) - $os.LastBootUpTime).TotalDays, 1)

    $patch = Get-LastPatch
    $patchDays = $null
    if ($null -ne $patch) { $patchDays = [math]::Floor(((Get-Date).ToUniversalTime() - $patch.Date).TotalDays) }

    $reasons = @()
    if (Test-Path -LiteralPath $CbsKey) { $reasons += 'Windows servicing' }
    if (Test-Path -LiteralPath $WindowsUpdateKey) { $reasons += 'Windows Update' }
    $rebootText = $(if ($reasons.Count -gt 0) { 'Yes (' + ($reasons -join ', ') + ')' } else { 'No' })

    $defender = Get-DefenderFact

    $systemDrive = (Split-Path -Path ([Environment]::GetFolderPath('Windows')) -Qualifier).ToUpperInvariant()
    $bitLocker = Get-BitLockerFact -Drive $systemDrive
    $freePercent = 'Unknown'
    $freeGB = 'Unknown'
    $disk = Get-CimInstance -ClassName Win32_LogicalDisk -Filter "DeviceID = '$systemDrive'" -ErrorAction SilentlyContinue
    if ($null -ne $disk -and [double]$disk.Size -gt 0) {
        $freePercent = [string][math]::Round(([double]$disk.FreeSpace / [double]$disk.Size) * 100, 1)
        $freeGB = [string][math]::Round([double]$disk.FreeSpace / $BytesPerGB, 1)
    }

    $ramGB = [math]::Round([double]$system.TotalPhysicalMemory / $BytesPerGB, 0)
    $cpuText = 'Unknown'
    if ($cpus.Count -gt 0) {
        $cores = 0
        foreach ($cpu in $cpus) { $cores += [int](Get-PropertyOrNull -Source $cpu -Name 'NumberOfCores') }
        $cpuText = (([string]$cpus[0].Name) -replace '\s+', ' ').Trim()
        if ($cpus.Count -gt 1) { $cpuText = "$($cpus.Count) x $cpuText" }
        if ($cores -gt 0) { $cpuText = "$cpuText ($cores cores)" }
    }
    $serial = ([string](Get-PropertyOrNull -Source $bios -Name 'SerialNumber')).Trim()
    if ($serial -eq '') { $serial = 'Unknown' }

    Add-Fact -Fact 'Computer' -Value $computer
    Add-Fact -Fact 'Windows' -Value $osText
    Add-Fact -Fact 'Windows build' -Value $buildText
    Add-Fact -Fact 'Windows install date' -Value (Format-DateText -Time $os.InstallDate)
    Add-Fact -Fact 'Uptime (days)' -Value ([string]$uptimeDays)
    Add-Fact -Fact 'Last patch date' -Value $(if ($null -ne $patch) { Format-DateText -Time $patch.Date } else { 'Unknown (no update install recorded)' })
    Add-Fact -Fact 'Last patch' -Value $(if ($null -ne $patch) { $patch.Label } else { 'Unknown' })
    Add-Fact -Fact 'Restart pending' -Value $rebootText
    Add-Fact -Fact 'Defender' -Value $defender.State
    Add-Fact -Fact 'Defender signature age (days)' -Value $defender.SignatureAgeDays
    Add-Fact -Fact "BitLocker $systemDrive" -Value $bitLocker
    Add-Fact -Fact "Free space $systemDrive (%)" -Value $freePercent
    Add-Fact -Fact "Free space $systemDrive (GB)" -Value $freeGB
    Add-Fact -Fact 'RAM (GB)' -Value ([string]$ramGB)
    Add-Fact -Fact 'Processor' -Value $cpuText
    Add-Fact -Fact 'Manufacturer' -Value ([string](Get-PropertyOrNull -Source $system -Name 'Manufacturer'))
    Add-Fact -Fact 'Model' -Value ([string](Get-PropertyOrNull -Source $system -Name 'Model'))
    Add-Fact -Fact 'Serial number' -Value $serial
    Add-Fact -Fact 'Warranty' -Value 'Not included: run get-warranty-status'

    # Finish
    $patchPhrase = 'no patch date found'
    if ($null -ne $patchDays) { $patchPhrase = "patched $patchDays days ago" }
    $defenderShort = ($defender.State -split ' \(')[0]
    $defenderPhrase = "Defender: $defenderShort"
    if ($defender.State -like 'On (*') { $defenderPhrase = "Defender on (signatures $($defender.SignatureAgeDays) d)" }
    $bitLockerShort = ($bitLocker -split ' \(')[0].ToLowerInvariant()
    Complete-OutpostRun -Status 'OK' -Answer ($computer + ': ' + $osText + ' (' + $buildText + '), ' + $patchPhrase + ', ' + $defenderPhrase + ', BitLocker ' + $bitLockerShort + ', ' + $systemDrive + ' ' + $freePercent + '% free, ' + $ramGB + ' GB RAM')
}
catch {
    Stop-OutpostRun -ErrorRecord $_
}
