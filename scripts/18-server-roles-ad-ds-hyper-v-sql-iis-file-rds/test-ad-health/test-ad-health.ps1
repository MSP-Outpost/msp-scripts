# ---- Functions ------------------------------------------------------------
function Add-CheckRow {
    # One row; Status is OK, FAIL or SKIP. Returns 1 for a FAIL so callers can count.
    param([string] $Check, [string] $Target, [string] $Status, [string] $Detail)
    Add-OutpostRow -Values @{ Check = $Check; Target = $Target; Status = $Status; Detail = $Detail }
    if ($Status -eq 'FAIL') { $script:Problems += ($Check + ' ' + $Target + ': ' + $Detail) }
}

function Test-TcpPort {
    param([string] $HostName, [int] $Port, [int] $TimeoutMilliseconds)
    $client = New-Object -TypeName System.Net.Sockets.TcpClient
    try {
        $attempt = $client.BeginConnect($HostName, $Port, $null, $null)
        if (-not $attempt.AsyncWaitHandle.WaitOne($TimeoutMilliseconds, $false)) { return $false }
        $client.EndConnect($attempt)
        return $true
    }
    catch { return $false }
    finally { $client.Close() }
}

function Test-ServiceCheck {
    param([string] $ServiceName, [bool] $MustExist)
    $service = Get-Service -Name $ServiceName -ErrorAction SilentlyContinue
    if ($null -eq $service) {
        if ($MustExist) { Add-CheckRow -Check 'Service' -Target $ServiceName -Status 'FAIL' -Detail 'Service is not installed' }
        else { Add-CheckRow -Check 'Service' -Target $ServiceName -Status 'SKIP' -Detail 'Not installed on this domain controller' }
        return
    }
    if ([string]$service.Status -eq 'Running') {
        Add-CheckRow -Check 'Service' -Target $ServiceName -Status 'OK' -Detail 'Running'
        $script:ServicesOk++
    }
    else {
        Add-CheckRow -Check 'Service' -Target $ServiceName -Status 'FAIL' -Detail ('Service is ' + [string]$service.Status)
    }
}

function Test-ShareCheck {
    param([string] $ShareName)
    $share = $null
    try { $share = Get-SmbShare -Name $ShareName -ErrorAction Stop }
    catch { $share = $null }
    if ($null -eq $share) {
        Add-CheckRow -Check 'Share' -Target $ShareName -Status 'FAIL' -Detail 'Share is missing'
        return
    }
    Add-CheckRow -Check 'Share' -Target $ShareName -Status 'OK' -Detail ([string]$share.Path)
    $script:SharesOk++
}

function Test-FsmoCheck {
    param([string] $RoleName, [string] $Holder)
    if ([string]::IsNullOrWhiteSpace($Holder)) {
        Add-CheckRow -Check 'FSMO' -Target $RoleName -Status 'FAIL' -Detail 'No role holder is recorded'
        return
    }
    if (Test-TcpPort -HostName $Holder -Port $DirectoryPort -TimeoutMilliseconds $ConnectTimeoutMilliseconds) {
        Add-CheckRow -Check 'FSMO' -Target $RoleName -Status 'OK' -Detail "Held by $Holder, answers on port $DirectoryPort"
        $script:RolesOk++
    }
    else {
        Add-CheckRow -Check 'FSMO' -Target $RoleName -Status 'FAIL' -Detail "Held by $Holder, which does not answer on port $DirectoryPort"
    }
}

function Test-ReplicationCheck {
    param([int] $MaxAgeHours)
    $partners = @()
    try { $partners = @(Get-ADReplicationPartnerMetadata -Target ([Environment]::MachineName) -Scope Server -ErrorAction Stop) }
    catch {
        Add-CheckRow -Check 'Replication' -Target 'Partners' -Status 'FAIL' -Detail ('Could not read replication metadata: ' + $_.Exception.Message)
        return
    }
    if ($partners.Count -eq 0) {
        Add-CheckRow -Check 'Replication' -Target 'Partners' -Status 'OK' -Detail 'No replication partners (single domain controller)'
        return
    }
    foreach ($partner in $partners) {
        $name = [string]$partner.PartnerAddress
        $lastSuccess = $partner.LastReplicationSuccess
        $result = [int]$partner.LastReplicationResult
        $failures = [int]$partner.ConsecutiveReplicationFailures
        if ($result -ne 0 -or $failures -gt 0) {
            Add-CheckRow -Check 'Replication' -Target $name -Status 'FAIL' -Detail "Last result $result, $failures consecutive failure(s)"
            continue
        }
        if ($null -eq $lastSuccess -or $lastSuccess -le [DateTime]::MinValue.AddYears(1)) {
            Add-CheckRow -Check 'Replication' -Target $name -Status 'FAIL' -Detail 'No successful replication recorded'
            continue
        }
        $ageHours = [math]::Round(([DateTime]::UtcNow - ([DateTime]$lastSuccess).ToUniversalTime()).TotalHours, 1)
        if ($ageHours -gt $MaxAgeHours) {
            Add-CheckRow -Check 'Replication' -Target $name -Status 'FAIL' -Detail "Last success $ageHours hours ago; limit $MaxAgeHours"
            continue
        }
        Add-CheckRow -Check 'Replication' -Target $name -Status 'OK' -Detail "Last success $ageHours hours ago"
    }
    $script:PartnerCount = $partners.Count
}

function Invoke-DcdiagCheck {
    # dcdiag /q prints only failures, so any output (or a non-zero exit) is a failure; no English text is parsed.
    param([int] $TimeoutSeconds)
    $systemFolder = [Environment]::GetFolderPath('System')
    if (-not $systemFolder) { $systemFolder = 'C:\Windows\System32' }
    $exe = Join-Path -Path $systemFolder -ChildPath 'dcdiag.exe'
    if (-not (Test-Path -LiteralPath $exe)) {
        Add-CheckRow -Check 'Dcdiag' -Target 'dcdiag /q' -Status 'FAIL' -Detail 'dcdiag.exe was not found; install the AD DS tools'
        return
    }
    $info = New-Object -TypeName System.Diagnostics.ProcessStartInfo
    $info.FileName = $exe
    # Event-log tests fail on any warning of the last 24 hours (a restored or restarted DC logs
    # DFSR warnings while SYSVOL comes back, 2026-11-18): live replication is checked above instead.
    $info.Arguments = '/q /skip:SystemLog /skip:DFSREvent /skip:KccEvent /skip:FrsEvent'
    $info.UseShellExecute = $false
    $info.RedirectStandardOutput = $true
    $info.RedirectStandardError = $true
    $info.CreateNoWindow = $true
    $process = [System.Diagnostics.Process]::Start($info)
    $outTask = $process.StandardOutput.ReadToEndAsync()
    $errTask = $process.StandardError.ReadToEndAsync()
    if (-not $process.WaitForExit($TimeoutSeconds * 1000)) {
        try { $process.Kill() } catch { $null = $_ }
        Add-CheckRow -Check 'Dcdiag' -Target 'dcdiag /q' -Status 'FAIL' -Detail "dcdiag did not finish within $TimeoutSeconds seconds"
        return
    }
    $process.WaitForExit()
    $text = ([string]$outTask.Result + [string]$errTask.Result).Trim()
    $lines = @($text -split "`r?`n" | ForEach-Object { $_.Trim() } | Where-Object { $_ -ne '' })
    if ($lines.Count -eq 0 -and $process.ExitCode -eq 0) {
        Add-CheckRow -Check 'Dcdiag' -Target 'dcdiag /q' -Status 'OK' -Detail 'No failed tests'
        return
    }
    $shown = @($lines | Select-Object -First 3) -join ' | '
    if ($lines.Count -eq 0) { $shown = 'no output' }
    Add-CheckRow -Check 'Dcdiag' -Target 'dcdiag /q' -Status 'FAIL' -Detail "Exit code $($process.ExitCode); $($lines.Count) line(s): $shown"
}

# ---- Main -----------------------------------------------------------------
Start-OutpostRun
try {
    # Validate: every input read once, typed, into $Config.
    $Config = [pscustomobject]@{
        MaxReplicationAgeHours = Read-OutpostInt -Name 'MaxReplicationAgeHours' -Min 1 -Max 720
        RunDcdiag              = Read-OutpostBool -Name 'RunDcdiag'
        DcdiagTimeoutSeconds   = Read-OutpostInt -Name 'DcdiagTimeoutSeconds' -Min 30 -Max 1800
    }
    if (-not (Test-OutpostAdmin)) {
        Stop-OutpostRun -Message 'This script needs administrator rights. Run it as SYSTEM from your RMM or from an elevated PowerShell.'
    }
    if ([int](Get-CimInstance -ClassName Win32_ComputerSystem).DomainRole -lt $DomainControllerRole) {
        Complete-OutpostRun -Status 'SKIPPED' -Answer 'Skipped: this is not a domain controller.'
    }
    if (-not (Get-Module -ListAvailable -Name ActiveDirectory)) {
        Stop-OutpostRun -Message 'The ActiveDirectory PowerShell module was not found. Install it with Install-WindowsFeature RSAT-AD-PowerShell, then run again.'
    }
    Import-Module -Name ActiveDirectory

    # Detect
    $script:Problems = @()
    $script:ServicesOk = 0
    $script:SharesOk = 0
    $script:RolesOk = 0
    $script:PartnerCount = 0
    Write-OutpostLine -Text "Checking Active Directory health on $([Environment]::MachineName)."

    foreach ($serviceName in $RequiredServices) { Test-ServiceCheck -ServiceName $serviceName -MustExist $true }
    foreach ($serviceName in $OptionalServices) { Test-ServiceCheck -ServiceName $serviceName -MustExist $false }
    foreach ($shareName in $RequiredShares) { Test-ShareCheck -ShareName $shareName }

    $domain = Get-ADDomain
    $forest = Get-ADForest
    Test-FsmoCheck -RoleName 'SchemaMaster' -Holder ([string]$forest.SchemaMaster)
    Test-FsmoCheck -RoleName 'DomainNamingMaster' -Holder ([string]$forest.DomainNamingMaster)
    Test-FsmoCheck -RoleName 'PDCEmulator' -Holder ([string]$domain.PDCEmulator)
    Test-FsmoCheck -RoleName 'RIDMaster' -Holder ([string]$domain.RIDMaster)
    Test-FsmoCheck -RoleName 'InfrastructureMaster' -Holder ([string]$domain.InfrastructureMaster)

    Test-ReplicationCheck -MaxAgeHours $Config.MaxReplicationAgeHours

    if ($Config.RunDcdiag) { Invoke-DcdiagCheck -TimeoutSeconds $Config.DcdiagTimeoutSeconds }
    else { Add-CheckRow -Check 'Dcdiag' -Target 'dcdiag /q' -Status 'SKIP' -Detail 'RunDcdiag is false' }

    # Finish
    $computerName = [Environment]::MachineName
    if ($script:Problems.Count -gt 0) {
        $shownProblems = @($script:Problems | Select-Object -First 3) -join '; '
        $more = ''
        if ($script:Problems.Count -gt 3) { $more = " (+$($script:Problems.Count - 3) more)" }
        Complete-OutpostRun -Status 'ALERT' -Answer "AD unhealthy on $($computerName): $($script:Problems.Count) problem(s): $shownProblems$more"
    }
    $replicationText = 'no replication partners'
    if ($script:PartnerCount -gt 0) { $replicationText = "replication OK ($($script:PartnerCount) partners)" }
    $dcdiagText = 'dcdiag clean'
    if (-not $Config.RunDcdiag) { $dcdiagText = 'dcdiag not run' }
    Complete-OutpostRun -Status 'OK' -Answer "AD healthy on $($computerName): $($script:ServicesOk) services, $($script:SharesOk) shares, $($script:RolesOk) FSMO roles, $replicationText, $dcdiagText"
}
catch {
    Stop-OutpostRun -ErrorRecord $_
}
