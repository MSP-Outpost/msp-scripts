#Requires -Version 5.1
<#
.SYNOPSIS
    Alerts when this domain controller's Active Directory services, replication, FSMO roles, shares or dcdiag tests are unhealthy.

.DESCRIPTION
    THIS SCRIPT IS READ-ONLY. Run it on a domain controller. It checks, in order:

    1. Services: NTDS, Netlogon, KDC and W32Time must be running. DNS and DFSR
       must be running when they are installed (a domain controller that does
       not host DNS, or still uses the old FRS for SYSVOL, is not an alert).
    2. Shares: SYSVOL and NETLOGON must be shared.
    3. FSMO roles: the five role holders (schema master, domain naming master,
       PDC emulator, RID master, infrastructure master) must answer on the
       directory port (TCP 389).
    4. Replication: every replication partner of this domain controller must
       show a last result of success, no consecutive failures, and a last
       success newer than MaxReplicationAgeHours. This reads the same data as
       repadmin /replsummary, but through typed values instead of text, so it
       works in every Windows language. A single-domain-controller forest has
       no partners: that is healthy, not an alert.
    5. dcdiag: runs "dcdiag /q" (quiet: prints only what failed) and alerts
       when it prints anything or exits non-zero. The event-log tests
       (SystemLog, DFSREvent, KccEvent, FrsEvent) are skipped: they fail on any
       warning event of the last 24 hours, so one restart alerts for a day.

    Each check is one row. On a computer that is not a domain controller it
    ends SKIPPED. If the ActiveDirectory module is missing it ends ERROR.

.PARAMETER MaxReplicationAgeHours
    Alert when a replication partner's last successful replication is older
    than this many hours. Whole number, 1 to 720. Default 24.
    Environment variable: MaxReplicationAgeHours

.PARAMETER RunDcdiag
    Run the dcdiag check. true or false. Default true. Set false when dcdiag
    takes too long for your RMM's script timeout.
    Environment variable: RunDcdiag

.PARAMETER DcdiagTimeoutSeconds
    Stop dcdiag after this many seconds and count that as a failure. Whole
    number, 30 to 1800. Default 300.
    Environment variable: DcdiagTimeoutSeconds

.PARAMETER DryRun
    Reserved; ignored by Monitors.

.PARAMETER OutputFormat
    Text (default), Answer, Json or Csv. Environment variable: OutputFormat

.PARAMETER ExportPath
    Also write the rows to this .csv or .json file. Environment variable: ExportPath

.PARAMETER ResultField
    Also write the answer to this RMM custom field. Environment variable: ResultField

.EXAMPLE
    .\test-ad-health.ps1

    Checks this domain controller and alerts on any failed check.

.EXAMPLE
    .\test-ad-health.ps1 -MaxReplicationAgeHours 6 -RunDcdiag false

    Stricter replication age, without the slow dcdiag run.

