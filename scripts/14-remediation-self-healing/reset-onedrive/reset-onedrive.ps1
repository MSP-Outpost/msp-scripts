#Requires -Version 5.1
<#
.SYNOPSIS
    Resets OneDrive for the signed-in user (OneDrive.exe /reset) and makes sure
    it is running again; files are not deleted, OneDrive re-syncs.

.DESCRIPTION
    THIS SCRIPT CHANGES THINGS. As the user who is signed in at the console
    (the script runs from SYSTEM and starts the steps in that user's own
    session), it:

      * finds OneDrive.exe: %LOCALAPPDATA%\Microsoft\OneDrive, then
        Program Files\Microsoft OneDrive, then Program Files (x86)\Microsoft OneDrive,
      * runs OneDrive.exe /reset, which stops OneDrive and clears its sync
        settings and cache,
      * waits up to RestartWaitSeconds for OneDrive to start again by itself,
      * if it did not, starts it again with OneDrive.exe /background,
      * checks that OneDrive is running for that user.

    WARNING FOR THE USER: after a reset OneDrive scans and re-syncs everything.
    On a large library that can take hours and use bandwidth. No file is
    deleted from the PC or from the cloud, but OneDrive may forget folder
    choices (selective sync) and the user may have to confirm their account.
    Tell the user first.

    It never touches the files in the OneDrive folders, other users, or a
    user who is not signed in. Nobody signed in: SKIPPED. OneDrive not
    installed for that user: SKIPPED. Running it twice resets twice: a reset is
    not something that can already be done.

.PARAMETER RestartWaitSeconds
    How long to wait for OneDrive to restart by itself after the reset before
    starting it with /background. Whole number, 5 to 300. Default 60.
    Environment variable: RestartWaitSeconds

.PARAMETER DryRun
    true to list what would be changed and change nothing. Default false.
    -WhatIf does the same. Environment variable: DryRun

.PARAMETER OutputFormat
    Text (default), Json or Csv. Environment variable: OutputFormat

.PARAMETER ExportPath
    Also write the rows to this .csv or .json file. Environment variable: ExportPath

.PARAMETER ResultField
    Also write the answer to this RMM custom field. Environment variable: ResultField

.EXAMPLE
    .\reset-onedrive.ps1 -DryRun true

    Says which OneDrive.exe it would reset and for whom; changes nothing.

.EXAMPLE
    .\reset-onedrive.ps1 -RestartWaitSeconds 90

    Resets OneDrive and gives it 90 seconds to restart by itself.

.NOTES
