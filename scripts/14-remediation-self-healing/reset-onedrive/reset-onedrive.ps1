# ---- Constants ------------------------------------------------------------
$ProfileListKey = 'HKLM:\SOFTWARE\Microsoft\Windows NT\CurrentVersion\ProfileList'
$OneDriveProcessName = 'OneDrive.exe'
$OneDrivePerUserPath = 'AppData\Local\Microsoft\OneDrive\OneDrive.exe'
$OneDrivePerMachinePath = 'Microsoft OneDrive\OneDrive.exe'
$VerifyWaitSeconds = 20

# ---- Functions ------------------------------------------------------------
function Get-UserSid {
    param([string] $Account)
    try {
        return (New-Object -TypeName Security.Principal.NTAccount -ArgumentList $Account).Translate([Security.Principal.SecurityIdentifier]).Value
    }
    catch { return $null }
}

function Get-UserProfilePath {
    param([string] $Sid)
    if (-not $Sid) { return $null }
    try {
        $path = [string](Get-ItemPropertyValue -LiteralPath "$ProfileListKey\$Sid" -Name 'ProfileImagePath')
        return [Environment]::ExpandEnvironmentVariables($path)
    }
    catch { return $null }
}

function Get-UserProcess {
    # Processes with this image name that belong to this DOMAIN\user.
    param([string] $Account, [string] $Name)
    $found = New-Object -TypeName System.Collections.ArrayList
    foreach ($process in @(Get-CimInstance -ClassName Win32_Process -Filter "Name = '$Name'" -ErrorAction SilentlyContinue)) {
        $owner = ''
        try {
            $result = Invoke-CimMethod -InputObject $process -MethodName GetOwner
            if ($result.User) { $owner = "$($result.Domain)\$($result.User)" }
        }
        catch { $owner = '' }
        if ($owner -ieq $Account) {
            [void]$found.Add([pscustomobject]@{ ProcessId = [int]$process.ProcessId; Path = [string]$process.ExecutablePath })
        }
    }
    return @($found)
}

function Find-OneDrivePath {
    # The three places Microsoft documents, then wherever it is running from.
    param([string] $Account, [string] $ProfilePath)
    $candidates = New-Object -TypeName System.Collections.ArrayList
    if ($ProfilePath) { [void]$candidates.Add((Join-Path -Path $ProfilePath -ChildPath $OneDrivePerUserPath)) }
    foreach ($folderName in @('ProgramFiles', 'ProgramFilesX86')) {
        $folder = [Environment]::GetFolderPath($folderName)
        if ($folder) { [void]$candidates.Add((Join-Path -Path $folder -ChildPath $OneDrivePerMachinePath)) }
    }
    foreach ($process in @(Get-UserProcess -Account $Account -Name $OneDriveProcessName)) {
        if ($process.Path -and [IO.Path]::GetFileName($process.Path) -ieq $OneDriveProcessName) { [void]$candidates.Add($process.Path) }
    }
    foreach ($candidate in $candidates) {
        if (Test-Path -LiteralPath $candidate -PathType Leaf) { return [string]$candidate }
    }
    return $null
}

function ConvertTo-CodeText {
    # Text as a PowerShell expression that cannot break out of the code around it.
    param([string] $Text)
    $encoded = [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($Text))
    return "([Text.Encoding]::UTF8.GetString([Convert]::FromBase64String('$encoded')))"
}

function Invoke-UserCode {
    param([string] $Code, [int] $TimeoutSeconds)
    $result = Invoke-OutpostAsUser -Code $Code -TimeoutSeconds $TimeoutSeconds
    if ($null -eq $result) { throw 'Nobody is signed in any more, so the step could not run.' }
    if ($result.ExitCode -ne 0) { throw "The step run as the signed-in user failed (exit code $($result.ExitCode)): $($result.Output)" }
    return [string]$result.Output
}

function Get-ResetCode {
    # Runs in the user's session: /reset, then wait for OneDrive to come back by itself.
    param([string] $ExePath, [int] $WaitSeconds)
    $template = @'
$exePath = __EXE__
$waitSeconds = __WAIT__
$sessionId = [Diagnostics.Process]::GetCurrentProcess().SessionId
function Get-OneDriveId {
    @(Get-Process -Name 'OneDrive' -ErrorAction SilentlyContinue | Where-Object { $_.SessionId -eq $sessionId } | ForEach-Object { [int]$_.Id })
}
$beforeIds = @(Get-OneDriveId)
$resetProcess = Start-Process -FilePath $exePath -ArgumentList '/reset' -PassThru
if (-not $resetProcess.WaitForExit(30000)) { Write-Output 'OP|warning|OneDrive.exe /reset did not exit within 30 seconds' }
$restarted = $false
$deadline = (Get-Date).AddSeconds($waitSeconds)
do {
    Start-Sleep -Seconds 2
    $newIds = @(Get-OneDriveId | Where-Object { $beforeIds -notcontains $_ })
    if ($newIds.Count -gt 0) { $restarted = $true }
} while (-not $restarted -and (Get-Date) -lt $deadline)
Write-Output ('OP|restarted|' + $restarted)
'@
    return $template.Replace('__EXE__', (ConvertTo-CodeText -Text $ExePath)).Replace('__WAIT__', [string]$WaitSeconds)
}

function Get-RelaunchCode {
    # Runs in the user's session: start OneDrive detached from this one-shot task, so it keeps running after it.
    param([string] $ExePath)
    $template = @'
$exePath = __EXE__
$sessionId = [Diagnostics.Process]::GetCurrentProcess().SessionId
function Get-OneDriveId {
    @(Get-Process -Name 'OneDrive' -ErrorAction SilentlyContinue | Where-Object { $_.SessionId -eq $sessionId } | ForEach-Object { [int]$_.Id })
}
function Wait-OneDriveStart {
    $deadline = (Get-Date).AddSeconds(15)
    do {
        Start-Sleep -Seconds 1
        if (@(Get-OneDriveId).Count -gt 0) { return $true }
    } while ((Get-Date) -lt $deadline)
    return $false
}
$started = $false
$created = Invoke-CimMethod -ClassName Win32_Process -MethodName Create -Arguments @{ CommandLine = ('"' + $exePath + '" /background') }
if ($created.ReturnValue -eq 0) { $started = Wait-OneDriveStart }
if (-not $started) {
    Start-Process -FilePath $exePath -ArgumentList '/background'
    $started = Wait-OneDriveStart
}
Write-Output ('OP|started|' + $started)
'@
    return $template.Replace('__EXE__', (ConvertTo-CodeText -Text $ExePath))
}

# ---- Main -----------------------------------------------------------------
Start-OutpostRun
try {
    # Validate: every input read once, typed, into $Config.
    $Config = [pscustomobject]@{
        RestartWaitSeconds = Read-OutpostInt -Name 'RestartWaitSeconds' -Min 5 -Max 300
    }
    if (-not (Test-OutpostAdmin)) {
        Stop-OutpostRun -Message 'This script needs administrator rights. Run it as SYSTEM from your RMM or from an elevated PowerShell.'
    }
    $account = Get-OutpostSignedInUser
    if (-not $account) {
        Complete-OutpostRun -Status 'SKIPPED' -Answer 'Skipped: nobody is signed in, and OneDrive can only be reset in the user''s own session.'
    }

    # Detect
    $profilePath = Get-UserProfilePath -Sid (Get-UserSid -Account $account)
    $exePath = Find-OneDrivePath -Account $account -ProfilePath $profilePath
    if (-not $exePath) {
        Complete-OutpostRun -Status 'SKIPPED' -Answer "Skipped: OneDrive is not installed for $account."
    }
    $beforeIds = @(Get-UserProcess -Account $account -Name $OneDriveProcessName | ForEach-Object { $_.ProcessId })
    Write-OutpostLine -Text "Signed in: $account. OneDrive found at $exePath ($($beforeIds.Count) OneDrive process(es) running)."
    Write-OutpostLine -Text 'A reset makes OneDrive re-scan and re-sync everything; no files are deleted.'

    # Act
    $null = Invoke-OutpostChange -Item $account -Change 'Run OneDrive.exe /reset and wait for OneDrive to restart' -Action {
        $null = Invoke-UserCode -Code (Get-ResetCode -ExePath $exePath -WaitSeconds $Config.RestartWaitSeconds) -TimeoutSeconds ($Config.RestartWaitSeconds + 90)
    }
    $restarted = $false
    if (-not $script:OutpostRun.DryRun) {
        $newProcesses = @(Get-UserProcess -Account $account -Name $OneDriveProcessName | Where-Object { $beforeIds -notcontains $_.ProcessId })
        $restarted = $newProcesses.Count -gt 0
    }
    if ($script:OutpostRun.DryRun -or -not $restarted) {
        $null = Invoke-OutpostChange -Item $account -Change 'Start OneDrive with /background if it did not restart by itself' -Action {
            $null = Invoke-UserCode -Code (Get-RelaunchCode -ExePath $exePath) -TimeoutSeconds 90
        }
    }

    # Verify (skipped in a dry run: nothing was changed)
    if (-not $script:OutpostRun.DryRun) {
        $running = @()
        $deadline = [DateTime]::UtcNow.AddSeconds($VerifyWaitSeconds)
        do {
            $running = @(Get-UserProcess -Account $account -Name $OneDriveProcessName)
            if ($running.Count -eq 0) { Start-Sleep -Seconds 2 }
        } while ($running.Count -eq 0 -and [DateTime]::UtcNow -lt $deadline)
        if ($running.Count -eq 0) {
            Stop-OutpostRun -Message "OneDrive is not running for $account after the reset. Ask them to start OneDrive from the Start menu, or run this script again."
        }
    }

    # Finish
    $howText = 'it restarted on its own and is running'
    if (-not $restarted) { $howText = 'it did not restart by itself, so it was started with /background and is running' }
    if ($script:OutpostRun.DryRun) { $howText = 'it is started again if it does not restart' }
    Complete-OutpostRun -Status 'CHANGED' -Answer "Reset OneDrive for $account; $howText. It re-syncs; no files are deleted."
}
catch {
    Stop-OutpostRun -ErrorRecord $_
}
