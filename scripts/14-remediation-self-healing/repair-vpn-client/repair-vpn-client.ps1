# ---- Constants ------------------------------------------------------------
$ClientNames = @('BuiltIn', 'FortiClient', 'CiscoSecureClient', 'GlobalProtect', 'WireGuard')
# Same documented services as test-vpn-client.ps1 (see the sources there).
$FortiClientServices = @('FA_Scheduler')
$CiscoDisplayNames = @('Cisco Secure Client - AnyConnect VPN Agent', 'Cisco AnyConnect Secure Mobility Agent', 'Cisco AnyConnect VPN Agent')
$GlobalProtectServices = @('PanGPS')
$WireGuardPrefix = 'WireGuardTunnel$'
$ServiceWaitSeconds = 60

# ---- Functions ------------------------------------------------------------
function Find-ClientService {
    param([string] $ClientName, [string] $Tunnel)
    $found = @()
    switch ($ClientName) {
        'FortiClient' { foreach ($name in $FortiClientServices) { $found += @(Get-Service -Name $name -ErrorAction SilentlyContinue) } }
        'GlobalProtect' { foreach ($name in $GlobalProtectServices) { $found += @(Get-Service -Name $name -ErrorAction SilentlyContinue) } }
        'CiscoSecureClient' { foreach ($name in $CiscoDisplayNames) { $found += @(Get-Service -DisplayName $name -ErrorAction SilentlyContinue) } }
        'WireGuard' {
            if ($Tunnel -ne '') { $found += @(Get-Service -Name ($WireGuardPrefix + $Tunnel) -ErrorAction SilentlyContinue) }
            else { $found += @(Get-Service -Name ($WireGuardPrefix + '*') -ErrorAction SilentlyContinue) }
        }
    }
    return @($found | Sort-Object -Property Name -Unique)
}

function Get-VpnProfile {
    $items = @()
    try { $items = @(Get-VpnConnection -AllUserConnection -ErrorAction Stop) }
    catch { $items = @() }
    return $items
}

function Test-ServerResolves {
    param([string] $Server)
    $address = $null
    if ([Net.IPAddress]::TryParse($Server, [ref]$address)) { return $true }
    try {
        $null = Resolve-DnsName -Name $Server -DnsOnly -ErrorAction Stop
        return $true
    }
    catch { return $false }
}

function Get-StartModeMap {
    $map = @{}
    foreach ($serviceRecord in @(Get-CimInstance -ClassName Win32_Service)) { $map[[string]$serviceRecord.Name] = [string]$serviceRecord.StartMode }
    return $map
}

# ---- Main -----------------------------------------------------------------
Start-OutpostRun
try {
    # Validate
    $Config = [pscustomobject]@{
        Client      = Read-OutpostChoice -Name 'Client' -Allowed $ClientNames
        ProfileName = Read-OutpostText -Name 'ProfileName'
        Force       = Read-OutpostBool -Name 'Force'
    }
    if (-not (Test-OutpostAdmin)) {
        Stop-OutpostRun -Message 'This script needs administrator rights. Run it as SYSTEM from your RMM or from an elevated PowerShell.'
    }
    Write-OutpostLine -Text "VPN first aid for the $($Config.Client) client."

    # Detect
    $serviceNeedsStart = @()
    $serviceToRestart = @()
    $disabledNames = @()
    $unresolved = @()
    $subject = ''
    if ($Config.Client -eq 'BuiltIn') {
        if (-not (Get-Command -Name 'Get-VpnConnection' -ErrorAction SilentlyContinue)) {
            Complete-OutpostRun -Status 'SKIPPED' -Answer 'Skipped: the Windows VPN commands (VpnClient module) are not available here.'
        }
        $vpnProfiles = @(Get-VpnProfile)
        if ($Config.ProfileName -ne '') { $vpnProfiles = @($vpnProfiles | Where-Object { $_.Name -ieq $Config.ProfileName }) }
        if ($vpnProfiles.Count -eq 0) {
            Complete-OutpostRun -Status 'SKIPPED' -Answer 'Skipped: no matching all-users Windows VPN profile on this PC.'
        }
        foreach ($vpnProfile in $vpnProfiles) {
            if (-not (Test-ServerResolves -Server ([string]$vpnProfile.ServerAddress))) { $unresolved += $vpnProfile }
        }
        $subject = "$($vpnProfiles.Count) Windows VPN profile(s)"
    }
    else {
        $tunnelName = ''
        if ($Config.Client -eq 'WireGuard') { $tunnelName = $Config.ProfileName }
        $services = @(Find-ClientService -ClientName $Config.Client -Tunnel $tunnelName)
        if ($services.Count -eq 0 -and $tunnelName -ne '') {
            # Tested 2026-11-20: a tunnel name that does not exist said "WireGuard is not installed" on a PC with a tunnel.
            $otherTunnels = @(Find-ClientService -ClientName 'WireGuard' -Tunnel '' | ForEach-Object { $_.Name.Substring($WireGuardPrefix.Length) })
            if ($otherTunnels.Count -gt 0) { Stop-OutpostRun -Message "No WireGuard tunnel named $tunnelName (tunnels here: $($otherTunnels -join ', ')). Correct ProfileName. Nothing was changed." }
        }
        if ($services.Count -eq 0) {
            Complete-OutpostRun -Status 'SKIPPED' -Answer "Skipped: $($Config.Client) is not installed (no service found)."
        }
        $startModes = Get-StartModeMap
        foreach ($service in $services) {
            $mode = ''
            if ($startModes.ContainsKey($service.Name)) { $mode = $startModes[$service.Name] }
            if ($mode -eq 'Disabled') { $disabledNames += $service.Name }
            elseif ([string]$service.Status -ne 'Running') { $serviceNeedsStart += $service }
            elseif ($Config.Force) { $serviceToRestart += $service }
        }
        $subject = "$($services.Count) $($Config.Client) service(s)"
    }
    foreach ($disabledName in $disabledNames) {
        Write-OutpostWarning -Text "Service $disabledName is Disabled. This script does not change start types: enable it by hand or by policy."
    }
    $needsRepair = ($serviceNeedsStart.Count -gt 0) -or ($serviceToRestart.Count -gt 0) -or ($unresolved.Count -gt 0) -or $Config.Force
    if (-not $needsRepair) {
        if ($disabledNames.Count -gt 0) {
            Stop-OutpostRun -Message "Service $($disabledNames -join ', ') is Disabled, so the VPN client cannot start. Enable it (start type Automatic) and run again."
        }
        Complete-OutpostRun -Status 'OK' -Answer "Already healthy: $subject (nothing to repair)"
    }
    if ($serviceToRestart.Count -gt 0) {
        $signedIn = Get-OutpostSignedInUser
        if ($signedIn) { Write-OutpostWarning -Text "Force=true restarts a running VPN service while $signedIn is signed in: their VPN session will drop." }
    }

    # Act
    $done = @()
    foreach ($service in $serviceNeedsStart) {
        $serviceName = $service.Name
        $null = Invoke-OutpostChange -Item "Service $serviceName" -Change 'Start the stopped VPN client service' -Action {
            Start-Service -Name $serviceName
            (Get-Service -Name $serviceName).WaitForStatus('Running', [TimeSpan]::FromSeconds($ServiceWaitSeconds))
        }
        $done += "started $serviceName"
    }
    foreach ($service in $serviceToRestart) {
        $serviceName = $service.Name
        $null = Invoke-OutpostChange -Item "Service $serviceName" -Change 'Restart the running VPN client service (Force)' -Action {
            Restart-Service -Name $serviceName -Force
            (Get-Service -Name $serviceName).WaitForStatus('Running', [TimeSpan]::FromSeconds($ServiceWaitSeconds))
        }
        $done += "restarted $serviceName"
    }
    $null = Invoke-OutpostChange -Item 'DNS client cache' -Change 'Flush the DNS client cache' -Action { Clear-DnsClientCache }
    $null = Invoke-OutpostChange -Item 'DNS registration' -Change 'Re-register this PC in DNS' -Action { Register-DnsClient }
    $done += 'DNS cache flushed and re-registered'

    # Verify (skipped in a dry run: nothing was changed)
    if (-not $script:OutpostRun.DryRun) {
        foreach ($service in @($serviceNeedsStart) + @($serviceToRestart)) {
            if ([string](Get-Service -Name $service.Name).Status -ne 'Running') {
                Stop-OutpostRun -Message "Service $($service.Name) is still not running after the repair. Check the Windows event log and the vendor's client logs."
            }
        }
        foreach ($vpnProfile in $unresolved) {
            if (-not (Test-ServerResolves -Server ([string]$vpnProfile.ServerAddress))) {
                Stop-OutpostRun -Message "VPN profile $($vpnProfile.Name): the server $($vpnProfile.ServerAddress) still does not resolve after flushing DNS. Check the PC's DNS servers and the server name; the profile was not changed."
            }
        }
    }

    # Finish
    Complete-OutpostRun -Status 'CHANGED' -Answer (($done -join '; ') + " ($subject)")
}
catch {
    Stop-OutpostRun -ErrorRecord $_
}
