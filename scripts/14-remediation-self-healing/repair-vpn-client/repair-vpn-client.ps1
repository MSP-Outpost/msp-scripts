#Requires -Version 5.1
<#
.SYNOPSIS
    VPN first aid: starts a stopped VPN client service, flushes and re-registers DNS, never deletes a VPN profile.
.DESCRIPTION
    PARTLY TESTED: written from the vendors' documentation (Fortinet, Cisco, Palo Alto Networks, WireGuard, Microsoft Get-VpnConnection). Tested on Windows 11: the built-in Windows VPN repair, and WireGuard 1.1.1 with a real tunnel service (start a stopped tunnel, Force restart, a Disabled service refused, an unknown tunnel name refused, dry run, second run Already healthy). FortiClient, Cisco Secure Client and GlobalProtect were tested only on the not-installed path.

    THIS SCRIPT CHANGES THINGS. For the one client named in Client it:
      * starts a VPN client service that is Stopped (FortiClient FA_Scheduler;
        Cisco Secure Client / AnyConnect VPN Agent; GlobalProtect PanGPS;
        WireGuard tunnel services WireGuardTunnel$<name>);
      * with Force=true, also RESTARTS a service that is Running, which drops a
        connected tunnel and its user's session: use it when the client is
        running but stuck (GlobalProtect "stuck connecting" is documented to be
        cured by restarting PanGPS);
      * flushes the DNS client cache (Clear-DnsClientCache) and re-registers the
        PC's DNS records (Register-DnsClient).
    It acts only when something is wrong: a service that is not running, a
    built-in VPN profile whose server name does not resolve, or Force=true.
    Otherwise it says the VPN client is already healthy and changes nothing.

    It NEVER deletes or edits a VPN profile, never changes a service's start
    type (a Disabled service is reported, not enabled), and never uninstalls or
    reinstalls a client. For the built-in Windows VPN (Client BuiltIn) there is
    no service to restart: the repair is the DNS flush and re-register, and the
    script then checks that the profile's server name resolves. Profiles that
    belong to one user are invisible to an RMM running as SYSTEM; only the
    all-users phone book is read.
.PARAMETER Client
    BuiltIn (default), FortiClient, CiscoSecureClient, GlobalProtect or WireGuard.
    Environment variable: Client
.PARAMETER ProfileName
    BuiltIn: act only for this profile name. WireGuard: only this tunnel name.
    Empty (default) means all. Ignored for the other clients.
    Environment variable: ProfileName
.PARAMETER Force
    true to restart a service that is already Running, and to flush DNS even
    when everything looks healthy. Can disconnect a user's VPN. Default false.
    Environment variable: Force
.PARAMETER DryRun
    true prints every change it would make and makes none. -WhatIf does the same.
    Environment variable: DryRun
.PARAMETER OutputFormat
    Text (default), Answer, Json or Csv. Environment variable: OutputFormat
.PARAMETER ExportPath
    Also write the rows to this .csv or .json file. Environment variable: ExportPath
.PARAMETER ResultField
    Also write the answer to this RMM custom field. Environment variable: ResultField
.EXAMPLE
    .\repair-vpn-client.ps1 -Client GlobalProtect -Force true
    Restarts the GlobalProtect service PanGPS, then flushes and re-registers DNS.
.EXAMPLE
    .\repair-vpn-client.ps1 -Client BuiltIn -DryRun true
    Says whether a built-in VPN profile's server fails to resolve and what it would flush.
