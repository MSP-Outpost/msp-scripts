# ---- Constants ------------------------------------------------------------
$OfficeVersions = @('16.0', '15.0')
$OutlookProcessName = 'OUTLOOK.EXE'
$ProfileStoreKeyName = '9375CFF0413111d3B88A00104B2A6676'
$ProfileNamePattern = '^[A-Za-z0-9][A-Za-z0-9 ._-]{0,39}$'

# ---- Functions ------------------------------------------------------------
function Get-UserSid {
    param([string] $Account)
    try {
        return (New-Object -TypeName Security.Principal.NTAccount -ArgumentList $Account).Translate([Security.Principal.SecurityIdentifier]).Value
    }
    catch { return $null }
}

function Get-UserProcess {
    # Processes with this image name that belong to this DOMAIN\user.
    param([string] $Account, [string] $Name)
    $found = New-Object -TypeName System.Collections.ArrayList
    foreach ($process in @(Get-CimInstance -ClassName Win32_Process -Filter "Name = '$Name'" -ErrorAction SilentlyContinue)) {
        $owner = ''
        try {
            $result = Invoke-CimMethod -InputObject $process -MethodName GetOwner
            if ($result.User) { $owner = "$($result.Domain)\$($result.User)" }
        }
        catch { $owner = '' }
        if ($owner -ieq $Account) {
            [void]$found.Add([pscustomobject]@{ ProcessId = [int]$process.ProcessId })
        }
    }
    return @($found)
}

function Get-RegistryText {
    # One registry value as text, or '' when the key or value is missing.
    param([string] $Key, [string] $Name)
    try { return [string](Get-ItemPropertyValue -LiteralPath $Key -Name $Name) }
    catch { return '' }
}

function ConvertTo-CodeText {
    # Text as a PowerShell expression that cannot break out of the code around it.
    param([string] $Text)
    $encoded = [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($Text))
    return "([Text.Encoding]::UTF8.GetString([Convert]::FromBase64String('$encoded')))"
}

function Invoke-UserCode {
    param([string] $Code, [int] $TimeoutSeconds)
    $result = Invoke-OutpostAsUser -Code $Code -TimeoutSeconds $TimeoutSeconds
    if ($null -eq $result) { throw 'Nobody is signed in any more, so the step could not run.' }
    if ($result.ExitCode -ne 0) { throw "The step run as the signed-in user failed (exit code $($result.ExitCode)): $($result.Output)" }
    return [string]$result.Output
}

function Get-CloseCode {
    # Runs in the user's session: ask Outlook to close, force it after the wait.
    param([int] $WaitSeconds)
    $template = @'
$waitSeconds = __WAIT__
$sessionId = [Diagnostics.Process]::GetCurrentProcess().SessionId
function Get-OutlookProcess {
    @(Get-Process -Name 'OUTLOOK' -ErrorAction SilentlyContinue | Where-Object { $_.SessionId -eq $sessionId })
}
foreach ($process in @(Get-OutlookProcess)) { [void]$process.CloseMainWindow() }
$deadline = (Get-Date).AddSeconds($waitSeconds)
do {
    Start-Sleep -Milliseconds 500
} while (@(Get-OutlookProcess).Count -gt 0 -and (Get-Date) -lt $deadline)
$forced = $false
if (@(Get-OutlookProcess).Count -gt 0) {
    $forced = $true
    foreach ($process in @(Get-OutlookProcess)) { Stop-Process -Id $process.Id -Force -ErrorAction SilentlyContinue }
    Start-Sleep -Seconds 2
}
if (@(Get-OutlookProcess).Count -gt 0) { throw 'Outlook is still running after it was stopped.' }
Write-Output ('OP|forced|' + $forced)
'@
    return $template.Replace('__WAIT__', [string]$WaitSeconds)
}

function Get-CreateCode {
    # Runs in the user's session: an empty profile (Outlook sets up the account itself) and the default.
    param([string] $Version, [string] $NewProfile)
    $template = @'
$baseKey = 'HKCU:\Software\Microsoft\Office\' + __VERSION__ + '\Outlook'
$newProfile = __NAME__
$profileKey = $baseKey + '\Profiles\' + $newProfile
if (-not (Test-Path -LiteralPath $profileKey)) { $null = New-Item -Path $profileKey -Force }
$storeKey = $profileKey + '\__STORE__'
if (-not (Test-Path -LiteralPath $storeKey)) { $null = New-Item -Path $storeKey -Force }
Set-ItemProperty -LiteralPath $baseKey -Name 'DefaultProfile' -Value $newProfile
Write-Output 'OP|created|true'
'@
    return $template.Replace('__VERSION__', (ConvertTo-CodeText -Text $Version)).Replace('__NAME__', (ConvertTo-CodeText -Text $NewProfile)).Replace('__STORE__', $ProfileStoreKeyName)
}

# ---- Main -----------------------------------------------------------------
Start-OutpostRun
try {
    # Validate: every input read once, typed, into $Config.
    $Config = [pscustomobject]@{
        ProfileName      = Read-OutpostText -Name 'ProfileName'
        CloseOutlook     = Read-OutpostBool -Name 'CloseOutlook'
        CloseWaitSeconds = Read-OutpostInt -Name 'CloseWaitSeconds' -Min 5 -Max 120
    }
    if ($Config.ProfileName -notmatch $ProfileNamePattern) {
        Stop-OutpostInput -Name 'ProfileName' -Value $Config.ProfileName -Expected 'up to 40 letters, digits, spaces, dots, underscores or hyphens, starting with a letter or digit'
    }
    if (-not (Test-OutpostAdmin)) {
        Stop-OutpostRun -Message 'This script needs administrator rights. Run it as SYSTEM from your RMM or from an elevated PowerShell.'
    }
    $account = Get-OutpostSignedInUser
    if (-not $account) {
        Complete-OutpostRun -Status 'SKIPPED' -Answer 'Skipped: nobody is signed in, and the Outlook profile belongs to the signed-in user.'
    }
    $sid = Get-UserSid -Account $account
    if (-not $sid) {
        Stop-OutpostRun -Message "Could not look up the account $account. Sign the user out and in again, then run again."
    }
    $hiveKey = "Registry::HKEY_USERS\$sid"
    if (-not (Test-Path -LiteralPath $hiveKey)) {
        Stop-OutpostRun -Message "The registry of $account is not loaded. Make sure the user is signed in, then run again."
    }

    # Detect
    $versionText = ''
    foreach ($version in $OfficeVersions) {
        if ($versionText -eq '' -and (Test-Path -LiteralPath "$hiveKey\Software\Microsoft\Office\$version\Outlook")) { $versionText = $version }
    }
    if ($versionText -eq '') {
        Complete-OutpostRun -Status 'SKIPPED' -Answer "Skipped: classic Outlook is not set up for $account (no Outlook key under Office 16.0 or 15.0)."
    }
    $outlookKey = "$hiveKey\Software\Microsoft\Office\$versionText\Outlook"
    $profileNames = @(Get-ChildItem -LiteralPath "$outlookKey\Profiles" -ErrorAction SilentlyContinue | ForEach-Object { $_.PSChildName })
    $defaultText = Get-RegistryText -Key $outlookKey -Name 'DefaultProfile'
    $dateText = [DateTime]::Now.ToString('yyyy-MM-dd', [Globalization.CultureInfo]::InvariantCulture)
    $newProfile = "$($Config.ProfileName) $dateText"
    $running = @(Get-UserProcess -Account $account -Name $OutlookProcessName)
    Write-OutpostLine -Text "Signed in: $account. Outlook $versionText has $($profileNames.Count) profile(s); default is '$defaultText'; Outlook is $(if ($running.Count -gt 0) { 'running' } else { 'not running' })."

    if ($profileNames -contains $newProfile -and $defaultText -ieq $newProfile) {
        Complete-OutpostRun -Status 'OK' -Answer "Already done: Outlook profile '$newProfile' exists and is the default for $account."
    }
    if ($running.Count -gt 0 -and -not $Config.CloseOutlook) {
        Stop-OutpostRun -Message "Outlook is running for $account, so nothing was changed. Ask them to close Outlook, or run again with CloseOutlook set to true (unsaved drafts are lost)."
    }

    # Act
    $backupPath = Backup-OutpostItem -Path "HKU\$sid\Software\Microsoft\Office\$versionText\Outlook"
    if ($backupPath) { Write-OutpostLine -Text "Backed up the Outlook registry key to $backupPath" }
    if ($running.Count -gt 0) {
        $null = Invoke-OutpostChange -Item $account -Change "Close Outlook (stopped after $($Config.CloseWaitSeconds) seconds if it stays open)" -Action {
            $null = Invoke-UserCode -Code (Get-CloseCode -WaitSeconds $Config.CloseWaitSeconds) -TimeoutSeconds ($Config.CloseWaitSeconds + 60)
        }
    }
    $createChange = "Create Outlook profile '$newProfile' and make it the default (was '$defaultText')"
    $null = Invoke-OutpostChange -Item $newProfile -Change $createChange -Action {
        $null = Invoke-UserCode -Code (Get-CreateCode -Version $versionText -NewProfile $newProfile) -TimeoutSeconds 60
    }

    # Verify (skipped in a dry run: nothing was changed)
    if (-not $script:OutpostRun.DryRun) {
        $createdKey = "$outlookKey\Profiles\$newProfile"
        if (-not (Test-Path -LiteralPath "$createdKey\$ProfileStoreKeyName")) {
            Stop-OutpostRun -Message "The new profile '$newProfile' was not found in the registry of $account after it was created. Check the account's rights, then run again."
        }
        $nowDefault = Get-RegistryText -Key $outlookKey -Name 'DefaultProfile'
        if ($nowDefault -ine $newProfile) {
            Stop-OutpostRun -Message "The default Outlook profile is '$nowDefault', not '$newProfile'. Check whether a policy sets DefaultProfile, then run again."
        }
        if ($running.Count -gt 0 -and @(Get-UserProcess -Account $account -Name $OutlookProcessName).Count -gt 0) {
            Stop-OutpostRun -Message "Outlook is still running for $account after the profile change. Ask them to close it."
        }
    }

    # Finish
    $closedText = ''
    if ($running.Count -gt 0) { $closedText = 'Closed Outlook. ' }
    Complete-OutpostRun -Status 'CHANGED' -Answer "${closedText}Created Outlook profile '$newProfile' and set it as default; the old profile is kept. Outlook sets up the account at its next start."
}
catch {
    Stop-OutpostRun -ErrorRecord $_
}
