#Requires -Version 5.1
<#
.SYNOPSIS
    Outlook keeps asking for a password or will not open: creates a fresh
    Outlook profile for the signed-in user and makes it the default.

.DESCRIPTION
    THIS SCRIPT CHANGES THINGS. For the user signed in at the console, in
    classic Outlook (Office 2013, 2016, 2019, 2021 and Microsoft 365 apps;
    registry key HKCU\Software\Microsoft\Office\16.0\Outlook, or 15.0), it:

      * refuses to continue if Outlook is running, unless CloseOutlook is
        true: then it asks Outlook to close, and stops it after
        CloseWaitSeconds if it is still open (unsaved drafts are lost),
      * backs up the whole Outlook registry key to
        %ProgramData%\MSPOutpost\Backups\repair-outlook-profile,
      * creates a new, empty profile named "<ProfileName> <date>" (for example
        "Outlook 2026-11-16") and sets it as the default profile.

    It never deletes the old profile (it stays in the profile list, and the
    backup can restore it), never touches OST or PST files or mail data, and
    never starts Outlook. On its next start Outlook finds the new profile has
    no account and runs its automatic account setup (autodiscover), so the
    user may be asked to confirm their address or sign in once, and the
    mailbox is downloaded again into a new OST file. The old OST file is left
    in place and can be deleted later.

    Skipped: nobody signed in; classic Outlook not set up for that user (the
    new Outlook for Windows has no profiles, so there is nothing to rebuild).
    If today's new profile already exists and is the default, it says so and
    changes nothing. Running as an Action twice on the same day is therefore
    safe; on another day it creates another profile.

.PARAMETER ProfileName
    Base name of the new profile; the date is added. Letters, digits, space,
    dot, underscore and hyphen, up to 40 characters. Default Outlook.
    Environment variable: ProfileName

.PARAMETER CloseOutlook
    true to close Outlook if it is running (gracefully, then forced). Default
    false: a running Outlook ends the run with an error. Environment variable: CloseOutlook

.PARAMETER CloseWaitSeconds
    With CloseOutlook, how long to wait for Outlook to close by itself before
    stopping it. Whole number, 5 to 120. Default 30. Environment variable: CloseWaitSeconds

.PARAMETER DryRun
    true to list what would be changed and change nothing. Default false.
    -WhatIf does the same. Environment variable: DryRun

.PARAMETER OutputFormat
    Text (default), Json or Csv. Environment variable: OutputFormat

.PARAMETER ExportPath
    Also write the rows to this .csv or .json file. Environment variable: ExportPath

.PARAMETER ResultField
    Also write the answer to this RMM custom field. Environment variable: ResultField

.EXAMPLE
    .\repair-outlook-profile.ps1 -DryRun true

    Lists the profile it would create and whether Outlook is running.

.EXAMPLE
    .\repair-outlook-profile.ps1 -CloseOutlook true -CloseWaitSeconds 45

    Closes Outlook (forcing it after 45 seconds) and creates the new default profile.

.NOTES
