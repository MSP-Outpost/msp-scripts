# ---- Constants ------------------------------------------------------------
$RecentMinutes = 10
$MobilePhoneMethodId = '3179e48a-750b-4051-897c-87b9720928f7'
# Authentication method @odata.type -> the path segment under /users/{id}/authentication used to delete it.
# Only the methods a lost phone puts at risk. Not listed on purpose: password, Windows Hello for Business, email, Temporary Access Pass.
$MethodPaths = @{
    '#microsoft.graph.microsoftAuthenticatorAuthenticationMethod' = 'microsoftAuthenticatorMethods'
    '#microsoft.graph.phoneAuthenticationMethod'                  = 'phoneMethods'
    '#microsoft.graph.softwareOathAuthenticationMethod'           = 'softwareOathMethods'
    '#microsoft.graph.fido2AuthenticationMethod'                  = 'fido2Methods'
}
$MethodNames = @{
    'microsoftAuthenticatorMethods' = 'Microsoft Authenticator'
    'phoneMethods'                  = 'phone'
    'softwareOathMethods'           = 'OATH token'
    'fido2Methods'                  = 'security key'
}
# ---- Functions ------------------------------------------------------------
function Get-PropertyValue {
    # A property an object may not have: null instead of a strict-mode error.
    param($Object, [string] $Name)
    if ($null -eq $Object) { return $null }
    $found = $Object.PSObject.Properties[$Name]
    if ($null -eq $found) { return $null }
    return $found.Value
}
function ConvertTo-UtcDate {
    # Graph dates arrive as text (Windows PowerShell 5.1) or DateTime (PowerShell 7).
    param($Value)
    if ($null -eq $Value -or "$Value" -eq '') { return $null }
    if ($Value -is [DateTime]) { return $Value.ToUniversalTime() }
    return [DateTime]::Parse([string]$Value, [Globalization.CultureInfo]::InvariantCulture, [Globalization.DateTimeStyles]::AdjustToUniversal -bor [Globalization.DateTimeStyles]::AssumeUniversal)
}
function Format-UtcText {
    param($Time)
    $utc = ConvertTo-UtcDate -Value $Time
    if ($null -eq $utc) { return '' }
    return $utc.ToString("yyyy-MM-dd'T'HH:mm:ss'Z'", [Globalization.CultureInfo]::InvariantCulture)
}
function Get-DeletableMethod {
    # The user's methods that this script deletes, ordered so that a mobile phone goes after the alternate and office phones.
    param([Parameter(Mandatory = $true)][string] $UserId)
    $found = New-Object -TypeName System.Collections.ArrayList
    foreach ($entry in @(Invoke-OutpostGraph -Path ('v1.0/users/' + $UserId + '/authentication/methods') -All)) {
        $type = [string](Get-PropertyValue -Object $entry -Name '@odata.type')
        if (-not $MethodPaths.ContainsKey($type)) { continue }
        $path = $MethodPaths[$type]
        $id = [string](Get-PropertyValue -Object $entry -Name 'id')
        $order = 0
        $label = $MethodNames[$path]
        if ($path -eq 'phoneMethods') {
            $order = 1
            if ($id -eq $MobilePhoneMethodId) { $order = 2 }
            $phoneType = [string](Get-PropertyValue -Object $entry -Name 'phoneType')
            if ($phoneType -ne '') { $label = "phone ($phoneType)" }
        }
        else {
            $named = [string](Get-PropertyValue -Object $entry -Name 'displayName')
            if ($named -ne '') { $label = "$label '$named'" }
        }
        [void]$found.Add([pscustomobject]@{ Id = $id; Type = $type; Path = $path; Order = $order; Label = $label })
    }
    return @($found | Sort-Object -Property Order, Label)
}
# ---- Main -----------------------------------------------------------------
Start-OutpostRun
try {
    # Validate
    $Config = [pscustomobject]@{
        UserPrincipalName = Read-OutpostText -Name 'UserPrincipalName' -Required
        RevokeSessions    = Read-OutpostBool -Name 'RevokeSessions'
    }
    if ($Config.UserPrincipalName -notmatch '^[^@\s]+@[^@\s]+\.[A-Za-z]{2,}$') { Stop-OutpostInput -Name 'UserPrincipalName' -Value $Config.UserPrincipalName -Expected 'a sign-in name such as ann@contoso.com' }
    Read-OutpostM365Inputs

    # Detect (read-only)
    $started = [DateTime]::UtcNow
    $upn = $Config.UserPrincipalName
    Write-OutpostLine -Text "Resetting the MFA methods of $upn in tenant $($script:OutpostM365.Tenant)."
    $user = $null
    try { $user = Invoke-OutpostGraph -Path ('v1.0/users/' + [Uri]::EscapeDataString($upn) + '?$select=id,userPrincipalName') }
    catch {
        if ($_.Exception.Message -match 'HTTP 404') { Stop-OutpostRun -Message "No user $upn in tenant $($script:OutpostM365.Tenant). Correct UserPrincipalName. Nothing was changed." }
        throw
    }
    $userId = [string](Get-PropertyValue -Object $user -Name 'id')
    $methods = @(Get-DeletableMethod -UserId $userId)
    if ($methods.Count -eq 0) {
        Complete-OutpostRun -Status 'OK' -Answer "Already reset: $upn has no phone, authenticator, OATH or security key method registered"
    }
    $planned = $methods.Count
    if ($Config.RevokeSessions) { $planned++ }
    Assert-OutpostChangeLimit -Planned $planned

    # Before-state, written before the first deletion (never in a dry run). No phone numbers, no secrets.
    if (-not $script:OutpostRun.DryRun) {
        $folder = Join-Path -Path (Get-OutpostDataFolder) -ChildPath ('Backups\' + $OutpostScript.Slug + '\' + [DateTime]::UtcNow.ToString('yyyyMMdd-HHmmss', [Globalization.CultureInfo]::InvariantCulture))
        $null = New-Item -Path $folder -ItemType Directory -Force
        $beforeFile = Join-Path -Path $folder -ChildPath (($upn -replace '[^A-Za-z0-9.@-]', '_') + '-methods-before.json')
        $before = [pscustomobject]@{
            userPrincipalName = $upn; userId = $userId
            authenticationMethods = @($methods | ForEach-Object { [pscustomobject]@{ id = $_.Id; type = $_.Type; label = $_.Label } })
        }
        ConvertTo-Json -InputObject $before -Depth 5 | Set-Content -LiteralPath $beforeFile -Encoding UTF8
        Write-OutpostLine -Text "Before-state saved to $beforeFile"
    }

    # Act
    $removed = 0
    foreach ($entry in $methods) {
        $target = $entry
        $ok = Invoke-OutpostChange -Item $upn -Change "Delete $($target.Label) ($($target.Path) $($target.Id))" -Action {
            [void](Invoke-OutpostGraph -Method DELETE -Path ('v1.0/users/' + $userId + '/authentication/' + $target.Path + '/' + $target.Id))
        }
        if ($ok) { $removed++ }
    }
    if ($Config.RevokeSessions) {
        $null = Invoke-OutpostChange -Item $upn -Change 'Revoke all sign-in sessions and refresh tokens' -Action { [void](Invoke-OutpostGraph -Method POST -Path ('v1.0/users/' + $userId + '/revokeSignInSessions')) }
    }

    # Verify (skipped in a dry run: nothing was changed). Entra shows a change a few seconds late, so read up to 6 times.
    if (-not $script:OutpostRun.DryRun) {
        $left = @()
        for ($read = 1; $read -le 6; $read++) {
            $left = @(Get-DeletableMethod -UserId $userId)
            if ($left.Count -eq 0) { break }
            Start-Sleep -Seconds 5
        }
        if ($left.Count -gt 0) {
            Stop-OutpostRun -Message "$($left.Count) method(s) of $upn still show after the deletion ($(@($left | ForEach-Object { $_.Label }) -join ', ')). Check the UserAuthenticationMethod.ReadWrite.All permission, then run it again."
        }
        if ($Config.RevokeSessions) {
            $after = Invoke-OutpostGraph -Path ('v1.0/users/' + $userId + '?$select=id,signInSessionsValidFromDateTime')
            $valid = ConvertTo-UtcDate -Value (Get-PropertyValue -Object $after -Name 'signInSessionsValidFromDateTime')
            if ($null -eq $valid -or $valid -lt $started.AddMinutes(-$RecentMinutes)) {
                Write-OutpostWarning -Text 'signInSessionsValidFromDateTime did not move to the time of this run; check that the sessions were revoked.'
            }
        }
    }

    # Finish
    $answer = "Removed $($methods.Count) MFA method(s) from $upn"
    if ($Config.RevokeSessions) { $answer += '; sessions revoked' }
    $answer += '; the user registers again at next sign-in'
    Complete-OutpostRun -Status 'CHANGED' -Answer $answer
}
catch {
    Stop-OutpostRun -ErrorRecord $_
}
