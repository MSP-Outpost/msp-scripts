#Requires -Version 5.1
<#
.SYNOPSIS
    Resets a Microsoft 365 user's MFA methods (phone, authenticator app, OATH token, security key) so they register again, for a lost phone.
.DESCRIPTION
    THIS SCRIPT CHANGES THINGS. For the one account in UserPrincipalName it DELETES these registered authentication methods:
      * phone numbers (mobile, alternate mobile and office; used for SMS and voice calls),
      * the Microsoft Authenticator app registrations,
      * software OATH token registrations (other authenticator apps),
      * FIDO2 security keys.
    The user then has to register again the next time they sign in where MFA is required (Microsoft's "require re-register
    multifactor authentication" procedure: delete each method; with none left the user is prompted). It NEVER deletes the
    password method, a Windows Hello for Business credential (bound to a device, not to the lost phone), the email method (used for
    password reset) or a Temporary Access Pass (the admin may have just issued one so the user can register again), and never
    touches any other account. If RevokeSessions is true it also revokes the user's sign-in sessions and refresh tokens (the user is
    signed out everywhere), but only in a run that removes methods, so a second run changes nothing.
    A method that cannot be deleted stops the run with an error naming it (methods already deleted stay deleted; run it again).
    Microsoft says a phone number cannot be deleted while it is the user's default MFA method, and that a mobile number cannot be
    deleted while an alternate mobile number remains (the script deletes alternate and office numbers first); ask the user to
    change the default method first, or delete the method in the Entra admin center.

    HIGH RISK: it is a dry run (lists every method it would delete, changes nothing) unless DryRun=false AND
    Approve=reset-user-mfa-methods, and it refuses to delete more than MaxChanges (default 25) in one run. Before the first deletion it
    writes the method IDs and types (no phone numbers, no secrets) as JSON under
    %ProgramData%\MSPOutpost\Backups\reset-user-mfa-methods\ and prints the file name; a deleted method cannot be restored, the
    user registers a new one.

    Permission (Microsoft Graph APPLICATION): User.Read.All (find the user), UserAuthenticationMethod.ReadWrite.All (list and delete
    methods) and, only when RevokeSessions is true, User.RevokeSessions.All. For a user who holds an admin role, Microsoft ties
    changing credentials to a directory role: give the app's service principal the Privileged Authentication Administrator role, or
    the run stops with a 403 naming the method.

    Where each fact comes from (read in the Microsoft Graph v1.0 reference): GET /users/{id}/authentication/methods
    (UserAuthenticationMethod.Read.All; @odata.type per method), DELETE /users/{id}/authentication/phoneMethods/{id}
    (ReadWrite.All; ids 3179e48a-750b-4051-897c-87b9720928f7 mobile, b6332ec1-7057-4abe-9331-3d72feddfe41 alternateMobile,
    e37fc753-ff3b-4958-9484-eaa9425c82bc office; 204), DELETE .../microsoftAuthenticatorMethods/{id} (204), DELETE
    .../softwareOathMethods/{id} (204), and the overview page's list of method types and its re-register procedure.
    Not confirmed in the documentation, so read defensively: the delete path for FIDO2 keys (fido2Methods, the documented pattern; its page
    was not read), that the id of a phone entry in the methods list equals the phoneMethods id above (it is used only to order the
    deletions), whether an app-only token can delete a phone number that is the default MFA method, and that the
    user's methods list is updated within about 30 seconds (the check after the deletion reads up to 6 times, 5 seconds apart).
.PARAMETER TenantId
    The client tenant: its ID (a GUID) or a domain such as contoso.onmicrosoft.com. Required.
    Environment variable: TenantId
.PARAMETER ClientId
    The Application (client) ID of the app registration that holds the Graph permissions. Required.
    Environment variable: ClientId
.PARAMETER CertificateThumbprint
    Thumbprint of the app's certificate (private key in LocalMachine\My or CurrentUser\My). Preferred. When empty,
    the app secret is read from the environment variable ClientSecret (a secure/hidden RMM field; never an argument).
    Environment variable: CertificateThumbprint
.PARAMETER UserPrincipalName
    The user's sign-in name, for example ann@contoso.com. Required.
    Environment variable: UserPrincipalName
.PARAMETER RevokeSessions
    true to also revoke the user's sign-in sessions and refresh tokens in the same run. Default false.
    Environment variable: RevokeSessions
.PARAMETER DryRun
    true (the default for this script) to list the methods and change nothing. Real changes need DryRun=false and Approve=reset-user-mfa-methods.
    Environment variable: DryRun
.PARAMETER OutputFormat
    Text (default), Answer, Json or Csv. Environment variable: OutputFormat
.PARAMETER ExportPath
    Also write the rows to this .csv or .json file. Environment variable: ExportPath
.PARAMETER ResultField
    Also write the answer to this RMM custom field. Environment variable: ResultField
.EXAMPLE
    .\reset-user-mfa-methods.ps1 -TenantId contoso.onmicrosoft.com -ClientId 11111111-2222-3333-4444-555555555555 -CertificateThumbprint 0123456789ABCDEF0123456789ABCDEF01234567 -UserPrincipalName ann@contoso.com
    Dry run: lists the MFA methods Ann has registered.
.EXAMPLE
    .\reset-user-mfa-methods.ps1 -TenantId contoso.onmicrosoft.com -ClientId 11111111-2222-3333-4444-555555555555 -CertificateThumbprint 0123456789ABCDEF0123456789ABCDEF01234567 -UserPrincipalName ann@contoso.com -RevokeSessions true -DryRun false -Approve reset-user-mfa-methods
    Deletes Ann's phone, authenticator and security key methods and signs her out everywhere.
.NOTES
