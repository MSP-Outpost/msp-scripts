#Requires -Version 5.1
<#
.SYNOPSIS
    Resets an Active Directory user's password to a random value, stores it in a secure RMM field and makes the user change it at next sign-in.

.DESCRIPTION
    THIS SCRIPT CHANGES THINGS. For the one user in AccountName it:
    1. Sets a new random 20-character password (upper and lower case letters,
       digits and symbols, from the operating system's cryptographic random
       number generator).
    2. When ChangePasswordAtLogon is true (the default), makes the user choose a
       new password at the next sign-in (pwdLastSet = 0).
    3. When UnlockAccount is true (the default) and the account is locked out,
       unlocks it.

    THE PASSWORD IS NEVER PRINTED. It is not in the output, the answer, the
    data rows, the change log or an exported file. It is written only to the RMM
    custom field named by ResultField (NinjaOne, Datto RMM and Syncro are
    supported); make that a secure / secret field. Without ResultField, or on an
    RMM it cannot write to, the script refuses before changing anything.
    OutputFormat Answer is refused for the same reason. The password is written
    to the field BEFORE it is set, so a failed field write changes nothing.

    Second run: with ChangePasswordAtLogon true, an account that already must
    change its password at next sign-in is left alone and the script ends OK
    "Already pending" (the password in the field is still the one that works).
    Set ForceReset=true to issue a new password anyway. With
    ChangePasswordAtLogon false there is no such state, so every run issues a
    new password.

    Never touched: the built-in accounts (RIDs 500 to 503, including krbtgt) and
    anything marked as a critical system object. A password-never-expires account
    cannot be forced to change at next sign-in (Active Directory refuses): set
    ChangePasswordAtLogon=false for those. A disabled account gets the new
    password and stays disabled; the script never enables it.

    This script resets domain accounts only. For a local account use
    set-local-admin-password. Run it on a domain controller or a member server
    with the ActiveDirectory module (RSAT). Without the module it ends ERROR; on
    a computer that is not in a domain it ends SKIPPED.

.PARAMETER AccountName
    The user: the sign-in name (jsmith), DOMAIN\jsmith, or the user principal
    name. Required. (Named AccountName, not UserName: Windows already has an
    environment variable called USERNAME.)
    Environment variable: AccountName

.PARAMETER ChangePasswordAtLogon
    true to make the user change the password at next sign-in. Default true.
    Environment variable: ChangePasswordAtLogon

.PARAMETER UnlockAccount
    true to also unlock a locked-out account. Default true.
    Environment variable: UnlockAccount

.PARAMETER ForceReset
    true to issue a new password even when the user already must change it at
    next sign-in. Default false.
    Environment variable: ForceReset

.PARAMETER DryRun
    true to list what would be changed and change nothing. Default false.
    -WhatIf does the same. Environment variable: DryRun

.PARAMETER OutputFormat
    Text (default) or Json or Csv. Answer is refused because the run produces a
    password. Environment variable: OutputFormat

.PARAMETER ExportPath
    Also write the rows (never the password) to this .csv or .json file.
    Environment variable: ExportPath

.PARAMETER ResultField
    The RMM custom field that receives the password, a secure field. NinjaOne:
    the field name; Datto RMM: the UDF number 1-300; Syncro: the asset field.
    Required. Environment variable: ResultField

.EXAMPLE
    .\reset-ad-user-password.ps1 -AccountName jsmith -ResultField UserPassword

    Resets jsmith's password, stores it in the field and forces a change at next sign-in.

.EXAMPLE
    .\reset-ad-user-password.ps1 -AccountName svc-scan -ChangePasswordAtLogon false -ResultField 5

    Resets a service account's password without forcing a change.

.NOTES
