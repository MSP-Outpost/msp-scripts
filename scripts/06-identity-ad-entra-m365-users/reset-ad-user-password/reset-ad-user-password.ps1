# ---- Constants ------------------------------------------------------------
$UserProperties = @('Enabled', 'LockedOut', 'PasswordNeverExpires', 'pwdLastSet', 'isCriticalSystemObject')
$BuiltInSidPattern = '-(500|501|502|503)$'
$PasswordLength = 20

# ---- Functions ------------------------------------------------------------
function Assert-DomainMember {
    # SKIPPED when this computer is not in a domain, ERROR when the module is missing, else loads it.
    if (-not [bool](Get-CimInstance -ClassName Win32_ComputerSystem).PartOfDomain) {
        Complete-OutpostRun -Status 'SKIPPED' -Answer 'Skipped: this computer is not joined to an Active Directory domain.'
    }
    if (-not (Get-Module -ListAvailable -Name ActiveDirectory)) {
        Stop-OutpostRun -Message 'The ActiveDirectory PowerShell module was not found. On a domain controller run Install-WindowsFeature RSAT-AD-PowerShell; on a member server install the RSAT Active Directory tools. Then run again.'
    }
    Import-Module -Name ActiveDirectory
}

function Get-AdValue {
    # A property of an AD object, or $null when the object does not have it (strict mode throws on a missing one).
    param($Object, [string] $Name)
    $property = $Object.PSObject.Properties[$Name]
    if ($null -eq $property) { return $null }
    return $property.Value
}

function ConvertTo-LdapText {
    # Escapes a value for an LDAP filter (RFC 4515).
    param([string] $Text)
    return ($Text -replace '\\', '\5c' -replace '\*', '\2a' -replace '\(', '\28' -replace '\)', '\29')
}

function Find-AdUser {
    # One user by sign-in name, DOMAIN\name or UPN, or $null when there is none.
    param([string] $Name, [string[]] $Property)
    $clean = $Name -replace '^[^\\]+\\', ''
    $escaped = ConvertTo-LdapText -Text $clean
    $filter = "(&(objectCategory=person)(objectClass=user)(sAMAccountName=$escaped))"
    if ($clean -match '@') { $filter = "(&(objectCategory=person)(objectClass=user)(userPrincipalName=$escaped))" }
    $found = @(Get-ADUser -LDAPFilter $filter -Properties $Property)
    if ($found.Count -eq 0) { return $null }
    return $found[0]
}

function Get-RandomIndex {
    param($Generator, [int] $Count)
    $buffer = New-Object -TypeName byte[] -ArgumentList 4
    $Generator.GetBytes($buffer)
    return [int]([BitConverter]::ToUInt32($buffer, 0) % $Count)
}

function New-RandomPassword {
    # A random password with upper, lower, digit and symbol characters (no look-alike characters). Never printed.
    $sets = @('ABCDEFGHJKLMNPQRSTUVWXYZ', 'abcdefghijkmnpqrstuvwxyz', '23456789', '!@#%^&*-_=+')
    $all = $sets -join ''
    $generator = New-Object -TypeName System.Security.Cryptography.RNGCryptoServiceProvider
    try {
        $chars = New-Object -TypeName System.Collections.ArrayList
        foreach ($set in $sets) { [void]$chars.Add($set[(Get-RandomIndex -Generator $generator -Count $set.Length)]) }
        while ($chars.Count -lt $PasswordLength) { [void]$chars.Add($all[(Get-RandomIndex -Generator $generator -Count $all.Length)]) }
        for ($i = $chars.Count - 1; $i -gt 0; $i--) {
            $j = Get-RandomIndex -Generator $generator -Count ($i + 1)
            $swap = $chars[$i]
            $chars[$i] = $chars[$j]
            $chars[$j] = $swap
        }
        return (-join $chars)
    }
    finally { $generator.Dispose() }
}

# ---- Main -----------------------------------------------------------------
Start-OutpostRun
try {
    # Validate: every input read once, typed, into $Config. Nothing is changed before this is done.
    $Config = [pscustomobject]@{
        AccountName           = Read-OutpostText -Name 'AccountName' -Required
        ChangePasswordAtLogon = Read-OutpostBool -Name 'ChangePasswordAtLogon'
        UnlockAccount         = Read-OutpostBool -Name 'UnlockAccount'
        ForceReset            = Read-OutpostBool -Name 'ForceReset'
    }
    $fieldName = Get-OutpostRawInput -Name 'ResultField'
    Assert-OutpostSecretField
    if (-not (Test-OutpostAdmin)) {
        Stop-OutpostRun -Message 'This script needs administrator rights. Run it as SYSTEM from your RMM or from an elevated PowerShell.'
    }
    Assert-DomainMember

    # Detect
    $target = Find-AdUser -Name $Config.AccountName -Property $UserProperties
    if ($null -eq $target) {
        Stop-OutpostRun -Message "The user '$($Config.AccountName)' was not found in Active Directory. Check the spelling of AccountName (sign-in name, DOMAIN\name or UPN), then run again. Nothing was changed."
    }
    $samName = [string]$target.SamAccountName
    if ($target.SID.Value -match $BuiltInSidPattern -or [bool](Get-AdValue -Object $target -Name 'isCriticalSystemObject')) {
        Stop-OutpostRun -Message "$samName is a built-in or critical system account; this script never resets those. Reset it in Active Directory Users and Computers. Nothing was changed."
    }
    $userGuid = [string]$target.ObjectGUID
    $isEnabled = [bool](Get-AdValue -Object $target -Name 'Enabled')
    $isLockedOut = [bool](Get-AdValue -Object $target -Name 'LockedOut')
    $neverExpires = [bool](Get-AdValue -Object $target -Name 'PasswordNeverExpires')
    $oldPasswordSet = [long](Get-AdValue -Object $target -Name 'pwdLastSet')
    if ($Config.ChangePasswordAtLogon -and $neverExpires) {
        Stop-OutpostRun -Message "$samName has PasswordNeverExpires set, and Active Directory does not allow a forced change at next sign-in on such an account. Set ChangePasswordAtLogon=false, or clear the flag first. Nothing was changed."
    }
    if (-not $isEnabled) { Write-OutpostWarning -Text "$samName is disabled; the password is reset and the account stays disabled." }

    $isPending = ($oldPasswordSet -eq 0)
    $needsReset = (-not ($Config.ChangePasswordAtLogon -and $isPending)) -or $Config.ForceReset
    $needsUnlock = ($Config.UnlockAccount -and $isLockedOut)
    Write-OutpostLine -Text "$samName is $(if ($isEnabled) { 'enabled' } else { 'disabled' }), $(if ($isLockedOut) { 'locked out' } else { 'not locked out' }), $(if ($isPending) { 'must change the password at next sign-in' } else { 'has a current password' })."
    if (-not $needsReset -and -not $needsUnlock) {
        Complete-OutpostRun -Status 'OK' -Answer "Already pending: $samName must change the password at next sign-in; no new password issued (ForceReset=true issues one)"
    }

    # Act: the new password is written to the RMM field FIRST, then set; it is never printed.
    $state = @{ Password = '' }
    try {
        if ($needsReset) {
            $null = Invoke-OutpostChange -Item $samName -Change 'Set a new random password (written to the secure field, not shown)' -Action {
                $state.Password = New-RandomPassword
                Write-OutpostSecretField -Value $state.Password
                Set-ADAccountPassword -Identity $userGuid -Reset -NewPassword (ConvertTo-SecureString -String $state.Password -AsPlainText -Force)
            }
        }
        if ($needsReset -and $Config.ChangePasswordAtLogon) {
            $null = Invoke-OutpostChange -Item $samName -Change 'Require a password change at next sign-in' -Action {
                Set-ADUser -Identity $userGuid -ChangePasswordAtLogon $true
            }
        }
        if ($needsUnlock) {
            $null = Invoke-OutpostChange -Item $samName -Change 'Unlock the account' -Action {
                Unlock-ADAccount -Identity $userGuid
            }
        }
    }
    finally { $state.Password = '' }

    # Verify (skipped in a dry run: nothing was changed)
    if (-not $script:OutpostRun.DryRun) {
        $after = Get-ADUser -Identity $userGuid -Properties $UserProperties
        $failed = @()
        $newPasswordSet = [long](Get-AdValue -Object $after -Name 'pwdLastSet')
        if ($needsReset -and $Config.ChangePasswordAtLogon -and $newPasswordSet -ne 0) { $failed += 'the user is not required to change the password at next sign-in' }
        if ($needsReset -and -not $Config.ChangePasswordAtLogon -and $newPasswordSet -le $oldPasswordSet) { $failed += 'the password change time did not move' }
        if ($needsUnlock -and [bool](Get-AdValue -Object $after -Name 'LockedOut')) { $failed += 'the account is still locked out' }
        if ($failed.Count -gt 0) {
            Stop-OutpostRun -Message ("Resetting $samName did not finish: " + ($failed -join '; ') + ". If the password was reset, the new one is in field $fieldName. Run again with ForceReset=true.")
        }
    }

    # Finish
    $parts = @()
    if ($needsReset) { $parts += "Password for $samName reset" }
    else { $parts += $samName }
    if ($needsReset -and $Config.ChangePasswordAtLogon) { $parts += 'must change at next sign-in' }
    if ($needsUnlock) { $parts += 'unlocked' }
    if ($needsReset) { $parts += "password written to field $fieldName" }
    Complete-OutpostRun -Status 'CHANGED' -Answer ($parts -join '; ')
}
catch {
    Stop-OutpostRun -ErrorRecord $_
}
