#Requires -Version 5.1
<#
.SYNOPSIS
    Alerts when an Entra ID or hybrid-joined PC has a broken join, an expired device certificate or no sign-in token.

.DESCRIPTION
    THIS SCRIPT IS READ-ONLY. It runs dsregcmd /status and checks:

      * the join state: Entra ID joined, hybrid joined (domain and Entra ID),
        domain only, or neither (workgroup),
      * the device certificate's validity dates (an expired one means the PC
        can no longer authenticate to Entra ID),
      * whether the device key is protected by the TPM (shown, never alerted),
      * the tenant name and the MDM enrolment URL (shown),
      * in a user's context only: the signed-in user's Primary Refresh Token
        (AzureAdPrt) and its expiry. A joined PC whose user has no PRT cannot
        do single sign-on to Microsoft 365 and Teams.

    WHAT SYSTEM CAN SEE. The device facts are the same for every account, so
    they are read correctly when an RMM runs the script as SYSTEM. The
    Primary Refresh Token belongs to a signed-in user, and dsregcmd run as
    SYSTEM reports SYSTEM's own (always empty) token state, which would be a
    false alert. So when run as SYSTEM with someone signed in, the script runs
    dsregcmd inside that user's session (the runtime's Invoke-OutpostAsUser: a
    one-shot scheduled task for the user, deleted straight afterwards, with
    the user's rights only) and reads the PRT from that. With nobody signed
    in, or when that cannot be run, the PRT row says it was not checked and
    nothing is alerted. When the script is run directly as a user (an Intune
    remediation set to run with the logged-on credentials, or an RMM option
    to run as the logged-on user) it reads that user's own state. Only the
    console user, or the user of a desktop shell, is checked, not every
    signed-in user.

    The dsregcmd field names and YES/NO values are used as English text. They
    are identifiers, not translated resources, as far as the references
    show, but this has not been confirmed on a non-English Windows. If the
    AzureAdJoined field is not in the output, the script ends with an error
    rather than guessing.

    SKIPPED on a workgroup PC, and on a PC joined to a domain only (no
    Entra ID join to check). Set RequireEntraJoin to true to alert on those
    instead, for a fleet that must all be Entra ID joined or hybrid joined.

.PARAMETER RequireEntraJoin
    Alert, instead of skipping, when the PC is not Entra ID joined or hybrid
    joined (workgroup or domain only). true or false. Default false.
    Environment variable: RequireEntraJoin

.PARAMETER DryRun
    Reserved; ignored by Monitors.

.PARAMETER OutputFormat
    Text (default), Answer, Json or Csv. Environment variable: OutputFormat

.PARAMETER ExportPath
    Also write the rows to this .csv or .json file. Environment variable: ExportPath

.PARAMETER ResultField
    Also write the answer to this RMM custom field. Environment variable: ResultField

.EXAMPLE
    .\test-entra-join-health.ps1

    Checks the join and device certificate; checks the PRT too when run as a user.

.EXAMPLE
    .\test-entra-join-health.ps1 -RequireEntraJoin true

    Also alerts on a PC that is only in a workgroup or a domain.

