# ---- Constants ------------------------------------------------------------
$NetshPath = "$env:SystemRoot\System32\netsh.exe"
$IpconfigPath = "$env:SystemRoot\System32\ipconfig.exe"
$IpResetLogName = 'outpost-netsh-ip-reset.log'
$AddressWaitSeconds = 45
$BackupKeys = @(
    'HKLM:\SYSTEM\CurrentControlSet\Services\Tcpip\Parameters\Interfaces',
    'HKLM:\SYSTEM\CurrentControlSet\Services\WinSock2\Parameters'
)

# ---- Functions ------------------------------------------------------------
function Invoke-NetCommand {
    # Runs a native tool; a non-zero exit code is a failure that says which command.
    # -AllowExitOne is for the netsh resets: on Windows 10/11 they exit 1 even
    # though the reset worked (a protected key answers "Access is denied" and the
    # restart completes it). Any language: the exit code is what counts. English
    # "failed" lines are counted into a warning.
    param([string] $FilePath, [string[]] $Argument, [switch] $AllowExitOne)
    $ErrorActionPreference = 'Continue'
    $output = & $FilePath @Argument 2>&1
    $exitCode = $LASTEXITCODE
    $text = (@($output) -join "`n").Trim()
    if ($AllowExitOne -and ($exitCode -eq 0 -or $exitCode -eq 1)) {
        $failedCount = @($text -split "`n" | Where-Object { $_ -match 'Resetting .*failed' }).Count
        if ($failedCount -gt 0) {
            Write-OutpostWarning -Text "netsh $($Argument -join ' '): $failedCount step(s) reported 'failed / Access is denied' (a protected key, harmless); the restart completes the reset."
        }
        return
    }
    if ($exitCode -ne 0) {
        throw "$(Split-Path -Path $FilePath -Leaf) $($Argument -join ' ') failed with exit code $exitCode. $($text -replace '\s+', ' ')"
    }
}

function Get-DhcpAdapterName {
    @(Get-NetIPInterface -AddressFamily IPv4 -ErrorAction SilentlyContinue |
        Where-Object { $_.Dhcp -eq 'Enabled' -and $_.ConnectionState -eq 'Connected' -and $_.InterfaceAlias -notmatch 'Loopback' } |
        ForEach-Object { [string]$_.InterfaceAlias })
}

function Get-StaticAdapterName {
    @(Get-NetIPInterface -AddressFamily IPv4 -ErrorAction SilentlyContinue |
        Where-Object { $_.Dhcp -eq 'Disabled' -and $_.ConnectionState -eq 'Connected' -and $_.InterfaceAlias -notmatch 'Loopback' } |
        ForEach-Object { [string]$_.InterfaceAlias })
}

function Save-StaticAdapter {
    # The settings a TCP/IP reset may wipe, read before it runs.
    param([string] $Name)
    $addresses = @(Get-NetIPAddress -InterfaceAlias $Name -AddressFamily IPv4 -ErrorAction SilentlyContinue | Where-Object { $_.PrefixOrigin -eq 'Manual' })
    $route = Get-NetRoute -InterfaceAlias $Name -AddressFamily IPv4 -DestinationPrefix '0.0.0.0/0' -ErrorAction SilentlyContinue | Select-Object -First 1
    $dns = Get-DnsClientServerAddress -InterfaceAlias $Name -AddressFamily IPv4 -ErrorAction SilentlyContinue
    return [pscustomobject]@{
        Name      = $Name
        Addresses = @($addresses | ForEach-Object { [pscustomobject]@{ IPAddress = [string]$_.IPAddress; PrefixLength = [int]$_.PrefixLength } })
        Gateway   = if ($route -and $route.NextHop -ne '0.0.0.0') { [string]$route.NextHop } else { '' }
        DnsServers = if ($dns) { @($dns.ServerAddresses) } else { @() }
    }
}

function Restore-StaticAdapter {
    param([object] $Saved)
    Set-NetIPInterface -InterfaceAlias $Saved.Name -AddressFamily IPv4 -Dhcp Disabled
    $present = @(Get-NetIPAddress -InterfaceAlias $Saved.Name -AddressFamily IPv4 -ErrorAction SilentlyContinue | ForEach-Object { [string]$_.IPAddress })
    foreach ($address in $Saved.Addresses) {
        if ($present -notcontains $address.IPAddress) {
            $null = New-NetIPAddress -InterfaceAlias $Saved.Name -IPAddress $address.IPAddress -PrefixLength $address.PrefixLength
        }
    }
    if ($Saved.Gateway -ne '') {
        $route = Get-NetRoute -InterfaceAlias $Saved.Name -AddressFamily IPv4 -DestinationPrefix '0.0.0.0/0' -ErrorAction SilentlyContinue
        if (-not $route) { $null = New-NetRoute -InterfaceAlias $Saved.Name -DestinationPrefix '0.0.0.0/0' -NextHop $Saved.Gateway }
    }
    if ($Saved.DnsServers.Count -gt 0) { Set-DnsClientServerAddress -InterfaceAlias $Saved.Name -ServerAddresses $Saved.DnsServers }
}

function Test-StaticRestored {
    param([object] $Saved)
    $present = @(Get-NetIPAddress -InterfaceAlias $Saved.Name -AddressFamily IPv4 -ErrorAction SilentlyContinue | ForEach-Object { [string]$_.IPAddress })
    foreach ($address in $Saved.Addresses) { if ($present -notcontains $address.IPAddress) { return $false } }
    return $true
}

function Test-AdapterHasAddress {
    param([string] $Name)
    $addresses = @(Get-NetIPAddress -InterfaceAlias $Name -AddressFamily IPv4 -ErrorAction SilentlyContinue)
    return @($addresses | Where-Object { $_.IPAddress -notlike '169.254.*' }).Count -gt 0
}

# ---- Main -----------------------------------------------------------------
Start-OutpostRun
try {
    # Validate: every input read once, typed, into $Config.
    $Config = [pscustomobject]@{
        RenewDhcp  = Read-OutpostBool -Name 'RenewDhcp'
        ResetProxy = Read-OutpostBool -Name 'ResetProxy'
        AllowStaticAdapters = Read-OutpostBool -Name 'AllowStaticAdapters'
    }
    if (-not (Test-OutpostAdmin)) {
        Stop-OutpostRun -Message 'This script needs administrator rights. Run it as SYSTEM from your RMM or from an elevated PowerShell.'
    }
    if (-not (Test-Path -LiteralPath $NetshPath)) {
        Complete-OutpostRun -Status 'SKIPPED' -Answer 'Skipped: netsh.exe was not found.'
    }

    # Detect
    $dhcpAdapters = @()
    if ($Config.RenewDhcp) { $dhcpAdapters = @(Get-DhcpAdapterName) }
    $staticAdapters = @(Get-StaticAdapterName)
    Write-OutpostLine -Text "DHCP adapters to renew: $(if ($dhcpAdapters.Count -gt 0) { $dhcpAdapters -join ', ' } else { 'none' })."
    $savedStatic = @()
    if ($staticAdapters.Count -gt 0) {
        if (-not $Config.AllowStaticAdapters) {
            Stop-OutpostRun -Message "Connected adapter(s) with a static IPv4 address: $($staticAdapters -join ', '). The TCP/IP reset can wipe a static address and leave this PC off the network after the restart. Nothing was changed. Set AllowStaticAdapters to true to run anyway (the script then saves and restores the static settings), or reset the stack by hand with console access."
        }
        $savedStatic = @($staticAdapters | ForEach-Object { Save-StaticAdapter -Name $_ })
        foreach ($saved in $savedStatic) {
            Write-OutpostLine -Text "Static settings saved for $($saved.Name): $(($saved.Addresses | ForEach-Object { "$($_.IPAddress)/$($_.PrefixLength)" }) -join ', '); gateway $($saved.Gateway); DNS $($saved.DnsServers -join ', ')."
        }
    }
    $ipResetLog = Join-Path -Path ([System.IO.Path]::GetTempPath()) -ChildPath $IpResetLogName

    $planned = 3 + $savedStatic.Count + $dhcpAdapters.Count
    if ($Config.ResetProxy) { $planned++ }
    Assert-OutpostChangeLimit -Planned $planned

    # Back up the network configuration the reset rewrites (a real run only).
    foreach ($backupKey in $BackupKeys) {
        $backupPath = Backup-OutpostItem -Path $backupKey
        if ($backupPath) { Write-OutpostLine -Text "Backed up $backupKey to $backupPath (a .reg file; double-click or reg import to restore)." }
    }

    # Act: DHCP renew is last, so the network is back before the script ends.
    $null = Invoke-OutpostChange -Item 'Winsock' -Change 'netsh winsock reset' -Action {
        Invoke-NetCommand -FilePath $NetshPath -Argument @('winsock', 'reset') -AllowExitOne
    }
    $null = Invoke-OutpostChange -Item 'TCP/IP stack' -Change "netsh int ip reset (log $ipResetLog)" -Action {
        Invoke-NetCommand -FilePath $NetshPath -Argument @('int', 'ip', 'reset', $ipResetLog) -AllowExitOne
    }
    $null = Invoke-OutpostChange -Item 'DNS cache' -Change 'ipconfig /flushdns' -Action {
        Invoke-NetCommand -FilePath $IpconfigPath -Argument @('/flushdns')
    }
    if ($Config.ResetProxy) {
        $null = Invoke-OutpostChange -Item 'WinHTTP proxy' -Change 'netsh winhttp reset proxy' -Action {
            Invoke-NetCommand -FilePath $NetshPath -Argument @('winhttp', 'reset', 'proxy')
        }
    }
    foreach ($saved in $savedStatic) {
        $null = Invoke-OutpostChange -Item $saved.Name -Change 'Set the static IP settings again' -Action {
            Restore-StaticAdapter -Saved $saved
        }
    }
    foreach ($adapterName in $dhcpAdapters) {
        $null = Invoke-OutpostChange -Item $adapterName -Change 'Renew the DHCP lease' -Action {
            try { Invoke-NetCommand -FilePath $IpconfigPath -Argument @('/renew', $adapterName) }
            catch { Write-OutpostWarning -Text "Renew failed on ${adapterName}: $($_.Exception.Message)" }
        }
    }

    # Verify (skipped in a dry run: nothing was changed)
    if (-not $script:OutpostRun.DryRun) {
        foreach ($saved in $savedStatic) {
            if (-not (Test-StaticRestored -Saved $saved)) {
                Stop-OutpostRun -Message "The static IP settings of $($saved.Name) did not come back ($(($saved.Addresses | ForEach-Object { "$($_.IPAddress)/$($_.PrefixLength)" }) -join ', '), gateway $($saved.Gateway), DNS $($saved.DnsServers -join ', ')). Set them by hand now, before any restart."
            }
        }
        foreach ($adapterName in $dhcpAdapters) {
            $deadline = (Get-Date).AddSeconds($AddressWaitSeconds)
            while (-not (Test-AdapterHasAddress -Name $adapterName) -and (Get-Date) -lt $deadline) { Start-Sleep -Seconds 2 }
            if (-not (Test-AdapterHasAddress -Name $adapterName)) {
                Stop-OutpostRun -Message "$adapterName did not get an IPv4 address from DHCP after the renew. Check the cable or Wi-Fi and the DHCP server, then reboot (the resets finish at the restart)."
            }
        }
    }

    # Finish
    $parts = 'Reset Winsock and TCP/IP, flushed DNS'
    if ($Config.ResetProxy) { $parts += ', cleared the WinHTTP proxy' }
    if ($dhcpAdapters.Count -gt 0) { $parts += ", renewed $($dhcpAdapters.Count) DHCP lease(s)" }
    Complete-OutpostRun -Status 'CHANGED' -Answer "$parts; reboot needed to finish"
}
catch {
    Stop-OutpostRun -ErrorRecord $_
}
