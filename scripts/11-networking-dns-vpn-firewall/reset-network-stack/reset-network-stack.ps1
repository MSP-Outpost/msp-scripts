#Requires -Version 5.1
<#
.SYNOPSIS
    Resets the Windows network stack (Winsock, TCP/IP, DNS cache, DHCP leases) when the internet works but nothing loads.

.DESCRIPTION
    THIS SCRIPT CHANGES THINGS AND CAN DROP THE NETWORK. Because of that it
    defaults to a DRY RUN: set DryRun to false and Approve to reset-network-stack to make the changes. It:

      * resets Winsock (netsh winsock reset),
      * resets the TCP/IP stack (netsh int ip reset, log written to the
        Windows temp folder),
      * flushes the DNS cache (ipconfig /flushdns),
      * with ResetProxy, clears the machine-wide WinHTTP proxy
        (netsh winhttp reset proxy),
      * with RenewDhcp, last of all, renews the lease of every connected DHCP
        adapter (ipconfig /renew).

    WARNING: the machine briefly loses its network. A remote-control session
    or an RMM agent that runs over the network can disconnect while the
    leases are renewed; the script keeps running and finishes locally. The
    TCP/IP reset can clear static IP addresses, so the script REFUSES to run
    when a connected adapter has one, unless AllowStaticAdapters is true (it
    then saves and restores those settings). The Winsock reset only
    completes after a restart: the answer says "reboot needed to finish".
    The script never reboots.

    It does not touch firewall rules, VPN profiles, adapter drivers or the
    WinINET (per-user) proxy.

.PARAMETER RenewDhcp
    true to renew the lease of each connected DHCP adapter, last.
    Default true. Environment variable: RenewDhcp

.PARAMETER ResetProxy
    true to also clear the WinHTTP machine proxy. Default false.
    Environment variable: ResetProxy

.PARAMETER AllowStaticAdapters
    The script refuses to run while a connected adapter has a static IPv4
    address, because the TCP/IP reset can wipe it and leave a server off the
    network after the restart. true runs anyway: it saves each static adapter's
    address, prefix, gateway and DNS servers first, sets them again after the
    reset and checks them. Default false. Environment variable: AllowStaticAdapters

.PARAMETER DryRun
    Default true for this script. false to make the changes. -WhatIf does
    the same as true. Environment variable: DryRun

.PARAMETER OutputFormat
    Text (default), Answer, Json or Csv. Environment variable: OutputFormat

.PARAMETER ExportPath
    Also write the rows to this .csv or .json file. Environment variable: ExportPath

.PARAMETER ResultField
    Also write the answer to this RMM custom field. Environment variable: ResultField

.EXAMPLE
    .\reset-network-stack.ps1

    Dry run: lists every reset it would make and changes nothing.

.EXAMPLE
    .\reset-network-stack.ps1 -DryRun false -Approve reset-network-stack -ResetProxy true

    Resets the stack, clears the WinHTTP proxy and renews DHCP leases.

