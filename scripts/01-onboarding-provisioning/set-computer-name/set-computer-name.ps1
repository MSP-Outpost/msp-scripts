#Requires -Version 5.1
<#
.SYNOPSIS
    Renames a workgroup or Entra ID joined PC to a fixed name or a pattern such as PREFIX-SERIAL, without restarting.

.DESCRIPTION
    THIS SCRIPT CHANGES THINGS. It sets the computer name and nothing else:
    it does not restart the PC, change the domain, the DNS suffix, the RMM
    agent or any user. The new name takes effect at the next restart; until
    then Windows keeps the old name and the pending name is stored. The
    answer says a restart is needed (Reboot: Required).

    Give the name one of two ways. NewName is for ONE device: a NewName set
    site-wide in an RMM would try to give every PC the same name (a duplicate
    name breaks the network), so use Pattern for a fleet:

      * NewName: the exact name,
      * Pattern: a name built from tokens, for example {PREFIX}-{SERIAL}.
        {PREFIX} is the Prefix input. {SERIAL} is the BIOS serial number with
        everything except letters and digits removed, in capitals. When the
        name would be longer than 15 characters, the serial is shortened from
        the front (its last characters are kept, as they are the most
        distinct), and the rest of the pattern is never cut. A serial that is
        empty or a maker's placeholder ("To be filled by O.E.M.", "0",
        "Default string") is an error, because two PCs would get the same name.

    A computer name must be 1 to 15 characters: letters, digits and hyphens,
    not starting or ending with a hyphen, and not only digits (the NetBIOS
    limit). Names are stored in capitals by Windows; the comparison ignores
    case.

    Idempotent: when the PC already has the wanted name, or the rename is
    already queued for the next restart, it changes nothing and says so. When
    the PC has the wanted name but another rename is queued, the queued rename
    is cancelled by setting the wanted name again.

    SKIPPED on a PC joined to an Active Directory domain: renaming a domain
    computer needs domain credentials (and changes the AD account), which this
    script does not handle. Rename those from AD, or unjoin first. Needs
    administrator rights. Use DryRun=true to see the name it would set.

.PARAMETER NewName
    The exact new computer name. Do not combine with Pattern.
    Environment variable: NewName

.PARAMETER Pattern
    A name pattern with the tokens {PREFIX} and {SERIAL}, for example
    {PREFIX}-{SERIAL}. Do not combine with NewName. Other text in the pattern
    must be letters, digits or hyphens.
    Environment variable: Pattern

.PARAMETER Prefix
    Text for the {PREFIX} token: letters, digits and hyphens, up to 14
    characters. Required when the Pattern uses {PREFIX}.
    Environment variable: Prefix

.PARAMETER AllowServers
    Windows Server and domain controllers are skipped unless this is true,
    because renaming a server breaks what depends on its name. true or false.
    Default false.
    Environment variable: AllowServers

.PARAMETER DryRun
    true to print the rename that would be made and change nothing.
    -WhatIf means the same. Default false.

.PARAMETER OutputFormat
    Text (default), Answer, Json or Csv. Environment variable: OutputFormat

.PARAMETER ExportPath
    Also write the rows to this .csv or .json file. Environment variable: ExportPath

.PARAMETER ResultField
    Also write the answer to this RMM custom field. Environment variable: ResultField

.EXAMPLE
    .\set-computer-name.ps1 -NewName ACME-FRONTDESK1 -DryRun true

    Shows the rename without making it.

.EXAMPLE
    .\set-computer-name.ps1 -Pattern "{PREFIX}-{SERIAL}" -Prefix ACME

    Names the PC ACME- followed by its BIOS serial number (shortened to fit 15 characters).

