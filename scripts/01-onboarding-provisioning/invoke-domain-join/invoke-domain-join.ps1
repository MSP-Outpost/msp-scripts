#Requires -Version 5.1
<#
.SYNOPSIS
    Joins this PC to an Active Directory domain, into a chosen OU, with credentials from secure RMM fields and a restart you control.

.DESCRIPTION
    THIS SCRIPT CHANGES THINGS. Risk is High, so it is a dry run unless you set
    BOTH DryRun=false AND Approve=invoke-domain-join (typing the script name is
    the deliberate step). It runs ON THE PC that should join.

    What it does:
    1. Refuses a domain controller (ERROR). If the PC is already joined to
       DomainName it ends OK "Already joined" and changes nothing. If it is
       joined to a DIFFERENT domain it refuses (ERROR): it never moves a PC
       between domains; leave the old one first.
    2. Checks that DNS on this PC can find a domain controller of DomainName
       (the _ldap._tcp.dc._msdcs SRV record), so a PC with the wrong DNS fails
       early and clearly.
    3. Joins the domain with Add-Computer. The computer account is created in
       TargetOu when you set it, else in the domain's default Computers
       container. DomainController (a full DNS name, as Windows now requires
       for domain join) picks the controller to talk to.
    4. Checks Windows now reports the PC as a member of that domain.
    5. Restarts, depending on RestartMode: Never (default), IfNoUserSignedIn
       (restart in 60 seconds only when nobody is signed in) or Always (restart
       in 60 seconds, signed-in users or not). The restart is needed to finish
       the join; when it does not happen the answer says "restart needed".

    CREDENTIALS: JoinUser is the account allowed to join PCs (for example
    CONTOSO\svc-join or svc-join@contoso.com). JoinPassword is read from the
    environment variable JoinPassword ONLY, never from an argument: make it a
    secure / hidden field in your RMM. It is never printed, logged or stored.
    Give that account only the right to create computer accounts in TargetOu. A
    dry run does not need the password.

    Not checked: whether TargetOu exists (a PC outside the domain cannot read the
    directory); Windows then ends the join with an error that names the problem.
    Nothing is changed when the join fails.

.PARAMETER DomainName
    The domain's DNS name, e.g. contoso.com. Required.
    Environment variable: DomainName

.PARAMETER TargetOu
    The OU for the computer account, as a distinguished name, e.g.
    "OU=Workstations,DC=contoso,DC=com". Default empty: the default Computers
    container. Environment variable: TargetOu

.PARAMETER JoinUser
    The account that joins the PC, DOMAIN\user or user@domain. Required for a
    real run. Environment variable: JoinUser

.PARAMETER DomainController
    Full DNS name of the domain controller to join through, e.g.
    dc1.contoso.com. Default empty: Windows chooses.
    Environment variable: DomainController

.PARAMETER RestartMode
    Never (default), IfNoUserSignedIn or Always. Environment variable: RestartMode

.PARAMETER DryRun
    Default TRUE for this script: lists every change and makes none. To join, set
    DryRun=false AND Approve=invoke-domain-join (Approve is read by the runtime).
    -WhatIf does the same. Environment variable: DryRun

.PARAMETER OutputFormat
    Text (default), Answer, Json or Csv. Environment variable: OutputFormat

.PARAMETER ExportPath
    Also write the rows to this .csv or .json file. Environment variable: ExportPath

.PARAMETER ResultField
    Also write the answer to this RMM custom field. Environment variable: ResultField

.EXAMPLE
    .\invoke-domain-join.ps1 -DomainName contoso.com -TargetOu "OU=Workstations,DC=contoso,DC=com"

    Dry run: shows that the PC would join contoso.com into the Workstations OU.

.EXAMPLE
    .\invoke-domain-join.ps1 -DomainName contoso.com -JoinUser CONTOSO\svc-join -RestartMode IfNoUserSignedIn -DryRun false -Approve invoke-domain-join

    Joins for real (JoinPassword comes from the environment) and restarts when nobody is signed in.

