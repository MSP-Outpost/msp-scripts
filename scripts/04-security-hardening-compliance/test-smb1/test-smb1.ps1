#Requires -Version 5.1
<#
.SYNOPSIS
    Alerts when the old, unsafe SMBv1 protocol is still switched on (server, optional feature or client), and lists who still uses it.

.DESCRIPTION
    THIS SCRIPT IS READ-ONLY. It checks three places SMB1 can be on:

      * the SMB server setting (Get-SmbServerConfiguration, EnableSMB1Protocol),
      * the Windows optional features SMB1Protocol, SMB1Protocol-Client and
        SMB1Protocol-Server (Enabled or EnablePending is on),
      * the SMB1 client driver mrxsmb10 (its driver file is present and its
        service is not disabled).

    Any of them on is an alert. With AuditDays above 0 it also reads the SMB
    server audit log (Microsoft-Windows-SMBServer/Audit, event 3000, "SMB1
    access") for that many days and lists the client addresses that still used
    SMB1, with how many times. Turning that auditing on is not this script's
    job: when it is off the script says so, and an empty list then means
    "unknown", not "nobody". Enable it with
    Set-SmbServerConfiguration -AuditSmb1Access $true, wait a few weeks, then
    read this list before running disable-smb1.

    After disable-smb1 the SMB1 client driver file stays until the next
    restart, so the client line can still alert until then.

.PARAMETER AuditDays
    How many days of the SMB1 access audit log to read. Whole number 0 to 365;
    0 skips the audit. Default 7. Environment variable: AuditDays

.PARAMETER DryRun
    Reserved; ignored by Monitors.

.PARAMETER OutputFormat
    Text (default), Answer, Json or Csv. Environment variable: OutputFormat

.PARAMETER ExportPath
    Also write the rows to this .csv or .json file. Environment variable: ExportPath

.PARAMETER ResultField
    Also write the answer to this RMM custom field. Environment variable: ResultField

.EXAMPLE
    .\test-smb1.ps1

    Alerts when SMB1 is on anywhere, and lists clients seen using it in the last 7 days.

.EXAMPLE
    .\test-smb1.ps1 -AuditDays 30 -OutputFormat Json

    Reads 30 days of the audit log and prints one JSON object.

