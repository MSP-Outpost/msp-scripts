# ---- Constants ------------------------------------------------------------
$LanmanServerKey = 'HKLM:\SYSTEM\CurrentControlSet\Services\LanmanServer\Parameters'
$ClientDriverKey = 'HKLM:\SYSTEM\CurrentControlSet\Services\mrxsmb10'
$ClientDriverFile = 'drivers\mrxsmb10.sys'
$ServiceStartDisabled = 4
$AuditEventId = 3000
$MaxClientRows = 25
$MaxClientsInAnswer = 3

# ---- Functions ------------------------------------------------------------
function Get-AuditLogName {
    # A function, not a constant: the checker reads Word-Word in Constants as a command name.
    return 'Microsoft-Windows-SMBServer/Audit'
}

function Get-RegistryValueOrNull {
    param([string] $Path, [string] $Name)
    if (-not (Test-Path -LiteralPath $Path)) { return $null }
    $item = Get-ItemProperty -LiteralPath $Path -ErrorAction SilentlyContinue
    if ($null -eq $item) { return $null }
    $property = $item.PSObject.Properties[$Name]
    if ($null -eq $property) { return $null }
    return $property.Value
}

function Get-Smb1Feature {
    # The SMB1Protocol optional features and their state. Throws when DISM cannot answer.
    $found = @()
    foreach ($feature in @(Get-WindowsOptionalFeature -Online | Where-Object { $_.FeatureName -like 'SMB1Protocol*' })) {
        $found += [pscustomobject]@{ Name = [string]$feature.FeatureName; State = [string]$feature.State }
    }
    return $found
}

function Test-ClientDriverPresent {
    $systemDir = [Environment]::GetFolderPath('System')
    if (-not $systemDir) { $systemDir = 'C:\Windows\System32' }
    if (-not (Test-Path -LiteralPath (Join-Path -Path $systemDir -ChildPath $ClientDriverFile))) { return $false }
    if (-not (Test-Path -LiteralPath $ClientDriverKey)) { return $false }
    $start = Get-RegistryValueOrNull -Path $ClientDriverKey -Name 'Start'
    return ($null -eq $start) -or ([int]$start -ne $ServiceStartDisabled)
}

function Get-Smb1AuditClient {
    # Clients that logged event 3000 in the last $Days days: Address, Count, LastUtc, newest first.
    param([int] $Days)
    $auditEvents = @()
    try {
        $auditEvents = @(Get-WinEvent -FilterHashtable @{ LogName = (Get-AuditLogName); Id = $AuditEventId; StartTime = (Get-Date).AddDays(-$Days) })
    }
    catch {
        if ($_.FullyQualifiedErrorId -notlike 'NoMatchingEventsFound*') { throw }
    }
    $byAddress = @{}
    foreach ($auditEvent in $auditEvents) {
        $address = 'unknown'
        if ($auditEvent.Properties.Count -gt 0) { $address = ([string]$auditEvent.Properties[0].Value) -replace '^::ffff:', '' }
        $time = $auditEvent.TimeCreated.ToUniversalTime()
        if (-not $byAddress.ContainsKey($address)) { $byAddress[$address] = [pscustomobject]@{ Address = $address; Count = 0; LastUtc = $time } }
        $entry = $byAddress[$address]
        $entry.Count++
        if ($time -gt $entry.LastUtc) { $entry.LastUtc = $time }
    }
    return @($byAddress.Values | Sort-Object -Property LastUtc -Descending)
}

# ---- Main -----------------------------------------------------------------
Start-OutpostRun
try {
    # Validate
    $Config = [pscustomobject]@{
        AuditDays = Read-OutpostInt -Name 'AuditDays' -Min 0 -Max 365
    }
    if (-not (Test-OutpostAdmin)) {
        Stop-OutpostRun -Message 'Administrator rights are required to read the SMB settings. Run the script as SYSTEM or an administrator.'
    }

    # Detect
    Write-OutpostLine -Text 'Checking the SMB1 server setting, the optional features and the SMB1 client driver.'
    $problems = @()
    $featureError = ''
    $features = @()
    try { $features = @(Get-Smb1Feature) } catch { $featureError = $_.Exception.Message }
    $enabledFeatures = @($features | Where-Object { @('Enabled', 'EnablePending') -contains $_.State })

    $serverSetting = $null
    try { $serverSetting = [bool](Get-SmbServerConfiguration).EnableSMB1Protocol }
    catch {
        $registryValue = Get-RegistryValueOrNull -Path $LanmanServerKey -Name 'SMB1'
        $serverSetting = if ($null -ne $registryValue) { ([int]$registryValue -ne 0) } else { ($enabledFeatures.Count -gt 0) }
        Write-OutpostWarning -Text "Get-SmbServerConfiguration failed ($($_.Exception.Message)); the server setting was read from the registry."
    }
    $serverDetail = if ($serverSetting) { 'EnableSMB1Protocol is True' } else { 'EnableSMB1Protocol is False' }
    Add-OutpostRow -Values @{ Check = 'SMB1 server'; Item = 'Server setting'; Detail = $serverDetail; Problem = $serverSetting }
    if ($serverSetting) { $problems += 'SMB1 server is enabled' }

    if ($featureError -ne '') {
        Write-OutpostWarning -Text "Could not read the optional features: $featureError"
        Add-OutpostRow -Values @{ Check = 'SMB1 feature'; Item = 'Optional features'; Detail = 'unreadable'; Problem = $false }
    }
    elseif ($features.Count -eq 0) {
        Add-OutpostRow -Values @{ Check = 'SMB1 feature'; Item = 'Optional features'; Detail = 'not present on this Windows'; Problem = $false }
    }
    foreach ($feature in $features) {
        $isOn = $enabledFeatures -contains $feature
        Add-OutpostRow -Values @{ Check = 'SMB1 feature'; Item = $feature.Name; Detail = $feature.State; Problem = $isOn }
    }
    if ($enabledFeatures.Count -gt 0) {
        $problems += 'SMB1 optional feature ' + (($enabledFeatures | ForEach-Object { $_.Name }) -join ', ') + ' is enabled'
    }

    $clientOn = Test-ClientDriverPresent
    $clientDetail = if ($clientOn) { 'driver file present and service not disabled' } else { 'driver absent or disabled' }
    Add-OutpostRow -Values @{ Check = 'SMB1 client'; Item = 'mrxsmb10 driver'; Detail = $clientDetail; Problem = $clientOn }
    if ($clientOn) { $problems += 'SMB1 client driver (mrxsmb10) is present' }

    # Detect: who still uses SMB1
    $auditText = ''
    if ($Config.AuditDays -gt 0) {
        $auditOn = $false
        try { $auditOn = [bool](Get-SmbServerConfiguration).AuditSmb1Access } catch { $auditOn = $false }
        $logExists = $null -ne (Get-WinEvent -ListLog (Get-AuditLogName) -ErrorAction SilentlyContinue)
        if (-not $logExists) {
            Add-OutpostRow -Values @{ Check = 'SMB1 audit'; Item = 'Audit log'; Detail = 'log not available on this Windows'; Problem = $false }
            $auditText = 'SMB1 audit log not available'
        }
        else {
            $auditDetail = if ($auditOn) { 'on' } else { 'off: enable with Set-SmbServerConfiguration -AuditSmb1Access $true' }
            Add-OutpostRow -Values @{ Check = 'SMB1 audit'; Item = 'AuditSmb1Access'; Detail = $auditDetail; Problem = $false }
            $clients = @(Get-Smb1AuditClient -Days $Config.AuditDays)
            $shown = 0
            foreach ($client in $clients) {
                if ($shown -ge $MaxClientRows) { break }
                $lastText = $client.LastUtc.ToString('yyyy-MM-ddTHH:mm:ssZ', [Globalization.CultureInfo]::InvariantCulture)
                Add-OutpostRow -Values @{ Check = 'SMB1 client use'; Item = $client.Address; Detail = "$($client.Count) events, last $lastText"; Problem = $false }
                $shown++
            }
            if ($clients.Count -gt 0) {
                $topNames = @($clients | Select-Object -First $MaxClientsInAnswer | ForEach-Object { $_.Address }) -join ', '
                $auditText = "$($clients.Count) client(s) used SMB1 in the last $($Config.AuditDays) days ($topNames)"
            }
            elseif ($auditOn) { $auditText = "no SMB1 client access in the last $($Config.AuditDays) days" }
            else { $auditText = 'SMB1 auditing is off, so client use is unknown' }
        }
    }

    # Finish
    if ($problems.Count -gt 0) {
        $alertParts = @($problems)
        if ($auditText -ne '') { $alertParts += $auditText }
        Complete-OutpostRun -Status 'ALERT' -Answer ($alertParts -join '; ')
    }
    $okText = if ($featureError -ne '') { 'SMB1 is disabled (server setting and client; optional features unreadable)' } else { 'SMB1 is disabled (server, optional features and client)' }
    if ($auditText -ne '') { $okText = "$okText; $auditText" }
    Complete-OutpostRun -Status 'OK' -Answer $okText
}
catch {
    Stop-OutpostRun -ErrorRecord $_
}
