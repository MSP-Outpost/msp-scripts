#Requires -Version 5.1
<#
.SYNOPSIS
    Turns on Microsoft's recommended Defender attack surface reduction (ASR) rules in Audit or Block mode.

.DESCRIPTION
    THIS SCRIPT CHANGES THINGS. It applies a fixed set of 14 Microsoft Defender
    attack surface reduction rules (the three "standard protection" rules plus
    the other rules Microsoft recommends for most PCs; the list is written
    out in the script with names) to Audit or Block mode with
    Add-MpPreference, and reports each rule before and after:

      * Audit (the default) only logs what the rule would have blocked, so
        nothing breaks. Run in Audit first, read the events with the ASR
        report, then run again with Mode Block.
      * Block stops the behaviour. Office macro and script rules can stop
        line-of-business software that relies on them: audit first.

    A rule that is already at or stricter than the wanted mode is left alone:
    Audit never lowers a rule that is on Block (or Warn). ExcludeRules lists
    rule IDs to leave exactly as they are. The rule "Block process creations
    originating from PSExec and WMI commands" is not in the set because RMM
    tools and software deployment use those paths.

    It is skipped when Microsoft Defender is not the active antivirus
    (passive mode, or another antivirus is registered in Windows Security
    Center), because the rules do nothing there. It stops with an error when
    Defender is off: run repair-defender first. Rules pushed by Intune or
    Group Policy win over this script; if one does not take, the run ends in
    an error naming it. It never touches exclusions, Controlled Folder Access
    or any other Defender setting.

.PARAMETER Mode
    Audit (default) or Block. Environment variable: Mode

.PARAMETER ExcludeRules
    Rule IDs (GUIDs from the list in this script) to leave unchanged,
    separated by commas. Default none. Environment variable: ExcludeRules

.PARAMETER DryRun
    true to list what would be changed and change nothing. Default false.
    -WhatIf does the same. Environment variable: DryRun

.PARAMETER OutputFormat
    Text (default), Answer, Json or Csv. Environment variable: OutputFormat

.PARAMETER ExportPath
    Also write the rows to this .csv or .json file. Environment variable: ExportPath

.PARAMETER ResultField
    Also write the answer to this RMM custom field. Environment variable: ResultField

.EXAMPLE
    .\set-defender-asr-rules.ps1 -DryRun true

    Lists the rules that would be set to Audit.

.EXAMPLE
    .\set-defender-asr-rules.ps1 -Mode Block -ExcludeRules 9e6c4e1f-7d60-472f-ba1a-a39ef669e4b2

    Moves every rule to Block except credential stealing from LSASS.

