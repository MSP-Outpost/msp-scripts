# ---- Functions ------------------------------------------------------------
function Get-PropertyOrNull {
    param($Source, [string] $Name)
    if ($null -eq $Source) { return $null }
    $property = $Source.PSObject.Properties[$Name]
    if ($null -eq $property) { return $null }
    return $property.Value
}

function Get-OtherAntivirus {
    # Names of enabled antivirus products other than Defender (workstations only).
    $names = @()
    try {
        foreach ($product in @(Get-CimInstance -Namespace 'root/SecurityCenter2' -ClassName 'AntivirusProduct')) {
            $isDefender = $product.displayName -like 'Windows Defender*' -or $product.displayName -like 'Microsoft Defender*'
            $isOn = (([int]$product.productState -band $ProductStateOnMask) -eq $ProductStateOn)
            if ($isOn -and -not $isDefender) { $names += [string]$product.displayName }
        }
    }
    catch {
        Write-OutpostWarning -Text "Could not read Windows Security Center: $($_.Exception.Message)"
    }
    return $names
}

function Get-AsrState {
    # Rule ID (lower case) -> action number, as Defender reports it now.
    $preference = Get-MpPreference
    $ids = @(Get-PropertyOrNull -Source $preference -Name 'AttackSurfaceReductionRules_Ids')
    $actions = @(Get-PropertyOrNull -Source $preference -Name 'AttackSurfaceReductionRules_Actions')
    $result = @{}
    for ($i = 0; $i -lt $ids.Count; $i++) {
        if ($null -ne $ids[$i] -and $i -lt $actions.Count -and $null -ne $actions[$i]) {
            $result[([string]$ids[$i]).ToLowerInvariant()] = [int]$actions[$i]
        }
    }
    return $result
}

function Get-ActionText {
    param($Action)
    if ($null -eq $Action) { return 'Off' }
    switch ([int]$Action) {
        0 { return 'Off' }
        1 { return 'Block' }
        2 { return 'Audit' }
        6 { return 'Warn' }
        default { return "Action $Action" }
    }
}

# ---- Main -----------------------------------------------------------------
Start-OutpostRun
try {
    # Validate
    $knownIds = @($AsrRules | ForEach-Object { [string]$_.Id })
    $excludedIds = @()
    foreach ($text in @(Read-OutpostList -Name 'ExcludeRules')) {
        if ($knownIds -notcontains $text.ToLowerInvariant()) {
            Stop-OutpostInput -Name 'ExcludeRules' -Value $text -Expected ('rule IDs from this list, separated by commas: ' + ($knownIds -join ', '))
        }
        $excludedIds += $text.ToLowerInvariant()
    }
    $Config = [pscustomobject]@{
        Mode         = Read-OutpostChoice -Name 'Mode' -Allowed @('Audit', 'Block')
        ExcludeRules = $excludedIds
    }
    if (-not (Test-OutpostAdmin)) {
        Stop-OutpostRun -Message 'Administrator rights are required to change Defender settings. Run the script as SYSTEM or an administrator.'
    }
    if (-not (Get-Command -Name 'Get-MpPreference' -ErrorAction SilentlyContinue)) {
        Complete-OutpostRun -Status 'SKIPPED' -Answer 'Skipped: Microsoft Defender is not installed on this PC.'
    }

    # Detect: is Defender the active antivirus?
    $osInfo = Get-CimInstance -ClassName Win32_OperatingSystem
    $isWorkstation = ($osInfo.ProductType -eq $WorkstationProductType)
    $minBuild = if ($isWorkstation) { $MinWorkstationBuild } else { $MinServerBuild }
    if ([int]$osInfo.BuildNumber -lt $minBuild) {
        Complete-OutpostRun -Status 'SKIPPED' -Answer "Skipped: attack surface reduction needs Windows 10 1709 or Windows Server 2019 or later (this is build $($osInfo.BuildNumber))."
    }
    if ($isWorkstation) {
        $others = @(Get-OtherAntivirus)
        if ($others.Count -gt 0) {
            Complete-OutpostRun -Status 'SKIPPED' -Answer ('Skipped: ' + ($others -join ', ') + ' is the active antivirus, so Defender ASR rules would do nothing.')
        }
    }
    $status = $null
    $statusError = ''
    try { $status = Get-MpComputerStatus } catch { $statusError = $_.Exception.Message }
    if ($null -eq $status -and -not $isWorkstation) {
        Complete-OutpostRun -Status 'SKIPPED' -Answer "Skipped: Defender is not answering ($statusError); on a server another antivirus usually turns it off, so it is not the active antivirus."
    }
    if ($null -eq $status) {
        Stop-OutpostRun -Message "Microsoft Defender is not answering ($statusError). Run repair-defender, then run this again."
    }
    $runningMode = [string](Get-PropertyOrNull -Source $status -Name 'AMRunningMode')
    if ($runningMode -like '*Passive*' -or $runningMode -like '*EDR Block*') {
        Complete-OutpostRun -Status 'SKIPPED' -Answer "Skipped: Defender is in $runningMode mode (another product is the active antivirus), so ASR rules would do nothing."
    }
    if (-not [bool](Get-PropertyOrNull -Source $status -Name 'AntivirusEnabled') -and -not $isWorkstation) {
        Complete-OutpostRun -Status 'SKIPPED' -Answer 'Skipped: Defender Antivirus is off on this server; another antivirus is probably the active one, so ASR rules would do nothing.'
    }
    if (-not [bool](Get-PropertyOrNull -Source $status -Name 'AntivirusEnabled')) {
        Stop-OutpostRun -Message 'Microsoft Defender Antivirus is turned off and no other antivirus is active. Run repair-defender first, then run this again.'
    }

    # Detect: where each rule is now
    $targetName = if ($Config.Mode -eq 'Block') { 'Enabled' } else { 'AuditMode' }
    $before = Get-AsrState
    Write-OutpostLine -Text "Mode $($Config.Mode): checking $($AsrRules.Count) attack surface reduction rules."
    $plan = @()
    $unchangedCount = 0
    $excludedCount = 0
    foreach ($rule in $AsrRules) {
        $ruleId = [string]$rule.Id
        $current = $null
        if ($before.ContainsKey($ruleId)) { $current = $before[$ruleId] }
        $currentText = Get-ActionText -Action $current
        if ($Config.ExcludeRules -contains $ruleId) {
            Add-OutpostRow -Values @{ Item = $rule.Name; Change = "Excluded, stays $currentText"; Result = 'Skipped' }
            $excludedCount++
            continue
        }
        if ($Config.Mode -eq 'Block') { $isDone = ($current -eq $ActionBlock) }
        else { $isDone = ($current -eq $ActionBlock -or $current -eq $ActionAudit -or $current -eq $ActionWarn) }
        if ($isDone) {
            Add-OutpostRow -Values @{ Item = $rule.Name; Change = "No change, already $currentText"; Result = 'Already set' }
            $unchangedCount++
            continue
        }
        $plan += [pscustomobject]@{ Id = $ruleId; Name = [string]$rule.Name; CurrentText = $currentText }
    }

    if ($plan.Count -eq 0) {
        Complete-OutpostRun -Status 'OK' -Answer "Already set: $unchangedCount rule(s) at $($Config.Mode) or stricter, $excludedCount excluded."
    }

    # Act
    if (-not $script:OutpostRun.DryRun -and (Test-Path -LiteralPath $AsrRegistryKey)) {
        $null = Backup-OutpostItem -Path $AsrRegistryKey
    }
    foreach ($item in $plan) {
        $ruleId = $item.Id
        $null = Invoke-OutpostChange -Item $item.Name -Change "$($item.CurrentText) -> $($Config.Mode)" -Action {
            Add-MpPreference -AttackSurfaceReductionRules_Ids $ruleId -AttackSurfaceReductionRules_Actions $targetName
        }
    }

    # Verify (skipped in a dry run: nothing was changed)
    if (-not $script:OutpostRun.DryRun) {
        $after = Get-AsrState
        $failed = @()
        foreach ($item in $plan) {
            $now = $null
            if ($after.ContainsKey($item.Id)) { $now = $after[$item.Id] }
            $ok = if ($Config.Mode -eq 'Block') { $now -eq $ActionBlock } else { $now -eq $ActionAudit -or $now -eq $ActionBlock -or $now -eq $ActionWarn }
            if (-not $ok) { $failed += "$($item.Name) (now $(Get-ActionText -Action $now))" }
        }
        if ($failed.Count -gt 0) {
            Stop-OutpostRun -Message ("$($failed.Count) rule(s) did not take effect: " + ($failed -join '; ') + '. Intune, Group Policy or tamper protection may be setting them; change them there.')
        }
    }

    # Finish
    $excludedText = if ($excludedCount -gt 0) { ", $excludedCount excluded" } else { '' }
    Complete-OutpostRun -Status 'CHANGED' -Answer "ASR rules set to $($Config.Mode): $($plan.Count) changed, $unchangedCount already set$excludedText"
}
catch {
    Stop-OutpostRun -ErrorRecord $_
}
