#Requires -Version 5.1
<#
.SYNOPSIS
    Turns on the Domain, Private and Public Windows Firewall profiles and sets default inbound to Block, unless Group Policy controls them.

.DESCRIPTION
    THIS SCRIPT CHANGES THINGS. It reads the Domain, Private and Public
    firewall profiles twice: as they are in force (the active store, which
    includes Group Policy and MDM) and as they are set on this PC (the
    persistent store). For each profile that is off, or that allows inbound
    connections by default, it:

      * saves the firewall policy first: a registry export of
        HKLM\SYSTEM\CurrentControlSet\Services\SharedAccess\Parameters\FirewallPolicy
        and a netsh export (firewall-policy.wfw, restorable with
        "netsh advfirewall import") in the MSPOutpost backup folder,
      * turns the profile on and, when BlockInbound is true, sets its default
        inbound action to Block,
      * starts the Windows Defender Firewall service (MpsSvc) when it is
        stopped.

    It changes the local settings only. When Group Policy (or MDM) sets a
    value that is not what is wanted, that profile is reported as "managed by
    Group Policy" and left alone: the script never fights a policy. It never
    adds, edits or deletes a firewall rule and never changes outbound
    defaults. It does not look at third-party firewall products: use
    test-firewall-profiles to see those.

    It is skipped on servers unless AllowServers is true, and when Windows
    Security Center lists an enabled firewall product that is not Microsoft's
    (that product is doing the job).

    Inbound Block is Windows' own default; turning it back on does not remove
    any Allow rule, so the remote desktop, file sharing and other rules that
    are enabled stay enabled.

.PARAMETER BlockInbound
    true (default) to also set the default inbound action of each profile to
    Block; false to only turn the profiles on. Environment variable: BlockInbound

.PARAMETER AllowServers
    false (default): on a server the script does nothing and says so, because
    blocking inbound on a server that ran with the firewall off can cut off
    SQL and line-of-business ports. true to act on servers too (check the
    open ports first). Environment variable: AllowServers

.PARAMETER DryRun
    true to list what would be changed and change nothing. Default false.
    -WhatIf does the same. Environment variable: DryRun

.PARAMETER OutputFormat
    Text (default), Answer, Json or Csv. Environment variable: OutputFormat

.PARAMETER ExportPath
    Also write the rows to this .csv or .json file. Environment variable: ExportPath

.PARAMETER ResultField
    Also write the answer to this RMM custom field. Environment variable: ResultField

.EXAMPLE
    .\enable-windows-firewall.ps1 -DryRun true

    Lists the profiles it would turn on or set to Block inbound.

.EXAMPLE
    .\enable-windows-firewall.ps1 -BlockInbound false

    Turns profiles on but leaves their default inbound action as it is.

