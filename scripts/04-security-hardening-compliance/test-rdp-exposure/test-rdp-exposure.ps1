$TerminalServerKey = 'HKLM:\SYSTEM\CurrentControlSet\Control\Terminal Server'
$RdpTcpKey = 'HKLM:\SYSTEM\CurrentControlSet\Control\Terminal Server\WinStations\RDP-Tcp'
$PolicyKey = 'HKLM:\SOFTWARE\Policies\Microsoft\Windows NT\Terminal Services'
$DefaultPort = 3389
$AnyAddressWords = @('Any', '*', 'Internet')
$LocalAddressWords = @('LocalSubnet', 'Intranet', 'DefaultGateway', 'DHCP', 'DNS', 'WINS', 'PlayToDevice')
$MaxRuleRows = 25

# ---- Functions ------------------------------------------------------------
function Get-RegistryValueOrNull {
    param([string] $Path, [string] $Name)
    if (-not (Test-Path -LiteralPath $Path)) { return $null }
    $item = Get-ItemProperty -LiteralPath $Path -ErrorAction SilentlyContinue
    if ($null -eq $item) { return $null }
    $property = $item.PSObject.Properties[$Name]
    if ($null -eq $property) { return $null }
    return $property.Value
}

function Get-EffectiveValue {
    # Group Policy value first, then the local one, then $Default. Returns an int.
    param([string] $PolicyName, [string] $LocalKey, [string] $LocalName, [int] $Default)
    $policyValue = Get-RegistryValueOrNull -Path $PolicyKey -Name $PolicyName
    if ($null -ne $policyValue) { return [int]$policyValue }
    $localValue = Get-RegistryValueOrNull -Path $LocalKey -Name $LocalName
    if ($null -ne $localValue) { return [int]$localValue }
    return $Default
}

function Test-PortInSpec {
    # True when a firewall port spec ("3389", "5000-5100", "Any", "RPC") covers $Port.
    param([string] $Spec, [int] $Port)
    if ($Spec -match '^\d+$') { return ([int]$Spec -eq $Port) }
    if ($Spec -match '^(\d+)-(\d+)$') { return ([int]$Matches[1] -le $Port -and $Port -le [int]$Matches[2]) }
    return $false
}

function ConvertTo-AddressRange {
    # "10.0.0.0/24", "10.0.0.0/255.255.255.0", "10.0.0.5", "10.0.0.1-10.0.0.9" or an IPv6 form ->
    # Low and High as fixed-width hex text (so they compare as text); $null when it is not an address.
    param([string] $Text)
    $value = $Text.Trim()
    $lowBytes = $null
    $highBytes = $null
    if ($value -match '^([^/]+)-([^/]+)$') {
        $first = $null
        $last = $null
        if (-not (Test-AddressText -Text $Matches[1]) -or -not (Test-AddressText -Text $Matches[2])) { return $null }
        if (-not [Net.IPAddress]::TryParse($Matches[1], [ref]$first) -or -not [Net.IPAddress]::TryParse($Matches[2], [ref]$last)) { return $null }
        $lowBytes = [byte[]]$first.GetAddressBytes()
        $highBytes = [byte[]]$last.GetAddressBytes()
        if ($lowBytes.Length -ne $highBytes.Length) { return $null }
    }
    else {
        $addressText = $value
        $prefixText = $null
        if ($value -match '^([^/]+)/(.+)$') { $addressText = $Matches[1]; $prefixText = $Matches[2] }
        if (-not (Test-AddressText -Text $addressText)) { return $null }
        $address = $null
        if (-not [Net.IPAddress]::TryParse($addressText, [ref]$address)) { return $null }
        $bytes = [byte[]]$address.GetAddressBytes()
        $bits = $bytes.Length * 8
        $prefix = $bits
        if ($null -ne $prefixText) {
            if ($prefixText -match '^\d+$') { $prefix = [int]$prefixText }
            else {
                $mask = $null
                if (-not (Test-AddressText -Text $prefixText) -or -not [Net.IPAddress]::TryParse($prefixText, [ref]$mask)) { return $null }
                $prefix = 0
                foreach ($maskByte in $mask.GetAddressBytes()) {
                    foreach ($bit in 7..0) { if ((([int]$maskByte -shr $bit) -band 1) -eq 1) { $prefix++ } }
                }
            }
            if ($prefix -gt $bits) { return $null }
        }
        $lowBytes = [byte[]]$bytes.Clone()
        $highBytes = [byte[]]$bytes.Clone()
        for ($i = 0; $i -lt $bytes.Length; $i++) {
            $bitsInByte = [math]::Max(0, [math]::Min(8, $prefix - ($i * 8)))
            $maskValue = (255 -shl (8 - $bitsInByte)) -band 255
            $lowBytes[$i] = [byte]([int]$bytes[$i] -band $maskValue)
            $highBytes[$i] = [byte]([int]$bytes[$i] -bor (255 - $maskValue))
        }
    }
    return [pscustomobject]@{ Low = [BitConverter]::ToString($lowBytes); High = [BitConverter]::ToString($highBytes) }
}

function Test-AddressText {
    # Dotted IPv4 or an IPv6 text; refuses the short forms ("10.1", "3389") IPAddress would accept.
    param([string] $Text)
    if ($Text -match ':') { return ($Text -match '^[0-9A-Fa-f:.%]+$') }
    return ($Text -match '^\d{1,3}(\.\d{1,3}){3}$')
}

function Get-RuleExposure {
    # Why a rule's remote addresses are a problem; an empty array when they are fine.
    param([string[]] $Addresses, $AllowedRanges)
    $reasons = @()
    foreach ($address in $Addresses) {
        $text = $address.Trim()
        if ($AnyAddressWords -contains $text) { $reasons += "any address ($text)"; continue }
        if ($LocalAddressWords -contains $text) { continue }
        $range = ConvertTo-AddressRange -Text $text
        if ($null -eq $range) { continue }
        if ($range.Low -match '^(00-?)+$' -and $range.High -match '^(FF-?)+$') { $reasons += "any address ($text)"; continue }
        if (@($AllowedRanges).Count -eq 0) { continue }
        $isCovered = $false
        foreach ($allowed in @($AllowedRanges)) {
            if ($allowed.Low.Length -eq $range.Low.Length -and [string]::CompareOrdinal($allowed.Low, $range.Low) -le 0 -and [string]::CompareOrdinal($range.High, $allowed.High) -le 0) { $isCovered = $true; break }
        }
        if (-not $isCovered) { $reasons += "$text is outside AllowedSources" }
    }
    return $reasons
}

# ---- Main -----------------------------------------------------------------
Start-OutpostRun
try {
    # Validate
    $allowedRanges = @()
    foreach ($text in @(Read-OutpostList -Name 'AllowedSources')) {
        $range = ConvertTo-AddressRange -Text $text
        if ($null -eq $range) {
            Stop-OutpostInput -Name 'AllowedSources' -Value $text -Expected 'IP addresses, CIDR blocks (10.0.0.0/24) or ranges (10.0.0.1-10.0.0.9) separated by commas'
        }
        $allowedRanges += $range
    }
    $Config = [pscustomobject]@{
        AllowedSources = $allowedRanges
    }
    if (-not (Test-OutpostAdmin)) {
        Stop-OutpostRun -Message 'Administrator rights are required to read firewall rules. Run the script as SYSTEM or an administrator.'
    }
    if (-not (Get-Command -Name 'Get-NetFirewallPortFilter' -ErrorAction SilentlyContinue)) {
        Stop-OutpostRun -Message 'The NetSecurity module (Get-NetFirewallPortFilter) was not found. This needs Windows 10, 11 or Server 2016 or later.'
    }

    # Detect: settings
    Write-OutpostLine -Text 'Checking Remote Desktop settings and the firewall rules for its port.'
    $deny = Get-EffectiveValue -PolicyName 'fDenyTSConnections' -LocalKey $TerminalServerKey -LocalName 'fDenyTSConnections' -Default 1
    $rdpOn = ($deny -eq 0)
    $nla = Get-EffectiveValue -PolicyName 'UserAuthentication' -LocalKey $RdpTcpKey -LocalName 'UserAuthentication' -Default 0
    $nlaRequired = ($nla -eq 1)
    $layer = Get-EffectiveValue -PolicyName 'SecurityLayer' -LocalKey $RdpTcpKey -LocalName 'SecurityLayer' -Default 1
    $port = [int](Get-RegistryValueOrNull -Path $RdpTcpKey -Name 'PortNumber')
    if ($port -lt 1 -or $port -gt 65535) { $port = $DefaultPort }
    $layerText = switch ($layer) { 0 { 'RDP security (weak)' } 1 { 'negotiate' } 2 { 'TLS' } default { "layer $layer" } }
    $nlaProblem = $rdpOn -and -not $nlaRequired
    $problems = @()

    Add-OutpostRow -Values @{ Check = 'Remote Desktop'; Item = 'Connections'; Detail = $(if ($rdpOn) { 'allowed (on)' } else { 'not allowed (off)' }); Problem = $false }
    Add-OutpostRow -Values @{ Check = 'NLA'; Item = 'Network Level Authentication'; Detail = $(if ($nlaRequired) { 'required' } else { 'not required' }); Problem = $nlaProblem }
    Add-OutpostRow -Values @{ Check = 'Port'; Item = 'RDP-Tcp'; Detail = "TCP $port"; Problem = $false }
    Add-OutpostRow -Values @{ Check = 'Security layer'; Item = 'RDP-Tcp'; Detail = $layerText; Problem = $false }

    # Detect: firewall rules for the port (only when Remote Desktop is on)
    $exposedNames = @()
    $offProfiles = @()
    $exposedAny = $false
    if ($rdpOn) {
        $listening = $false
        try { $listening = (@(Get-NetTCPConnection -LocalPort $port -State Listen -ErrorAction SilentlyContinue).Count -gt 0) } catch { $listening = $false }
        Add-OutpostRow -Values @{ Check = 'Listening'; Item = "TCP $port"; Detail = $(if ($listening) { 'listening' } else { 'not listening yet' }); Problem = $false }
        foreach ($firewallProfile in @(Get-NetFirewallProfile -PolicyStore ActiveStore)) {
            if (([string]$firewallProfile.Enabled) -eq 'False') { $offProfiles += [string]$firewallProfile.Name }
        }
        Add-OutpostRow -Values @{ Check = 'Firewall profile'; Item = 'Windows Firewall'; Detail = $(if ($offProfiles.Count -gt 0) { 'off: ' + ($offProfiles -join ', ') } else { 'on' }); Problem = ($offProfiles.Count -gt 0) }
        $ruleRows = 0
        $portFilters = @(Get-NetFirewallPortFilter -PolicyStore ActiveStore | Where-Object { @($_.LocalPort).Count -gt 0 })
        foreach ($portFilter in $portFilters) {
            if (@('TCP', '6') -notcontains ([string]$portFilter.Protocol)) { continue }
            $covers = $false
            foreach ($spec in @($portFilter.LocalPort | ForEach-Object { [string]$_ })) {
                if (Test-PortInSpec -Spec $spec -Port $port) { $covers = $true; break }
            }
            if (-not $covers) { continue }
            $rule = Get-NetFirewallRule -AssociatedNetFirewallPortFilter $portFilter -PolicyStore ActiveStore
            if (([string]$rule.Enabled) -ne 'True' -or ([string]$rule.Direction) -ne 'Inbound' -or ([string]$rule.Action) -ne 'Allow') { continue }
            $addresses = @((Get-NetFirewallAddressFilter -AssociatedNetFirewallRule $rule -PolicyStore ActiveStore).RemoteAddress | ForEach-Object { [string]$_ })
            $reasons = @(Get-RuleExposure -Addresses $addresses -AllowedRanges $Config.AllowedSources)
            if ($reasons.Count -eq 0) { continue }
            $exposedNames += [string]$rule.DisplayName
            if (@($reasons | Where-Object { $_ -like 'any address*' }).Count -gt 0) { $exposedAny = $true }
            if ($ruleRows -lt $MaxRuleRows) {
                Add-OutpostRow -Values @{ Check = 'Firewall rule'; Item = [string]$rule.DisplayName; Detail = ("TCP $port from " + ($addresses -join ',') + ", profile $($rule.Profile): " + ($reasons -join ', ')); Problem = $true }
                $ruleRows++
            }
        }
        if ($exposedNames.Count -eq 0) {
            Add-OutpostRow -Values @{ Check = 'Firewall rule'; Item = "TCP $port"; Detail = 'no enabled inbound rule open to any address'; Problem = $false }
        }
    }
    else {
        Add-OutpostRow -Values @{ Check = 'Firewall rule'; Item = "TCP $port"; Detail = 'not checked: Remote Desktop is off'; Problem = $false }
    }

    # Finish
    if ($exposedNames.Count -gt 0) {
        $nameText = (@($exposedNames | Select-Object -Unique) -join ', ')
        if ($exposedAny) { $problems += "RDP is on and reachable from any address via $nameText; restrict the rule's RemoteAddress" }
        else { $problems += "RDP is on and reachable from addresses outside AllowedSources via $nameText" }
    }
    if ($offProfiles.Count -gt 0) { $problems += ('RDP is on and the firewall is off for the ' + ($offProfiles -join ', ') + ' profile(s)') }
    if ($nlaProblem) { $problems += 'NLA is not required' }
    if ($problems.Count -gt 0) {
        Complete-OutpostRun -Status 'ALERT' -Answer ($problems -join '; ')
    }
    if ($rdpOn) {
        Complete-OutpostRun -Status 'OK' -Answer "RDP is on (port $port, NLA required, $layerText security); no inbound rule open to any address."
    }
    Complete-OutpostRun -Status 'OK' -Answer "RDP is off (port $port)"
}
catch {
    Stop-OutpostRun -ErrorRecord $_
}
