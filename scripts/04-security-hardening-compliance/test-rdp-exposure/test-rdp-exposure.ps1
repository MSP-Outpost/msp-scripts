#Requires -Version 5.1
<#
.SYNOPSIS
    Alerts when Remote Desktop is on and reachable from any address, or on without Network Level Authentication.

.DESCRIPTION
    THIS SCRIPT IS READ-ONLY. It reads, as Windows enforces them (a Group
    Policy value wins over the local one):

      * whether Remote Desktop connections are allowed (fDenyTSConnections),
      * whether Network Level Authentication is required (UserAuthentication),
      * the listening port (RDP-Tcp PortNumber) and the RDP security layer
        (SecurityLayer: 0 RDP security, 1 negotiate, 2 TLS),
      * when Remote Desktop is on: every enabled inbound Allow rule in the
        active firewall store (domain Group Policy included) for that TCP
        port, and the remote addresses each rule accepts.

    It alerts when Remote Desktop is on AND (a rule accepts Any address,
    Internet or a 0.0.0.0/0 range, or, when AllowedSources is set, accepts an
    address outside it), or when Remote Desktop is on and NLA is not
    required. The keywords LocalSubnet, Intranet, DefaultGateway, DHCP, DNS
    and WINS are treated as local and are fine. A rule is counted when it
    names the RDP port; rules that open every port and Block rules are not evaluated.
    A firewall profile that is off while Remote Desktop is on also alerts. A weak security layer (0) is shown but does
    not alert on its own.

.PARAMETER AllowedSources
    Addresses, CIDR blocks (10.0.0.0/24) or ranges (10.0.0.1-10.0.0.9) from
    which Remote Desktop is acceptable, separated by commas. When set, a rule
    that accepts any address outside them alerts. Default none (only
    Any/Internet alerts). Environment variable: AllowedSources

.PARAMETER DryRun
    Reserved; ignored by Monitors.

.PARAMETER OutputFormat
    Text (default), Answer, Json or Csv. Environment variable: OutputFormat

.PARAMETER ExportPath
    Also write the rows to this .csv or .json file. Environment variable: ExportPath

.PARAMETER ResultField
    Also write the answer to this RMM custom field. Environment variable: ResultField

.EXAMPLE
    .\test-rdp-exposure.ps1

    Alerts when RDP is on and open to any address or runs without NLA.

.EXAMPLE
    .\test-rdp-exposure.ps1 -AllowedSources "10.9.0.0/24,192.168.1.10"

    Also alerts when an RDP rule accepts addresses outside the management range.

