$FixedDriveType = 3
$HomeSkus = @(98, 99, 100, 101)
$PolicyKey = 'HKLM:\SOFTWARE\Policies\Microsoft\FVE'
$EscrowEventId = 845

# ---- Functions ------------------------------------------------------------
function ConvertTo-DriveName {
    param([Parameter(Mandatory = $true)][string] $Text)
    if ($Text -notmatch '^([A-Za-z]):?\\?$') {
        Stop-OutpostInput -Name 'Drives' -Value $Text -Expected 'drive letters such as C: or D: separated by commas'
    }
    return ($Matches[1].ToUpperInvariant() + ':')
}

function Invoke-NativeText {
    # Runs a program and returns its output lines. stderr is folded in without
    # raising: under $ErrorActionPreference Stop Windows PowerShell 5.1 would throw.
    param([Parameter(Mandatory = $true)][string] $FilePath, [string[]] $Arguments)
    $savedPreference = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try { return @(& $FilePath @Arguments 2>&1 | ForEach-Object { "$_" }) }
    finally { $ErrorActionPreference = $savedPreference }
}

function Get-EscrowEventText {
    # The XML of each event 845 (language independent; .Message can be null).
    $texts = @()
    try {
        foreach ($entry in @(Get-WinEvent -FilterHashtable @{ LogName = 'Microsoft-Windows-BitLocker/BitLocker Management'; Id = $EscrowEventId } -MaxEvents 200 -ErrorAction Stop)) {
            try { $texts += [string]$entry.ToXml() } catch { $null = $_ }
        }
    }
    catch { $null = $_ }
    return $texts
}

function Test-AdBackupPolicy {
    if (-not (Test-Path -LiteralPath $PolicyKey)) { return $false }
    $policy = Get-ItemProperty -LiteralPath $PolicyKey
    foreach ($name in @('ActiveDirectoryBackup', 'OSActiveDirectoryBackup', 'FDVActiveDirectoryBackup')) {
        $property = $policy.PSObject.Properties[$name]
        if ($property -and [string]$property.Value -eq '1') { return $true }
    }
    return $false
}

function Get-ProtectionLabel {
    # Protection Off can mean decrypted, still encrypting, or encrypted with the
    # protectors suspended or waiting for activation: say which.
    param([string] $Protection, [int] $Percent)
    if ($Protection -ne 'Off') { return $Protection }
    if ($Percent -ge 100) { return 'Encrypted, protection off' }
    if ($Percent -gt 0) { return 'Encrypting' }
    return 'Off'
}

function Get-EncryptableLetter {
    # Drive letters BitLocker can protect, including volumes Windows lists as removable (some VHDs).
    try {
        return @(Get-CimInstance -Namespace 'root\CIMV2\Security\MicrosoftVolumeEncryption' -ClassName Win32_EncryptableVolume -ErrorAction Stop |
            Where-Object { $_.DriveLetter } | ForEach-Object { ([string]$_.DriveLetter).ToUpperInvariant() })
    }
    catch { return @() }
}

function Get-VolumeState {
    # One object per drive: from Get-BitLockerVolume, else from manage-bde.exe.
    param([Parameter(Mandatory = $true)][string] $Drive, [Parameter(Mandatory = $true)][string] $OsDrive)
    $type = if ($Drive -eq $OsDrive) { 'OperatingSystem' } else { 'Data' }
    $volume = $null
    if (Get-Command -Name 'Get-BitLockerVolume' -ErrorAction SilentlyContinue) {
        try { $volume = Get-BitLockerVolume -MountPoint $Drive -ErrorAction Stop } catch { $volume = $null }
    }
    if ($volume) {
        $protectorTypes = @($volume.KeyProtector | ForEach-Object { [string]$_.KeyProtectorType })
        $recoveryIds = @($volume.KeyProtector | Where-Object { [string]$_.KeyProtectorType -eq 'RecoveryPassword' } | ForEach-Object { [string]$_.KeyProtectorId })
        $percent = [int][math]::Round([double]$volume.EncryptionPercentage, 0)
        $protection = [string]$volume.ProtectionStatus
        $protection = Get-ProtectionLabel -Protection $protection -Percent $percent
        $method = [string]$volume.EncryptionMethod
        if ($method -eq '') { $method = 'None' }
        return [pscustomobject]@{ Drive = $Drive; Type = $type; Protection = $protection; Percent = $percent; Method = $method; ProtectorTypes = $protectorTypes; RecoveryIds = $recoveryIds }
    }

    $exe = Join-Path -Path ([Environment]::SystemDirectory) -ChildPath 'manage-bde.exe'
    if (-not (Test-Path -LiteralPath $exe)) { return $null }
    $status = @(Invoke-NativeText -FilePath $exe -Arguments @('-status', $Drive))
    $protection = 'Unknown'
    $percent = 0
    $method = 'None'
    foreach ($line in $status) {
        if ($line -match 'Protection Status:\s*Protection (On|Off)') { $protection = $Matches[1] }
        elseif ($line -match 'Percentage Encrypted:\s*([0-9.,]+)\s*%') { $percent = [int][math]::Round([double]::Parse(($Matches[1] -replace ',', '.'), [Globalization.CultureInfo]::InvariantCulture), 0) }
        elseif ($line -match 'Encryption Method:\s*(.+?)\s*$') { $method = $Matches[1] }
    }
    $protection = Get-ProtectionLabel -Protection $protection -Percent $percent
    if ($protection -eq 'Unknown') { return $null }
    $protectorTypes = @()
    foreach ($line in (Invoke-NativeText -FilePath $exe -Arguments @('-protectors', '-get', $Drive))) {
        if ($line -match '^\s+([^:]+):\s*$') { $protectorTypes += ($Matches[1].Trim() -replace 'Numerical Password', 'RecoveryPassword') }
    }
    $recoveryIds = @()
    foreach ($line in (Invoke-NativeText -FilePath $exe -Arguments @('-protectors', '-get', $Drive, '-type', 'recoverypassword'))) {
        if ($line -match '\{([0-9A-Fa-f-]{36})\}') { $recoveryIds += $Matches[1] }
    }
    if ($recoveryIds.Count -gt 0 -and $protectorTypes -notcontains 'RecoveryPassword') { $protectorTypes += 'RecoveryPassword' }
    return [pscustomobject]@{ Drive = $Drive; Type = $type; Protection = $protection; Percent = $percent; Method = $method; ProtectorTypes = $protectorTypes; RecoveryIds = $recoveryIds }
}

function Get-EscrowEvidence {
    # 'Entra ID', 'Unknown (AD)', 'None found' or 'n/a' (no recovery password to escrow).
    param($State, [string[]] $EscrowTexts, [bool] $IsDomainJoined, [bool] $HasAdPolicy)
    if ($State.RecoveryIds.Count -eq 0) { return 'n/a' }
    foreach ($text in $EscrowTexts) {
        foreach ($id in $State.RecoveryIds) {
            if ($text.IndexOf($id.Trim('{', '}'), [StringComparison]::OrdinalIgnoreCase) -ge 0) { return 'Entra ID' }
        }
    }
    if ($IsDomainJoined -and $HasAdPolicy) { return 'Unknown (AD)' }
    return 'None found'
}

# ---- Main -----------------------------------------------------------------
Start-OutpostRun
try {
    # Validate: every input read once, typed, into $Config.
    $Config = [pscustomobject]@{
        RequireEscrow = Read-OutpostBool -Name 'RequireEscrow'
        Drives        = @(Read-OutpostList -Name 'Drives' | ForEach-Object { ConvertTo-DriveName -Text $_ })
    }
    if (-not (Test-OutpostAdmin)) {
        Stop-OutpostRun -Message 'This script needs administrator rights. Run it as SYSTEM from your RMM or from an elevated PowerShell.'
    }
    $osInfo = Get-CimInstance -ClassName Win32_OperatingSystem
    if ($HomeSkus -contains [int]$osInfo.OperatingSystemSKU) {
        Complete-OutpostRun -Status 'SKIPPED' -Answer 'Skipped: BitLocker is not available on Windows Home editions.'
    }
    $manageBde = Join-Path -Path ([Environment]::SystemDirectory) -ChildPath 'manage-bde.exe'
    if (-not (Get-Command -Name 'Get-BitLockerVolume' -ErrorAction SilentlyContinue) -and -not (Test-Path -LiteralPath $manageBde)) {
        Complete-OutpostRun -Status 'SKIPPED' -Answer 'Skipped: the BitLocker tools are not installed on this PC.'
    }
    $osDrive = $env:SystemDrive
    if (-not $osDrive) { $osDrive = 'C:' }
    $osDrive = $osDrive.ToUpperInvariant()

    $fixedDrives = @(Get-CimInstance -ClassName Win32_LogicalDisk -Filter "DriveType = $FixedDriveType" | ForEach-Object { $_.DeviceID.ToUpperInvariant() } | Sort-Object)
    $allowedDrives = @($fixedDrives + @(Get-EncryptableLetter) | Sort-Object -Unique)
    foreach ($name in $Config.Drives) {
        if ($allowedDrives -notcontains $name) {
            if (-not (Test-Path -LiteralPath ($name + '\'))) {
                Stop-OutpostInput -Name 'Drives' -Value $name -Expected ("a drive that exists: $name was not found on this PC (BitLocker-capable drives: " + ($allowedDrives -join ', ') + ')')
            }
            Stop-OutpostInput -Name 'Drives' -Value $name -Expected ('a drive BitLocker can protect on this PC (' + ($allowedDrives -join ', ') + ')')
        }
    }
    $checked = if ($Config.Drives.Count -gt 0) { @($Config.Drives | Sort-Object -Unique) } else { $fixedDrives }

    # Detect
    Write-OutpostLine -Text ('Checking BitLocker on ' + ($checked -join ', ') + '.')
    $escrowTexts = @(Get-EscrowEventText)
    $isDomainJoined = [bool](Get-CimInstance -ClassName Win32_ComputerSystem).PartOfDomain
    $hasAdPolicy = Test-AdBackupPolicy

    $problems = @()
    $protectedDrives = @()
    $escrowNotes = @()
    foreach ($drive in $checked) {
        $state = Get-VolumeState -Drive $drive -OsDrive $osDrive
        if (-not $state) {
            Stop-OutpostRun -Message "Could not read BitLocker state for $drive (Get-BitLockerVolume failed and manage-bde output was not English). Run 'manage-bde -status $drive' to see why."
        }
        $hasRecovery = $state.RecoveryIds.Count -gt 0
        $escrow = Get-EscrowEvidence -State $state -EscrowTexts $escrowTexts -IsDomainJoined $isDomainJoined -HasAdPolicy $hasAdPolicy
        Add-OutpostRow -Values @{
            Volume              = $drive
            Type                = $state.Type
            Protection          = $state.Protection
            EncryptionPercent   = $state.Percent
            Method              = $state.Method
            Protectors          = ($state.ProtectorTypes -join ', ')
            HasRecoveryPassword = $hasRecovery
            Escrow              = $escrow
        }

        $isOs = $state.Type -eq 'OperatingSystem'
        $isNamed = $Config.Drives -contains $drive
        if ($state.Protection -eq 'On') {
            $protectedDrives += $drive
            if (-not $hasRecovery) { $problems += "$drive has no recovery password" }
            elseif ($Config.RequireEscrow -and $escrow -eq 'None found') { $problems += "$drive recovery key not escrowed" }
            elseif ($escrow -ne 'n/a') { $escrowNotes += $escrow }
        }
        elseif ($isOs -or $isNamed) {
            $problems += "$drive BitLocker $($state.Protection.ToLowerInvariant())"
        }
    }

    # Finish
    if ($problems.Count -gt 0) {
        Complete-OutpostRun -Status 'ALERT' -Answer ($problems -join '; ')
    }
    if ($protectedDrives.Count -eq 0) {
        Complete-OutpostRun -Status 'OK' -Answer ('No BitLocker protection required on ' + ($checked -join ', ') + '.')
    }
    $escrowText = @($escrowNotes | Sort-Object -Unique) -join '/'
    if ($escrowText -eq '') { $escrowText = 'not checked' }
    Complete-OutpostRun -Status 'OK' -Answer ('BitLocker ON for ' + ($protectedDrives -join ', ') + '; recovery key escrow: ' + $escrowText)
}
catch {
    Stop-OutpostRun -ErrorRecord $_
}
