#Requires -Version 5.1
<#
.SYNOPSIS
    Alerts when BitLocker is off on the OS drive or a recovery key is missing or not escrowed.

.DESCRIPTION
    THIS SCRIPT IS READ-ONLY. For every fixed volume it reads the BitLocker
    protection status, encryption percentage, encryption method and key
    protectors, and whether a recovery password protector exists. It then looks
    for evidence that the recovery key was escrowed:

      * Entra ID (Azure AD): event 845 in the "Microsoft-Windows-BitLocker/BitLocker
        Management" log whose data contains one of the volume's CURRENT recovery
        password IDs (read from the event XML, so it works in any language and
        an old event from before a key rotation does not count).
      * Active Directory: the key is stored in the msFVE-RecoveryInformation
        object, which a PC cannot read about itself. On a domain-joined PC with
        the Group Policy for AD backup switched on, the escrow is reported as
        "Unknown (AD)" and does NOT raise an alert, because it cannot be proven
        either way from here. Check it in AD Users and Computers or Entra.

    It alerts (exit 1) when the OS drive is not protected, when a protected or
    named volume has no recovery password, or, only when you switch
    RequireEscrow on, when a volume's key is provably not escrowed (no event
    845 and no AD policy). Keys stored by MBAM or by your RMM are invisible to
    this check, which is why RequireEscrow is off by default: turn it on only
    where keys are escrowed to Entra ID or AD.
    Unprotected data volumes are reported but alert only when you name them in
    Drives.

    Uses Get-BitLockerVolume, and manage-bde.exe (English output) when the
    cmdlet is missing. Skipped on Windows Home editions and on PCs without the
    BitLocker tools. Needs administrator rights.

.PARAMETER RequireEscrow
    true to alert when a recovery key has no escrow evidence. Only meaningful
    when keys are escrowed to Entra ID or AD. Default false: check only
    protection and the recovery password.
    Environment variable: RequireEscrow

.PARAMETER Drives
    Drive letters to check, separated by commas, e.g. "C:, D:". Default empty:
    every fixed drive. A letter that BitLocker cannot protect on this PC
    (not a fixed drive or an encryptable volume) is an error.
    Environment variable: Drives

.PARAMETER DryRun
    Reserved; ignored by Monitors.

.PARAMETER OutputFormat
    Text (default), Answer, Json or Csv. Environment variable: OutputFormat

.PARAMETER ExportPath
    Also write the rows to this .csv or .json file. Environment variable: ExportPath

.PARAMETER ResultField
    Also write the answer to this RMM custom field. Environment variable: ResultField

.EXAMPLE
    .\test-bitlocker-status.ps1

    Alerts when the OS drive is unprotected or its key is not escrowed.

.EXAMPLE
    .\test-bitlocker-status.ps1 -RequireEscrow true -Drives "C:, D:"

    Checks C: and D: for protection, a recovery password and escrow evidence.

