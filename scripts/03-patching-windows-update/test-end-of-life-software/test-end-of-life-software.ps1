#Requires -Version 5.1
<#
.SYNOPSIS
    Alerts when software past its end of support is installed, and says what to do about each one.

.DESCRIPTION
    THIS SCRIPT IS READ-ONLY. It compares the machine-wide installed-programs
    list (64-bit and 32-bit) with a built-in list of products whose vendor
    stopped issuing security fixes, and checks the Windows version itself.

    The built-in list is deliberately short and clear-cut: Adobe Flash Player,
    Adobe Shockwave Player, Microsoft Silverlight, Apple QuickTime for
    Windows, consumer Skype (retired 2025-05-05), Adobe Reader older than DC,
    Java 6 and Java 7, Python 2, Skype for Business, Microsoft Office, Visio and Project 2007,
    2010 and 2013, Office 2016 and 2019 (support ended 2025-10-14), and
    Internet Explorer 11 when its Windows feature is still switched on
    (not on Windows 10 LTSC or IoT, where IE11 is supported with the OS). The
    Windows row appears for Windows 11 releases past end of
    service (21H2, 22H2, 23H2 and 24H2, Home/Pro and Enterprise/Education
    dates differ), Windows 10 (support ended 2025-10-14, except the
    LTSC editions), Windows 8.1 and older, and Windows Server 2012 R2 and
    older. Set IncludeOs to false for PCs that have bought Extended Security
    Updates.

    ExtraNames adds your own names (for example a line-of-business tool that
    is retired); a match there says the software is on your own list.

    ALERT when anything is found; every finding is a row with what to do.
    OK otherwise. Per-user installs are not in the list this reads.

.PARAMETER ExtraNames
    Extra application names to treat as end-of-life, comma or semicolon
    separated. * and ? work; a name without a wildcard matches anywhere in
    the name. Each needs at least 3 letters besides wildcards. Default empty.
    Environment variable: ExtraNames

.PARAMETER IncludeOs
    true to also alert when Windows itself is out of support. Default true.
    Environment variable: IncludeOs

.PARAMETER OutputFormat
    Text (default), Answer, Json or Csv. Environment variable: OutputFormat

.PARAMETER ExportPath
    Also write the rows to this .csv or .json file. Environment variable: ExportPath

.PARAMETER ResultField
    Also write the answer to this RMM custom field. Environment variable: ResultField

.EXAMPLE
    .\test-end-of-life-software.ps1

    Checks the built-in list and Windows itself.

.EXAMPLE
    .\test-end-of-life-software.ps1 -ExtraNames "OldCrm*;LegacyScan" -IncludeOs false

    Also flags the two named programs, and ignores the Windows version.

