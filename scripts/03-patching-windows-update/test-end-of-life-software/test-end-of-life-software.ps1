# ---- Functions ------------------------------------------------------------
function Get-RegistryValue {
    # Strict mode throws on a missing property, so read through the property bag.
    param($Item, [string] $PropertyName)
    $property = $Item.PSObject.Properties[$PropertyName]
    if ($property) { return $property.Value }
    return $null
}

function Get-InstalledApplication {
    $applications = @()
    $seen = @{}
    foreach ($keyPattern in $UninstallKeys) {
        foreach ($item in @(Get-ItemProperty -Path $keyPattern -ErrorAction SilentlyContinue)) {
            $displayName = Get-RegistryValue -Item $item -PropertyName 'DisplayName'
            if (-not $displayName) { continue }
            if ((Get-RegistryValue -Item $item -PropertyName 'SystemComponent') -eq 1) { continue }
            if (@('Update', 'Hotfix', 'Security Update') -contains [string](Get-RegistryValue -Item $item -PropertyName 'ReleaseType')) { continue }
            $displayVersion = [string](Get-RegistryValue -Item $item -PropertyName 'DisplayVersion')
            $identity = "$displayName|$displayVersion"
            if ($seen.ContainsKey($identity)) { continue }
            $seen[$identity] = $true
            $applications += [pscustomobject]@{ Name = [string]$displayName; Version = $displayVersion }
        }
    }
    return $applications
}

function Get-WindowsSupportFinding {
    # A finding object when Windows itself is out of support, else $null.
    $os = Get-CimInstance -ClassName Win32_OperatingSystem
    $osVersion = $null
    if (-not [version]::TryParse([string]$os.Version, [ref]$osVersion)) { return $null }
    $isWorkstation = ([int]$os.ProductType -eq 1)
    $current = Get-ItemProperty -Path $CurrentVersionKey -ErrorAction SilentlyContinue
    $edition = ''
    $productName = [string]$os.Caption
    if ($current) {
        $edition = [string](Get-RegistryValue -Item $current -PropertyName 'EditionID')
        $registryName = [string](Get-RegistryValue -Item $current -PropertyName 'ProductName')
        if ($registryName -ne '' -and $osVersion.Major -lt 10) { $productName = $registryName }
    }
    $productName = ($productName -replace '^Microsoft\s+', '').Trim()
    if ($osVersion.Major -lt 10) {
        $ended = '2020-01-14'
        if ($osVersion.Major -eq 6 -and $osVersion.Minor -ge 2) { $ended = $(if ($isWorkstation) { '2023-01-10' } else { '2023-10-10' }) }
        return [pscustomobject]@{ Product = $productName; Found = "$productName (version $osVersion)"; Ended = $ended; Action = 'Upgrade or replace the operating system' }
    }
    if ($isWorkstation -and $osVersion.Build -lt 22000 -and $edition -notlike '*EnterpriseS*' -and $edition -notlike '*IoT*') {
        return [pscustomobject]@{ Product = 'Windows 10'; Found = "$productName (build $($osVersion.Build))"; Ended = '2025-10-14'; Action = 'Upgrade to Windows 11, or enrol in Extended Security Updates and set IncludeOs to false' }
    }
    if ($isWorkstation -and $osVersion.Build -ge 22000) {
        $isHomeOrPro = (($edition -like 'Core*') -or (($edition -like 'Professional*') -and ($edition -notlike '*Workstation*') -and ($edition -notlike '*Education*')))
        $group = $(if ($isHomeOrPro) { 'Home' } else { 'Business' })
        $isLongTermEdition = ($edition -like '*EnterpriseS*' -or $edition -like '*IoT*')
        foreach ($release in $Windows11Releases) {
            if ($release.Build -ne $osVersion.Build -or $isLongTermEdition) { continue }
            $ended = $release[$group]
            $endedDate = [DateTime]::ParseExact($ended, 'yyyy-MM-dd', [Globalization.CultureInfo]::InvariantCulture)
            if ($endedDate -gt [DateTime]::UtcNow) { return $null }
            return [pscustomobject]@{ Product = "Windows 11 $($release.Name)"; Found = "$productName $($release.Name) (build $($osVersion.Build))"; Ended = $ended; Action = 'Update to the current Windows 11 release (feature update)' }
        }
    }
    return $null
}

function Get-InternetExplorerFinding {
    # Internet Explorer 11 as a Windows feature that is still switched on (PCs only:
    # on Windows Server it is supported as long as the server is).
    if ([int](Get-CimInstance -ClassName Win32_OperatingSystem).ProductType -ne 1) { return '' }
    # Windows 10 LTSC and IoT keep IE11 supported with the OS, so it is not a finding there.
    $current = Get-ItemProperty -Path $CurrentVersionKey -ErrorAction SilentlyContinue
    if ($current) {
        $editionId = [string](Get-RegistryValue -Item $current -PropertyName 'EditionID')
        if ($editionId -like '*EnterpriseS*' -or $editionId -like '*IoT*') { return '' }
    }
    try {
        $features = @(Get-WindowsOptionalFeature -Online -ErrorAction Stop | Where-Object { $_.FeatureName -like 'Internet-Explorer-Optional*' -and [string]$_.State -eq 'Enabled' })
        if ($features.Count -gt 0) { return [string]$features[0].FeatureName }
    }
    catch { Write-OutpostWarning -Text "Could not check the Internet Explorer feature: $($_.Exception.Message)" }
    return ''
}

# ---- Main -----------------------------------------------------------------
Start-OutpostRun
try {
    # Validate: every input read once, typed, into $Config.
    $Config = [pscustomobject]@{
        ExtraNames = @(Read-OutpostList -Name 'ExtraNames')
        IncludeOs  = Read-OutpostBool -Name 'IncludeOs'
    }
    foreach ($extraName in $Config.ExtraNames) {
        if (($extraName -replace '[\*\?\[\]\s]', '').Length -lt $MinNameLetters) {
            Stop-OutpostInput -Name 'ExtraNames' -Value $extraName -Expected "names with at least $MinNameLetters letters besides wildcards, so one run cannot match everything"
        }
    }

    # Detect
    Write-OutpostLine -Text "Checking installed programs against $($KnownProducts.Count) known end-of-life products and $($Config.ExtraNames.Count) of your own names."
    $applications = @(Get-InstalledApplication)
    $findings = 0
    $summary = @()
    foreach ($known in $KnownProducts) {
        $excludePattern = $known.Exclude
        if ($excludePattern -eq 'OFFICECOMPONENTS') { $excludePattern = $OfficeComponentWords }
        foreach ($application in $applications) {
            if ($application.Name -notmatch $known.NamePattern) { continue }
            if ($excludePattern -ne '' -and $application.Name -match $excludePattern) { continue }
            $found = ("$($application.Name) $($application.Version)").Trim()
            Add-OutpostRow -Values @{ Product = $known.Product; Found = $found; SupportEnded = $known.Ended; WhatToDo = $known.Action }
            $findings++
            $summary += "$found (ended $($known.Ended))"
        }
    }
    foreach ($extraName in $Config.ExtraNames) {
        $extraPattern = $extraName
        if ($extraName -notmatch '[\*\?]') { $extraPattern = '*' + [WildcardPattern]::Escape($extraName) + '*' }
        foreach ($application in $applications) {
            if ($application.Name -notlike $extraPattern) { continue }
            $found = ("$($application.Name) $($application.Version)").Trim()
            Add-OutpostRow -Values @{ Product = "Your list: $extraName"; Found = $found; SupportEnded = 'Per your ExtraNames'; WhatToDo = 'Remove or replace it (uninstall-application)' }
            $findings++
            $summary += "$found (on your list)"
        }
    }
    $ieFeature = Get-InternetExplorerFinding
    if ($ieFeature -ne '') {
        Add-OutpostRow -Values @{ Product = 'Internet Explorer 11'; Found = "Windows feature $ieFeature is enabled"; SupportEnded = '2022-06-15'; WhatToDo = 'Turn the feature off: Disable-WindowsOptionalFeature -Online -FeatureName ' + $ieFeature }
        $findings++
        $summary += 'Internet Explorer 11 (ended 2022-06-15)'
    }
    if ($Config.IncludeOs) {
        $windowsFinding = Get-WindowsSupportFinding
        if ($null -ne $windowsFinding) {
            Add-OutpostRow -Values @{ Product = $windowsFinding.Product; Found = $windowsFinding.Found; SupportEnded = $windowsFinding.Ended; WhatToDo = $windowsFinding.Action }
            $findings++
            $summary += "$($windowsFinding.Product) (ended $($windowsFinding.Ended))"
        }
    }

    # Finish
    if ($findings -gt 0) {
        Complete-OutpostRun -Status 'ALERT' -Answer "$findings end-of-life item(s): $($summary -join '; ')"
    }
    Complete-OutpostRun -Status 'OK' -Answer "No end-of-life software found among $($applications.Count) installed programs."
}
catch {
    Stop-OutpostRun -ErrorRecord $_
}
