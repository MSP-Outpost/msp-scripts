#Requires -Version 5.1
<#
.SYNOPSIS
    Maps network drives (X: to \\server\share) for the signed-in user, keeping
    them across sign-ins, and checks each one opens.

.DESCRIPTION
    THIS SCRIPT CHANGES THINGS. For the user signed in at the console (the
    script runs from SYSTEM and maps the drives in that user's own session,
    with that user's own rights), for every item in Mappings it:

      * leaves a drive letter alone when it is already mapped to the same
        path and opens (OK),
      * maps the letter to the share with net use; with Persistent true the
        mapping is saved in the user's profile and comes back at every sign-in,
      * refuses the whole run, before changing anything, when a letter is
        already mapped to a DIFFERENT path (unless Replace is true: then that
        mapping is removed and replaced) or is a local disk or other non-network drive such as C: or a virtual disk,
      * checks that the drive opens, and for persistent drives that the
        mapping is saved in the user's registry.

    It uses the signed-in user's own credentials only: no user name or
    password is taken or stored, so the user needs access to the share. It
    maps the drives of the user signed in at the console only, never other
    users, and never touches files on the share.

    NOT covered: mapping by group membership or per site (do that in Group
    Policy or Intune, or run this script with different Mappings per group in
    your RMM), and shares that need a different user name. Nobody signed in:
    SKIPPED. If a share cannot be reached (server off, VPN down, no rights),
    the run ends in an error naming the drive and the Windows message.

.PARAMETER Mappings
    The drives to map: items like Z:=\\server\share, separated by commas or
    semicolons. The share may include a sub-folder (Z:=\\server\share\folder).
    Required. Environment variable: Mappings

.PARAMETER Persistent
    true (default) to keep the mappings across sign-ins; false to map them for
    this sign-in only. Environment variable: Persistent

.PARAMETER Replace
    true to replace a drive letter that is mapped to a different path. Default
    false: such a letter ends the run in an error and nothing is changed.
    Environment variable: Replace

.PARAMETER DryRun
    true to list what would be changed and change nothing. Default false.
    -WhatIf does the same. Environment variable: DryRun

.PARAMETER OutputFormat
    Text (default), Json or Csv. Environment variable: OutputFormat

.PARAMETER ExportPath
    Also write the rows to this .csv or .json file. Environment variable: ExportPath

.PARAMETER ResultField
    Also write the answer to this RMM custom field. Environment variable: ResultField

.EXAMPLE
    .\set-mapped-drives.ps1 -Mappings "S:=\\fileserver\shared,H:=\\fileserver\home"

    Maps S: and H: for the signed-in user and keeps them across sign-ins.

.EXAMPLE
    .\set-mapped-drives.ps1 -Mappings "S:=\\newserver\shared" -Replace true

    Points S: at the new server even if S: is mapped to the old one.

.NOTES
