# ---- Constants ------------------------------------------------------------
$MappingPattern = '^([A-Za-z]):?\s*=\s*(\\\\[A-Za-z0-9._-]+(?:\\[A-Za-z0-9 ._()$#@+~-]+)+)\\?$'

# ---- Functions ------------------------------------------------------------
function Get-UserSid {
    param([string] $Account)
    try {
        return (New-Object -TypeName Security.Principal.NTAccount -ArgumentList $Account).Translate([Security.Principal.SecurityIdentifier]).Value
    }
    catch { return $null }
}

function ConvertTo-CodeText {
    # Text as a PowerShell expression that cannot break out of the code around it.
    param([string] $Text)
    $encoded = [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($Text))
    return "([Text.Encoding]::UTF8.GetString([Convert]::FromBase64String('$encoded')))"
}

function ConvertTo-CodeBool {
    param([bool] $Value)
    if ($Value) { return '$true' }
    return '$false'
}

function Invoke-UserCode {
    param([string] $Code, [int] $TimeoutSeconds)
    $result = Invoke-OutpostAsUser -Code $Code -TimeoutSeconds $TimeoutSeconds
    if ($null -eq $result) { throw 'Nobody is signed in any more, so the step could not run.' }
    if ($result.ExitCode -ne 0) { throw "The step run as the signed-in user failed (exit code $($result.ExitCode)): $($result.Output)" }
    return [string]$result.Output
}

function Get-DriveState {
    # Runs in the user's session, changes nothing: what each wanted letter is now.
    param([object[]] $Drives, [bool] $WantPersistent)
    $lineText = (@($Drives | ForEach-Object { $_.Letter + '|' + $_.Path }) -join [Environment]::NewLine)
    $template = @'
$specLines = __SPECS__
$wantPersistent = __PERSIST__
$connections = @{}
foreach ($connection in @(Get-CimInstance -ClassName Win32_NetworkConnection -ErrorAction SilentlyContinue)) {
    if ($connection.LocalName) { $connections[([string]$connection.LocalName).ToUpperInvariant()] = [string]$connection.RemoteName }
}
foreach ($line in @($specLines -split '\r?\n')) {
    if ($line.Trim() -eq '') { continue }
    $parts = $line.Trim() -split '\|', 2
    $letter = $parts[0]
    $wanted = $parts[1]
    $existing = ''
    if ($connections.ContainsKey($letter.ToUpperInvariant())) { $existing = $connections[$letter.ToUpperInvariant()] }
    $registryKey = 'HKCU:\Network\' + $letter.Substring(0, 1)
    $persisted = Test-Path -LiteralPath $registryKey
    if ($existing -eq '' -and $persisted) {
        try { $existing = [string](Get-ItemPropertyValue -LiteralPath $registryKey -Name 'RemotePath') } catch { $existing = '' }
    }
    $localDrives = @([IO.DriveInfo]::GetDrives() | Where-Object { $_.Name -ieq ($letter + '\') -and @('Fixed', 'Removable', 'CDRom', 'Ram') -contains [string]$_.DriveType })
    $anyDrives = @([IO.DriveInfo]::GetDrives() | Where-Object { $_.Name -ieq ($letter + '\') })
    $state = 'free'
    if ($localDrives.Count -gt 0) { $state = 'local' }
    elseif ($existing -eq '' -and $anyDrives.Count -gt 0) { $state = 'taken' }
    elseif ($existing -ne '') {
        if ($existing.TrimEnd('\') -ieq $wanted.TrimEnd('\')) {
            $reachable = [IO.Directory]::Exists($letter + '\')
            if ($reachable -and ((-not $wantPersistent) -or $persisted)) { $state = 'ok' } else { $state = 'stale' }
        }
        else { $state = 'other' }
    }
    Write-Output ('OP|drive|' + $letter + '|' + $state + '|' + $existing)
}
'@
    return $template.Replace('__SPECS__', (ConvertTo-CodeText -Text $lineText)).Replace('__PERSIST__', (ConvertTo-CodeBool -Value $WantPersistent))
}

function Get-MapCode {
    # Runs in the user's session: (remove the old mapping,) map one letter, check it opens.
    param([string] $Letter, [string] $Path, [bool] $WantPersistent, [bool] $RemoveFirst)
    $template = @'
$letter = __LETTER__
$wanted = __PATH__
$wantPersistent = __PERSIST__
$removeFirst = __REMOVE__
$ErrorActionPreference = 'Continue'
$netExe = Join-Path -Path ([Environment]::SystemDirectory) -ChildPath 'net.exe'
if ($removeFirst) {
    $null = & $netExe use $letter /delete /y 2>&1
    $registryKey = 'HKCU:\Network\' + $letter.Substring(0, 1)
    if (Test-Path -LiteralPath $registryKey) { Remove-Item -LiteralPath $registryKey -Recurse -Force }
}
$persistText = 'no'
if ($wantPersistent) { $persistText = 'yes' }
$netOutput = & $netExe use $letter $wanted ('/persistent:' + $persistText) 2>&1
$netCode = $LASTEXITCODE
$netText = (@($netOutput) | ForEach-Object { [string]$_ }) -join ' '
if ($netCode -ne 0) {
    Write-Output ('OP|drive|' + $letter + '|failed|net use exit code ' + $netCode + ': ' + $netText)
}
elseif ([IO.Directory]::Exists($letter + '\')) {
    Write-Output ('OP|drive|' + $letter + '|mapped|ok')
}
else {
    Write-Output ('OP|drive|' + $letter + '|failed|mapped, but ' + $letter + '\ cannot be opened (no rights, or the server went away)')
}
'@
    return $template.Replace('__LETTER__', (ConvertTo-CodeText -Text $Letter)).Replace('__PATH__', (ConvertTo-CodeText -Text $Path)).Replace('__PERSIST__', (ConvertTo-CodeBool -Value $WantPersistent)).Replace('__REMOVE__', (ConvertTo-CodeBool -Value $RemoveFirst))
}

function ConvertFrom-DriveOutput {
    # OP|drive|Z:|state|detail lines -> letter -> state and detail.
    param([string] $Text)
    $table = @{}
    foreach ($found in [regex]::Matches($Text, '(?m)^OP\|drive\|([A-Za-z]:)\|(\w+)\|(.*?)\s*$')) {
        $table[$found.Groups[1].Value.ToUpperInvariant()] = [pscustomobject]@{ State = $found.Groups[2].Value; Detail = $found.Groups[3].Value }
    }
    return $table
}

# ---- Main -----------------------------------------------------------------
Start-OutpostRun
try {
    # Validate: every input read once, typed, into $Config.
    $Config = [pscustomobject]@{
        Mappings   = @(Read-OutpostList -Name 'Mappings' -Required)
        Persistent = Read-OutpostBool -Name 'Persistent'
        Replace    = Read-OutpostBool -Name 'Replace'
    }
    $wantedDrives = New-Object -TypeName System.Collections.ArrayList
    foreach ($item in $Config.Mappings) {
        $parsed = [regex]::Match($item, $MappingPattern)
        if (-not $parsed.Success) {
            Stop-OutpostInput -Name 'Mappings' -Value $item -Expected 'items like Z:=\\server\share (a drive letter, =, then a UNC path), separated by commas or semicolons'
        }
        $driveLetter = $parsed.Groups[1].Value.ToUpperInvariant() + ':'
        if (@($wantedDrives | Where-Object { $_.Letter -eq $driveLetter }).Count -gt 0) {
            Stop-OutpostInput -Name 'Mappings' -Value $item -Expected "each drive letter once ($driveLetter appears twice)"
        }
        [void]$wantedDrives.Add([pscustomobject]@{ Letter = $driveLetter; Path = $parsed.Groups[2].Value })
    }
    if (-not (Test-OutpostAdmin)) {
        Stop-OutpostRun -Message 'This script needs administrator rights. Run it as SYSTEM from your RMM or from an elevated PowerShell.'
    }
    $account = Get-OutpostSignedInUser
    if (-not $account) {
        Complete-OutpostRun -Status 'SKIPPED' -Answer 'Skipped: nobody is signed in, and mapped drives belong to the signed-in user.'
    }

    # Detect
    $stateText = Invoke-UserCode -Code (Get-DriveState -Drives @($wantedDrives) -WantPersistent $Config.Persistent) -TimeoutSeconds 90
    $states = ConvertFrom-DriveOutput -Text $stateText
    $toMap = New-Object -TypeName System.Collections.ArrayList
    $refused = New-Object -TypeName System.Collections.ArrayList
    $alreadyMapped = New-Object -TypeName System.Collections.ArrayList
    foreach ($drive in $wantedDrives) {
        if (-not $states.ContainsKey($drive.Letter)) {
            throw "The check run as $account gave no result for $($drive.Letter). Output: $stateText"
        }
        $driveState = $states[$drive.Letter]
        switch ($driveState.State) {
            'ok' {
                [void]$alreadyMapped.Add($drive.Letter)
                Add-OutpostRow -Values @{ Item = $drive.Letter; Change = "Already mapped to $($drive.Path)"; Result = 'Already mapped' }
            }
            'free' { [void]$toMap.Add([pscustomobject]@{ Drive = $drive; Change = "Map $($drive.Letter) to $($drive.Path)"; RemoveFirst = $false }) }
            'stale' { [void]$toMap.Add([pscustomobject]@{ Drive = $drive; Change = "Reconnect $($drive.Letter) to $($drive.Path) (it did not open or was not saved)"; RemoveFirst = $true }) }
            'other' {
                if ($Config.Replace) {
                    [void]$toMap.Add([pscustomobject]@{ Drive = $drive; Change = "Replace $($drive.Letter) (now $($driveState.Detail)) with $($drive.Path)"; RemoveFirst = $true })
                }
                else { [void]$refused.Add("$($drive.Letter) is mapped to $($driveState.Detail)") }
            }
            'local' { [void]$refused.Add("$($drive.Letter) is a local disk") }
            'taken' { [void]$refused.Add("$($drive.Letter) is in use by something that is not a network mapping (a virtual disk, guest tools or a WebDAV share)") }
            default { throw "The check run as $account reported '$($driveState.State)' for $($drive.Letter), which this script does not know." }
        }
    }
    Write-OutpostLine -Text "Signed in: $account. $($toMap.Count) drive(s) to map, $($alreadyMapped.Count) already mapped, $($refused.Count) refused."
    if ($refused.Count -gt 0) {
        Stop-OutpostRun -Message "Nothing was changed: $($refused -join '; '). Use another letter, or set Replace to true to replace a mapped drive (a local disk or other non-network drive is never replaced)."
    }
    if ($toMap.Count -eq 0) {
        Complete-OutpostRun -Status 'OK' -Answer "Already mapped for ${account}: $($alreadyMapped -join ' ')"
    }

    # Act
    foreach ($entry in $toMap) {
        $null = Invoke-OutpostChange -Item $entry.Drive.Letter -Change $entry.Change -Action {
            $mapText = Invoke-UserCode -Code (Get-MapCode -Letter $entry.Drive.Letter -Path $entry.Drive.Path -WantPersistent $Config.Persistent -RemoveFirst $entry.RemoveFirst) -TimeoutSeconds 90
            $mapResult = ConvertFrom-DriveOutput -Text $mapText
            if (-not $mapResult.ContainsKey($entry.Drive.Letter)) { throw "The mapping step for $($entry.Drive.Letter) gave no result: $mapText" }
            if ($mapResult[$entry.Drive.Letter].State -ne 'mapped') {
                throw "Could not map $($entry.Drive.Letter) to $($entry.Drive.Path): $($mapResult[$entry.Drive.Letter].Detail)"
            }
        }
    }

    # Verify (skipped in a dry run: nothing was changed). The drive opened inside the mapping step;
    # a persistent mapping must also be saved in the user's registry so it comes back at sign-in.
    if (-not $script:OutpostRun.DryRun -and $Config.Persistent) {
        $sid = Get-UserSid -Account $account
        foreach ($entry in $toMap) {
            $savedPath = ''
            if ($sid) {
                try { $savedPath = [string](Get-ItemPropertyValue -LiteralPath "Registry::HKEY_USERS\$sid\Network\$($entry.Drive.Letter.Substring(0, 1))" -Name 'RemotePath') }
                catch { $savedPath = '' }
            }
            if ($savedPath.TrimEnd('\') -ine $entry.Drive.Path.TrimEnd('\')) {
                Stop-OutpostRun -Message "$($entry.Drive.Letter) is mapped but is not saved for the next sign-in (saved path: '$savedPath'). Check that the user's profile is writable, then run again."
            }
        }
    }

    # Finish
    $letters = @($toMap | ForEach-Object { $_.Drive.Letter }) -join ' '
    $persistText = 'this sign-in only'
    if ($Config.Persistent) { $persistText = 'persistent' }
    $alreadyText = ''
    if ($alreadyMapped.Count -gt 0) { $alreadyText = "; $($alreadyMapped.Count) already mapped" }
    Complete-OutpostRun -Status 'CHANGED' -Answer "Mapped $($toMap.Count) drive(s) for ${account}: $letters ($persistText)$alreadyText"
}
catch {
    Stop-OutpostRun -ErrorRecord $_
}
