# ---- Constants ------------------------------------------------------------
$TimeParametersKey = 'HKLM:\SYSTEM\CurrentControlSet\Services\W32Time\Parameters'
$TimeServiceName = 'W32Time'
$SampleCount = 3

# ---- Functions ------------------------------------------------------------
function Get-TimeSourceText {
    # Reads Type and NtpServer from the registry and says where the clock syncs from.
    $sourceType = ''
    $ntpServer = ''
    $item = Get-ItemProperty -LiteralPath $TimeParametersKey -ErrorAction SilentlyContinue
    if ($null -ne $item) {
        if ($null -ne $item.PSObject.Properties['Type']) { $sourceType = [string]$item.PSObject.Properties['Type'].Value }
        if ($null -ne $item.PSObject.Properties['NtpServer']) { $ntpServer = [string]$item.PSObject.Properties['NtpServer'].Value }
    }
    $isDomain = [bool](Get-CimInstance -ClassName Win32_ComputerSystem).PartOfDomain
    if ($sourceType -eq '') { return 'Type not set in the registry' }
    $meaning = switch ($sourceType.ToUpperInvariant()) {
        'NT5DS' { if ($isDomain) { 'domain hierarchy (domain controller)' } else { 'domain hierarchy, but this PC is not domain-joined' } }
        'NTP' { "NTP server $ntpServer" }
        'ALLSYNC' { "domain hierarchy and NTP server $ntpServer" }
        'NOSYNC' { 'none (NoSync)' }
        default { "unknown type; NtpServer $ntpServer" }
    }
    return "Type $sourceType; $meaning"
}

function Measure-ClockOffset {
    # Returns the middle offset in seconds (sign as w32tm prints it; only its size is used) or $null.
    # Reads only the numbers in "HH:MM:SS, +00.1234567s" data lines.
    param([Parameter(Mandatory = $true)][string] $Server)
    $systemFolder = [Environment]::GetFolderPath('System')
    if ([string]::IsNullOrEmpty($systemFolder)) { $systemFolder = 'C:\Windows\System32' }
    $w32tm = Join-Path -Path $systemFolder -ChildPath 'w32tm.exe'
    if (-not (Test-Path -LiteralPath $w32tm)) { Stop-OutpostRun -Message 'w32tm.exe was not found in the system folder. This Windows install is damaged.' }
    $previousPreference = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        $lines = @(& $w32tm /stripchart "/computer:$Server" "/samples:$SampleCount" /period:1 /dataonly 2>&1 | ForEach-Object { [string]$_ })
    }
    finally { $ErrorActionPreference = $previousPreference }
    $offsets = New-Object System.Collections.ArrayList
    foreach ($line in $lines) {
        $match = [regex]::Match($line, ',\s*([+-]\d+[.,]\d+)s\s*$')
        if ($match.Success) {
            $text = $match.Groups[1].Value.Replace(',', '.')
            [void]$offsets.Add([double]::Parse($text, [System.Globalization.CultureInfo]::InvariantCulture))
        }
    }
    if ($offsets.Count -eq 0) { return $null }
    $sorted = @($offsets | Sort-Object)
    return [double]$sorted[[int][math]::Floor(($sorted.Count - 1) / 2)]
}

function Format-Seconds {
    param([Parameter(Mandatory = $true)][double] $Value)
    return $Value.ToString('0.000', [System.Globalization.CultureInfo]::InvariantCulture)
}

# ---- Main -----------------------------------------------------------------
Start-OutpostRun
try {
    # Validate
    $Config = [pscustomobject]@{
        ReferenceServer  = Read-OutpostText -Name 'ReferenceServer' -Required
        MaxOffsetSeconds = Read-OutpostInt -Name 'MaxOffsetSeconds' -Min 1 -Max 86400
    }
    if ($Config.ReferenceServer -notmatch '^[A-Za-z0-9][A-Za-z0-9.:-]{0,252}$') {
        Stop-OutpostInput -Name 'ReferenceServer' -Value $Config.ReferenceServer -Expected 'a host name or IP address (letters, digits, dots, dashes, colons)'
    }
    if (-not (Test-OutpostAdmin)) {
        Stop-OutpostRun -Message 'This script needs administrator rights. Run it as SYSTEM from your RMM or from an elevated PowerShell.'
    }

    # Detect
    Write-OutpostLine -Text "Measuring the clock against $($Config.ReferenceServer) ($SampleCount samples)."
    $findings = @()

    $service = Get-Service -Name $TimeServiceName -ErrorAction SilentlyContinue
    if ($null -eq $service) {
        Stop-OutpostRun -Message 'The Windows Time service (W32Time) does not exist on this PC. This Windows install is damaged; repair it with DISM and SFC.'
    }
    $isRunning = $service.Status -eq [System.ServiceProcess.ServiceControllerStatus]::Running
    $serviceText = "$($service.Status), start type $($service.StartType)"
    Add-OutpostRow -Values @{ Check = 'Windows Time service'; Value = $serviceText; Pass = $isRunning }
    if (-not $isRunning) { $findings += "Windows Time service is $($service.Status)" }

    Add-OutpostRow -Values @{ Check = 'Configured time source'; Value = (Get-TimeSourceText); Pass = $true }

    $offset = Measure-ClockOffset -Server $Config.ReferenceServer
    if ($null -eq $offset) {
        Stop-OutpostRun -Message "Could not measure the clock: $($Config.ReferenceServer) did not answer. Check that UDP port 123 is open to it and that the name resolves, or set ReferenceServer to a reachable time server (on a domain, a domain controller)."
    }
    $absolute = [math]::Abs($offset)
    $isOffsetOk = $absolute -le $Config.MaxOffsetSeconds
    $offsetText = "$(Format-Seconds -Value $absolute) s from $($Config.ReferenceServer) (limit $($Config.MaxOffsetSeconds) s)"
    Add-OutpostRow -Values @{ Check = 'Clock offset'; Value = $offsetText; Pass = $isOffsetOk }
    if (-not $isOffsetOk) { $findings += "clock is $(Format-Seconds -Value $absolute) s from $($Config.ReferenceServer) (limit $($Config.MaxOffsetSeconds) s)" }

    # Finish
    $sourceShort = (Get-TimeSourceText) -replace '^Type ', ''
    if ($findings.Count -gt 0) {
        Complete-OutpostRun -Status 'ALERT' -Answer (($findings -join '; ') + "; source $sourceShort")
    }
    Complete-OutpostRun -Status 'OK' -Answer "Clock is $(Format-Seconds -Value $absolute) s from $($Config.ReferenceServer) (limit $($Config.MaxOffsetSeconds) s); W32Time running; source $sourceShort"
}
catch {
    Stop-OutpostRun -ErrorRecord $_
}
