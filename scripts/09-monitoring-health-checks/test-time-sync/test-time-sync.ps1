#Requires -Version 5.1
<#
.SYNOPSIS
    Alerts when the PC clock is more than MaxOffsetSeconds from a reference time server or the Windows Time service is stopped.

.DESCRIPTION
    THIS SCRIPT IS READ-ONLY. It checks three things, one row each:

      * The Windows Time service (W32Time): running or not. A stopped service
        is an alert.
      * The configured time source, read from the registry (HKLM\SYSTEM\
        CurrentControlSet\Services\W32Time\Parameters: Type and NtpServer).
        Type NT5DS on a domain-joined PC means it syncs from the domain
        hierarchy (the domain controller), and the row says so; Type NTP means
        the listed NtpServer; AllSync means both; NoSync means none.
      * The clock offset: it asks ReferenceServer three times with
        "w32tm /stripchart ... /dataonly" and reads the NUMBERS in its output
        (never the English text), using the middle sample by size. The alert is
        raised when the offset is larger than MaxOffsetSeconds, in either
        direction (the sign is not interpreted).

    If the reference server cannot be reached (blocked UDP port 123, no
    internet) the run ends ERROR and says so, because the clock could not be
    measured; on a domain-joined PC whose firewall blocks Internet time, set
    ReferenceServer to a domain controller. The offset is measured, not
    corrected: nothing is resynchronised.

.PARAMETER ReferenceServer
    Host name or IP address of the time server to measure against. Letters,
    digits, dots, dashes and colons only. Default time.windows.com.
    Environment variable: ReferenceServer

.PARAMETER MaxOffsetSeconds
    Largest clock offset allowed, in seconds. Whole number, 1 to 86400.
    Default 60. Environment variable: MaxOffsetSeconds

.PARAMETER DryRun
    Reserved; ignored by Monitors.

.PARAMETER OutputFormat
    Text (default), Answer, Json or Csv. Environment variable: OutputFormat

.PARAMETER ExportPath
    Also write the rows to this .csv or .json file. Environment variable: ExportPath

.PARAMETER ResultField
    Also write the answer to this RMM custom field. Environment variable: ResultField

.EXAMPLE
    .\test-time-sync.ps1

    Alerts when the clock is more than 60 seconds from time.windows.com.

.EXAMPLE
    .\test-time-sync.ps1 -ReferenceServer dc01.contoso.com -MaxOffsetSeconds 5

    Measures against a domain controller and allows 5 seconds.

.NOTES
